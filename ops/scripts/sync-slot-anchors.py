#!/usr/bin/env python3
"""sync-slot-anchors — generate `zenoh_active_slot_anchors` from the live slot
registry (ADR 1101, docs/design/zenoh-storage-taxonomy-sharding.md).

Under lazy per-slot storage the router declares a rocksdb store only for a LIVE
slot. Which slots are live is a fact the portal's registry holds and nothing
else does, so the list belongs in generated group_vars, exactly as the org
catalog does (`sync-org-catalog.py`, ADR 1112).

WHY A GENERATOR AND NOT A LIST. The interim list was a one-off census of slot
directories holding `.sst` data. A census cannot follow a mint or a revoke, so
it drifts in both directions at once, and F-428 measured what that costs on
one goatnet, 2026-09-03: 252 declared stores against 179 live slots — 94 correct, 85
live slots with NO store (writes permitted, nothing retained, queries answering
EMPTY), and 158 stores for slots that are not live, of which 141 were pool
indices the portal has no row for at all.

WHAT COUNTS AS LIVE. A slot with an `assigned_to` and no `revoked_at`. A
revoked slot's store is NOT dropped by this script's output alone — removing a
declaration leaves the directory on disk, so the data survives a re-add; but
treat a revoke as a deliberate act and check before regenerating past one.

Usage:
  ops/scripts/sync-slot-anchors.py --env zagros --db /path/to/registry.db
  ops/scripts/sync-slot-anchors.py --env zagros --db ... --check
  # a goatnet whose portal runs on Postgres (portal_store: postgres):
  ops/scripts/sync-slot-anchors.py --env zagros --registry-store postgres --pg-ssh <mgmt host>

--check exits 1 when the committed list differs from the live registry (drift
gate; writes nothing) and 2 when the registry could not be read at all. Those
are different answers and must never collapse into one: an unreadable source
reported as drift inverts the guard, which is the failure this repo already
caught once in sync-org-catalog.py.
"""

from __future__ import annotations

import argparse
from contextlib import closing
import sqlite3
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import portal_registry_pg  # noqa: E402

REPO = Path(__file__).resolve().parent.parent.parent
GROUP_VARS = REPO / "ops" / "ansible" / "group_vars"

HEADER = """\
---
# GENERATED by ops/scripts/sync-slot-anchors.py — DO NOT hand-edit the anchor
# list below. The portal's slot registry is authoritative (ADR 1101); re-run the
# sync to update, and re-run it whenever slots are minted or revoked.
#
# `zenoh_lazy_slot_storage` and `portal_lazy_slot_storage` are ONE decision
# written in two files. Setting only one inverts the design rather than halving
# it: with the router lazy and the portal not, neither side creates a slot's
# store and every new slot is silently unstored. Change both or neither.
"""


LIVE_SLOTS_SQL = ("SELECT slot_id FROM slots "
                  "WHERE assigned_to IS NOT NULL AND assigned_to != '' "
                  "  AND revoked_at IS NULL")


def live_anchors_pg(conn: dict[str, str]) -> list[str]:
    """live_anchors() against the Postgres registry."""
    try:
        rows = portal_registry_pg.query(LIVE_SLOTS_SQL, **conn)
    except portal_registry_pg.RegistryUnreadable as exc:
        print(f"UNREADABLE: {exc} — not a drift verdict", file=sys.stderr)
        raise SystemExit(2)
    return sorted(r["slot_id"] for r in rows)


def live_anchors(db_path: str) -> list[str]:
    """Anchors of every assigned, non-revoked slot, sorted."""
    try:
        with closing(sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)) as con:
            rows = con.execute(LIVE_SLOTS_SQL).fetchall()
    except sqlite3.Error as exc:
        print(f"UNREADABLE: {db_path}: {exc} — not a drift verdict", file=sys.stderr)
        raise SystemExit(2)
    return sorted(r[0] for r in rows)


def render(env: str, anchors: list[str], lazy_router: bool, lazy_portal: bool) -> str:
    body = yaml.safe_dump(
        {
            "zenoh_lazy_slot_storage": lazy_router,
            "portal_lazy_slot_storage": lazy_portal,
            "zenoh_active_slot_anchors": anchors,
        },
        sort_keys=False,
        default_flow_style=False,
    )
    return HEADER + f"# env: {env}   live slots: {len(anchors)}\n" + body


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--env", required=True, help="goatnet slug, e.g. zagros")
    ap.add_argument("--db", default="", help="path to the portal registry.db (read-only; sqlite store)")
    portal_registry_pg.add_arguments(ap, "--db")
    ap.add_argument("--check", action="store_true", help="exit 1 on drift; write nothing")
    a = ap.parse_args()

    target = GROUP_VARS / f"{a.env.replace('-', '_')}_hosts" / "zenoh-lazy-storage.yml"
    if a.registry_store == "postgres":
        anchors = live_anchors_pg(portal_registry_pg.kwargs(a))
    elif not a.db:
        return ap.error("--db is required with --registry-store sqlite")
    else:
        anchors = live_anchors(a.db)
    if not anchors:
        print("REFUSING: the registry reports zero live slots. That is either a wrong "
              "database or a real emptying, and both deserve a human.", file=sys.stderr)
        return 2

    existing = {}
    if target.exists():
        existing = yaml.safe_load(target.read_text()) or {}
    have = existing.get("zenoh_active_slot_anchors") or []

    added = sorted(set(anchors) - set(have))
    dropped = sorted(set(have) - set(anchors))

    print(f"{a.env}: live slots {len(anchors)} · committed {len(have)} · "
          f"+{len(added)} / -{len(dropped)}")

    if not added and not dropped:
        print("in sync")
        return 0

    if a.check:
        for x in added[:5]:
            print(f"  + {x}  (live slot with no declared store)")
        for x in dropped[:5]:
            print(f"  - {x}  (declared store for a slot that is not live)")
        if len(added) > 5 or len(dropped) > 5:
            print("  …")
        print("DRIFT: the committed anchor list does not match the live registry.",
              file=sys.stderr)
        return 1

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(
        a.env, anchors,
        bool(existing.get("zenoh_lazy_slot_storage", True)),
        bool(existing.get("portal_lazy_slot_storage", True)),
    ))
    print(f"wrote {target} ({len(anchors)} anchors)")
    print("NOTE: this changes the router config. A render + restart is required for "
          "it to take effect, and dropping a declaration leaves the directory on disk.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
