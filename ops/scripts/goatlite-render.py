def cloudflare_ref(f: dict, rep: "Report", check: bool) -> None:
    """lite.internet.cloudflare_token_ref, when declared: a reference line for
    CLOUDFLARE_API_TOKEN_<NAME> in a gitignored .refs file, for the reference store in
    force to resolve per command (ADR 1186, 1204). A reference cannot be resolved by a
    value store, so declaring one there is refused."""
    inet = f.get("internet") or {}
    ref = inet.get("cloudflare_token_ref")
    name = f"CLOUDFLARE_API_TOKEN_{f['upper']}"
    import importlib.util
    spec = importlib.util.spec_from_file_location("goat_posture", REPO / "ops/secrets/posture.py")
    posture = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(posture)
    try:
        store = posture.store(str(REPO))
    except posture.PostureError as e:
        raise Refuse(str(e))
    if not ref:
        rep.add(f"{name} ({store})", "the Cloudflare token: " + " ".join(posture.hint([name], str(REPO))))
        return
    scheme = next(p for p in REF_PREFIXES if ref.startswith(p))
    if store not in posture.REFERENCE_STORES:
        raise Refuse(f"lite.internet.cloudflare_token_ref is a {scheme} reference, but the secrets store in force is "
                     f"{store}, which holds values and resolves no reference: leave cloudflare_token_ref out and put "
                     f"{name} in the store, or declare `secrets: {{store: {REF_PREFIXES[scheme]}}}` in goatlite.yaml")
    text = (f"# generated by ops/scripts/goatlite-render.py from goatlite.yaml (lite.internet.cloudflare_token_ref)\n"
            f"# A reference, never a value (ADR 1186): resolved per command by the {store} store.\n"
            f"{name}={ref}\n")
    path = refs_path(f)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        rep.add(path, "unchanged")
        return
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        os.chmod(path, 0o600)
    rep.add(path, "would write" if check else "written")


SECRETISH = re.compile(r"(secret|token|password|_pass$|cookie|cipher|_key$|salt|nid$)")
ENV_LOOKUP = re.compile(r"^\{\{ *lookup\('env', *'([A-Z][A-Z0-9_]*)'\)( *\| *default\('', *true\))? *\}\}$")


def internet_problems(gv: dict, f: dict) -> list:
    """What in a rendered vars.yml is not internet-correct for this goatnet. The
    required-inputs scan proves only that a key exists; this checks its value."""
    inet, up, n = f["internet"], f["upper"], f["name"]
    apex, izone = f["apex"], inet["zone"]
    out = []

    def want(key, value):
        if gv.get(key) != value:
            out.append(f"{key} is {gv.get(key)!r}, want {value!r}")

    want("has_acme", True)
    want("has_internal_ca", True)
    want("dashboard_cert_delivery_mode", "acme")
    want("mgmt_dynamic_cert_mode", "acme")
    want("lan_coredns_enabled", False)
    for key in ("site_dns_zone", "public_mgmt_fqdn", "site_enrollment_dns"):
        want(key, apex)
    if str(gv.get("site_dns_zone", "")).endswith(PRIVATE_SUFFIXES):
        out.append(f"site_dns_zone {gv.get('site_dns_zone')!r} is a LAN-only name")
    for key in ("lan_dns_zone", "lan_dns_resolver_ip", "stun_host"):
        if key in gv:
            out.append(f"{key} is a LAN setting and is declared")
    want("mesh_coredns_port", 5353)
    want("acme_email", inet["acme_email"])
    m = ENV_LOOKUP.match(str(gv.get("cloudflare_api_token", "")))
    if not m or m.group(1) != f"CLOUDFLARE_API_TOKEN_{up}":
        # never echo the value: when this check fails, it may be a pasted token
        out.append(f"cloudflare_api_token must be the lookup of CLOUDFLARE_API_TOKEN_{up} (what phase 7 reads); "
                   "it holds something else (value not shown)")
    relays = relay_fqdns(f)
    want("stun_hosts", relays)
    want("relay_addresses", [f"rels://{r}:{RELAY_DATA_PORT}" for r in relays])
    for r in gv.get("relay_addresses") or []:
        if not str(r).startswith("rels://") or f".{izone}:" not in str(r):
            out.append(f"relay address {r!r} is not a TLS relay (rels://) under {izone}")
    want("aws_profile", inet["aws_profile"])
    want("portal_traefik_cert_resolver", "le")
    want("portal_traefik_mesh_only_middleware", "mesh-only-allowlist@file")
    want("zenoh_listen_host_override", "{{ mesh_ip_a }}")
    if inet["mesh_ip"]:
        want("mesh_ip_a", inet["mesh_ip"])
    for key, value in gv.items():
        if SECRETISH.search(key) and isinstance(value, str) and value and not value.startswith("{{") \
                and not key.endswith(("_envvar", "_name", "_path", "_dir", "_secret_name")) and "FAIL-LOUD" not in value:
            out.append(f"{key} holds a literal value; a secret is a lookup under the secrets posture")
    for key in ("relay_secret", "dashboard_oauth2_proxy_client_secret", "isitup_oidc_client_secret",
                "id_admin_console_oauth2_proxy_client_secret"):
        if not ENV_LOOKUP.match(str(gv.get(key, ""))):
            out.append(f"{key} must be an env lookup under the secrets posture")
    return out


