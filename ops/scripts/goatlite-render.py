def marker_lines(name: str, indent: str, comment: str, tag: str = "") -> tuple:
    t = f" {tag}" if tag else ""
    return f"{indent}{comment} BEGIN goatlite {name}{t}", f"{indent}{comment} END goatlite {name}{t}"


def find_markers(lines: list, name: str, comment: str, tag: str = ""):
    """(i, j) of the BEGIN/END marker lines for this name+tag, whatever their indent, or None."""
    begin, end = marker_lines(name, "", comment, tag)
    i = next((k for k, ln in enumerate(lines) if ln.strip() == begin), None)
    j = next((k for k, ln in enumerate(lines) if ln.strip() == end), None)
    return (i, j) if i is not None and j is not None and j > i else None


def _indent_of(line: str) -> str:
    return line[:len(line) - len(line.lstrip())]


def _next_content_indent(lines: list, pos: int, fallback: str) -> str:
    """yamllint's comments-indentation rule: a comment is indented like the next content
    line, or at end of file like the previous one."""
    for ln in lines[pos:]:
        if ln.strip() and not ln.lstrip().startswith("#"):
            return _indent_of(ln)
    for ln in reversed(lines[:pos]):
        if ln.strip() and not ln.lstrip().startswith("#"):
            return _indent_of(ln)
    return fallback


def framed(name: str, body: list, comment: str, tag: str, lines_after: list, fallback: str) -> list:
    """BEGIN indented like the block's first line, END like what follows the block."""
    first = _indent_of(next((b for b in body if b.strip()), fallback))
    begin, _ = marker_lines(name, first, comment, tag)
    end_indent = _next_content_indent(lines_after, 0, _indent_of(next((b for b in reversed(body) if b.strip()), fallback)))
    _, end = marker_lines(name, end_indent, comment, tag)
    return [begin] + body + [end]


def marker_block(path: Path, name: str, block: str, rep: "Report", check: bool, *, indent="  ",
                 comment="#", tag="", insert_before: str = None, insert_after: str = None) -> None:
    """Replace or insert the `BEGIN/END goatlite <name>` block in a hand-owned file.
    insert_before: a regex for the line the block goes before (first match);
    insert_after: a regex for the line it goes after; neither: append at EOF."""
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")
    body = block.split("\n")
    label = f"{path.relative_to(REPO)} [{tag or 'goatlite ' + name}]"
    found = find_markers(lines, name, comment, tag)
    if found:
        i, j = found
        rendered = framed(name, body, comment, tag, lines[j + 1:], indent)
        if lines[i:j + 1] == rendered:
            rep.add(label, "unchanged")
            return
        new_lines = lines[:i] + rendered + lines[j + 1:]
    else:
        pos = None
        if insert_before:
            for k, ln in enumerate(lines):
                if re.match(insert_before, ln):
                    pos = k
                    break
        elif insert_after:
            for k, ln in enumerate(lines):
                if re.match(insert_after, ln):
                    pos = k + 1
                    break
        if pos is None:
            if text and not text.endswith("\n"):
                lines.append("")
            while lines and lines[-1] == "":
                lines.pop()
            new_lines = lines + [""] + framed(name, body, comment, tag, [], indent) + [""]
        else:
            new_lines = lines[:pos] + framed(name, body, comment, tag, lines[pos:], indent) + lines[pos:]
    if not check:
        path.write_text("\n".join(new_lines), encoding="utf-8")
    rep.add(label, "would write" if check else "written")


def marker_remove(path: Path, name: str, rep: "Report", check: bool, *, indent="  ", comment="#", tag="") -> None:
    if not path.exists():
        return
    lines = path.read_text(encoding="utf-8").split("\n")
    found = find_markers(lines, name, comment, tag)
    if not found:
        return
    i, j = found
    new = lines[:i] + lines[j + 1:]
    # collapse a blank left behind at the seam
    if i > 0 and i < len(new) and new[i - 1] == "" and new[i] == "":
        del new[i]
    if not check:
        path.write_text("\n".join(new), encoding="utf-8")
    rep.add(f"{path.relative_to(REPO)} [{tag or 'goatlite ' + name}]", "would remove" if check else "removed")


def ini_section_remove(path: Path, section: str, rep: "Report", check: bool) -> None:
    """Drop `[section]` and its lines up to the next blank line or section (a block the
    door generator appended, which carries no markers)."""
    if not path.exists():
        return
    lines = path.read_text(encoding="utf-8").split("\n")
    out, i, removed = [], 0, False
    while i < len(lines):
        if lines[i].strip() == f"[{section}]":
            removed = True
            i += 1
            while i < len(lines) and lines[i].strip() and not lines[i].startswith("["):
                i += 1
            continue
        out.append(lines[i])
        i += 1
    if not removed:
        return
    text = "\n".join(out)
    text = re.sub(r"\n{3,}", "\n\n", text).rstrip("\n") + "\n"
    if not check:
        path.write_text(text, encoding="utf-8")
    rep.add(f"{path.relative_to(REPO)} [{section}]", "would remove" if check else "removed")


