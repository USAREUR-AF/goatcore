def render(f: dict, check: bool) -> Report:
    rep = Report()
    gv = REPO / "ops/ansible/group_vars" / f["group"]
    # The manifest first: mint-site-certs.sh reads the CA paths from it.
    whole_file(REPO / "ops/enrollment/manifests" / f"{f['name']}-certs.yaml", manifest_yaml(f), rep, check)
    ensure_ca(f, rep, check)
    admin_ssh_pubkey(f, rep, check)
    whole_file(gv / "vars.yml", vars_yml(f), rep, check)
    lan_zone = REPO / "ops/dns" / f["name"] / f"{f['zone']}.hosts"
    if f.get("internet"):
        # Grown out: the LAN zone a first LAN render wrote is no longer served by any phase.
        generated_remove(lan_zone, rep, check, "removed (a LAN zone; the internet names live in mesh CoreDNS)")
        mesh = REPO / "ops/dns" / f["name"] / "mesh-hosts"
        if f["internet"]["mesh_ip"]:
            whole_file(mesh, mesh_hosts(f), rep, check)
        else:
            rep.add(mesh, "not yet: set lite.internet.mesh_ip after phase 8 enrols the box, then re-render")
        whole_file(REPO / f"terraform-{f['name']}" / "main.tf", terraform_tf(f), rep, check)
        posture_file = REPO / "ops/ansible/inventory/relay-tls-posture.sh"
        if not posture_file.exists():
            raise Refuse(f"{posture_file.relative_to(REPO)} does not exist; generate-relays.sh reads each "
                         f"goatnet's relay TLS posture from it")
        marker_block(posture_file, f["name"], posture_block(f), rep, check, indent="    ",
                     insert_before=r"^\s*\*\) return 1 ;;\s*$")
        cloudflare_ref(f, rep, check)
    else:
        whole_file(lan_zone, zone_hosts(f), rep, check)
    whole_file(gv / "spire.yml", spire_yml(f), rep, check)
    whole_file(gv / "grant-keyd.yml", grant_keyd_yml(f), rep, check)
    whole_file(gv / "minio.yml", minio_yml(f), rep, check)
    whole_file(gv / "audit-subscriber.yml", audit_subscriber_yml(f), rep, check)

    inv = REPO / "ops/ansible/inventory/mgmt-hosts.ini"
    marker_block(inv, f["name"], f["group"], rep, check, indent="", tag="(mgmt_hosts child)",
                 insert_after=r"^\[mgmt_hosts:children\]\s*$")
    marker_block(inv, f["name"], inventory_block(f), rep, check, indent="")
    marker_block(REPO / "ops/ansible/group_vars/.groupvars-parity.yaml", f["name"], parity_block(f), rep, check,
                 insert_after=r"^exclusions:\s*$")
    if not check:
        lite_table_open(LITE_PINS)
    marker_block(LITE_PINS, f["name"], pins_block(f), rep, check, insert_before=r"^components:")
    pins_deviation_blocks(f, rep, check)
    marker_block(REPO / "ops/ansible/inventory/doors.yaml", f["name"], doors_block(f), rep, check)
    marker_block(REPO / "ops/goatnets/cross-env.yaml", f["name"], cross_env_block(f), rep, check)
    marker_block(REPO / "ops/validation/goatnet-runners.yaml", f["name"], runners_block(f), rep, check)
    render_acl(f, rep, check)

    if check:
        pins = gv / "pins.yml"
        rep.add(pins, "present" if pins.exists() else "would write (ops/pins/generate-pins.py)")
        if not pins.exists():
            rep.changed = True
        run_doors(f, rep, check=True)
    else:
        run_pins(f, rep)
        sign_intent(f, rep)
        run_doors(f, rep, check=False)
    if f.get("internet"):
        # The value check of the surface just written (or, under --check, the one there).
        text = (gv / "vars.yml").read_text(encoding="utf-8") if (gv / "vars.yml").exists() else vars_yml(f)
        problems = internet_problems(yaml.safe_load(text) or {}, f)
        if problems:
            raise Refuse("the rendered vars.yml is not internet-correct:\n  " + "\n  ".join(problems))
        rep.add(gv / "vars.yml", "internet values checked: ACME, public apex, relays, mesh-only routes, secrets as lookups")
    return rep


def generated_remove(path: Path, rep: "Report", check: bool, status: str) -> None:
    """Delete a whole file the renderer generated (its header is intact); keep one the
    learner has taken over."""
    if not path.exists():
        return
    if not path.read_text(encoding="utf-8").startswith(HEADER + "\n"):
        rep.add(path, "edited by hand — kept (remove it yourself if it is to go)")
        return
    if not check:
        path.unlink()
    rep.add(path, "would remove" if check else status)


def remove(f: dict, check: bool) -> Report:
    rep = Report()
    gv = REPO / "ops/ansible/group_vars" / f["group"]
    for p in [gv / n for n in ("vars.yml", "spire.yml", "grant-keyd.yml", "minio.yml", "audit-subscriber.yml")] + \
             [REPO / "ops/enrollment/manifests" / f"{f['name']}-certs.yaml",
              REPO / "ops/dns" / f["name"] / f"{f['zone']}.hosts",
              REPO / "ops/dns" / f["name"] / "mesh-hosts",
              REPO / f"terraform-{f['name']}" / "main.tf"]:
        if p.exists():
            if p.read_text(encoding="utf-8").startswith(HEADER + "\n"):
                if not check:
                    p.unlink()
                rep.add(p, "would remove" if check else "removed")
            else:
                rep.add(p, "edited by hand — kept (remove it yourself if it is to go)")
    pins = gv / "pins.yml"
    if pins.exists():
        if not check:
            pins.unlink()
        rep.add(pins, "would remove" if check else "removed")
    if gv.exists() and not check and not any(gv.iterdir()):
        gv.rmdir()
    for d in (REPO / f"terraform-{f['name']}", REPO / "ops/dns" / f["name"]):
        if d.is_dir() and not check and not any(d.iterdir()):
            d.rmdir()
    refs = refs_path(f)
    if refs.exists() and refs.read_text(encoding="utf-8").startswith("# generated by ops/scripts/goatlite-render.py"):
        if not check:
            refs.unlink()
        rep.add(refs, "would remove" if check else "removed")
    marker_remove(REPO / "ops/ansible/inventory/relay-tls-posture.sh", f["name"], rep, check, indent="    ")
    intent = REPO / "ops/consistency/intent" / f["name_us"]
    if intent.exists():
        if not check:
            shutil.rmtree(intent)
        rep.add(intent, "would remove" if check else "removed")
    inv = REPO / "ops/ansible/inventory/mgmt-hosts.ini"
    marker_remove(inv, f["name"], rep, check, indent="", tag="(mgmt_hosts child)")
    marker_remove(inv, f["name"], rep, check, indent="")
    pins_deviation_remove(f, rep, check)
    for rel in ("ops/ansible/group_vars/.groupvars-parity.yaml", "ops/pins/lite-pins.yaml",
                "ops/ansible/inventory/doors.yaml", "ops/goatnets/cross-env.yaml",
                "ops/validation/goatnet-runners.yaml"):
        marker_remove(REPO / rel, f["name"], rep, check)
    remove_acl(f, rep, check)
    lite_table_close(LITE_PINS, rep, check)
    ini_section_remove(REPO / "ops/ansible/inventory/doors.ini", f"{f['name_us']}_door_hosts", rep, check)
    ini_section_remove(REPO / "ops/ansible/inventory/doors-groupvars.ini", f["group"], rep, check)
    # The goatnet's CA goes with it: root cert dir, public key, and the operator's
    # state dir (CA key + leaves). A retired goatnet's key must not linger.
    for p in (f["root_cert"].parent, f["pubkey_dir"] / f"{f['ca_id']}.pem", f["root_key"].parent,
              STATE_DIR / f"{f['name']}-leaves"):
        if p.exists():
            if not check:
                shutil.rmtree(p) if p.is_dir() else p.unlink()
            rep.add(p, "would remove" if check else "removed (CA material)")
    return rep


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--site", required=True, help="the goatnet name; must equal lite.name")
    ap.add_argument("--config", default=str(REPO / "goatlite.yaml"), help="default <repo>/goatlite.yaml")
    ap.add_argument("--check", action="store_true", help="exit 1 if anything would change; write nothing")
    ap.add_argument("--remove", action="store_true", help="undo the render (a retired goatlite, or a rehearsal)")
    ap.add_argument("--verify", action="store_true",
                    help="check the rendered vars.yml carries internet-correct values (lite.internet); write nothing")
    a = ap.parse_args()
    try:
        f = facts(load_config(Path(a.config), a.site))
        if a.verify:
            if not f.get("internet"):
                raise Refuse("--verify checks the internet values; goatlite.yaml declares no lite.internet")
            problems = verify_internet(f)
            for p in problems:
                print(f"  FAIL  {p}")
            print(f"goatlite-render: {f['name']} internet values: "
                  + (f"{len(problems)} problem(s)" if problems else "ok (ACME, public apex, relays, mesh-only routes, secrets as lookups)"))
            return 1 if problems else 0
        rep = remove(f, a.check) if a.remove else render(f, a.check)
    except Refuse as e:
        print(f"goatlite-render: {e}", file=sys.stderr)
        return 1
    verb = "would remove" if (a.remove and a.check) else "removed" if a.remove else \
        "would render" if a.check else "rendered"
    where = f"internet zone {f['internet']['zone']}" if f.get("internet") else f"zone {f['zone']}"
    print(f"goatlite-render: {f['name']} ({f['group']}, {where}, host {f['host']}) — {verb}:")
    rep.print()
    if a.check and rep.changed:
        print("goatlite-render: --check: the checkout is not what goatlite.yaml renders; run without --check")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
