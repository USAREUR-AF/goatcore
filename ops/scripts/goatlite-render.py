def project_state_dir() -> Path:
    """Where this machine keeps the project's local state (the goatnet's CA key
    and leaves): deploy.state_dir in ops/goatbuilder/goatbuilder.yaml, else
    ~/.goat/state, the rule the builder and mint-site-certs.sh follow."""
    try:
        cfg = yaml.safe_load((REPO / "ops/goatbuilder/goatbuilder.yaml").read_text(encoding="utf-8")) or {}
        declared = str((cfg.get("deploy") or {}).get("state_dir") or "").strip()
    except (OSError, yaml.YAMLError, AttributeError):
        declared = ""  # no declaration in this checkout: the neutral directory
    return Path(os.path.expanduser(declared or "~/.goat/state"))


