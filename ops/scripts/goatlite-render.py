def lite_table_open(path: Path) -> None:
    """An empty sidecar spells its maps `goatnets: {}` / `components: {}`; a block
    can only nest under a bare key. Open them before the first block goes in."""
    text = path.read_text(encoding="utf-8")
    new = re.sub(r"^(goatnets|components): \{\}\s*$", r"\1:", text, flags=re.M)
