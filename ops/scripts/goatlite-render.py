#!/usr/bin/env python3
"""goatlite-render.py — the goatlite derivation step (ADR 1213 D3, docs/design/goatlite.md §4).

The learner writes four facts in <repo>/goatlite.yaml; the standup engines read a
file set. This renders that file set into the checkout, idempotently, and the
ordinary engines (standup-config-preflight.py, goat-standup.sh in the lan
profile, the acceptance assay) run over it unchanged:

  ops/ansible/inventory/mgmt-hosts.ini            [<name>_hosts] + the mgmt_hosts child  (marker block)
  ops/ansible/group_vars/<name>_hosts/vars.yml    the lite value set                     (whole file)
  ops/ansible/group_vars/<name>_hosts/spire.yml, grant-keyd.yml, minio.yml, audit-subscriber.yml
  ops/ansible/group_vars/.groupvars-parity.yaml   exclusions.<name>_hosts __group_class__ (marker block)
  ops/dns/<name>/<zone>.hosts                     the LAN DNS zone, every name at the host (whole file)
  ops/enrollment/manifests/<name>-certs.yaml      from TEMPLATE-certs.yaml               (whole file)
  ops/pins/lite-pins.yaml                         the goatnets row + per-component deviations (marker blocks)
    the lite SIDECAR of fleet-pins.yaml: generate-pins.py and `goatbuilder pins` merge the two, so
    fleet-pins.yaml — whose hash every committed intent carries — never changes under a learner
    -> ops/pins/generate-pins.py renders group_vars/<name>_hosts/pins.yml + intent/<name>/intent.json
    -> ops/enrollment/cmd/intent-sign signs that intent with the goatnet's CA key (intent.json.sig)
  the goatnet's CA, minted FIRST when absent (ADR 1213 D4): ~/.config/age/keys.txt (age-keygen,
    0600) as the single recipient, ca-init --mode dev -> <state dir>/<name>-ca/ca.key.age,
    ops/enrollment/ca/<name>/root-cert.pem, ops/enrollment/public-keys/<ca_id>.pem. An existing CA
    is kept and its ca_id read back from the public key, so a re-render on a later day changes nothing.
  ops/ansible/inventory/doors.yaml                a `direct` door                         (marker block)
    -> ops/scripts/generate-door-inventory.py <name> adds the two door inventory groups
  ops/goatnets/cross-env.yaml                     the goatnet, relay_health absent        (marker block)
  ops/validation/goatnet-runners.yaml             the acceptance runner entry             (marker block)

Growing out of lite (docs/design/goatlite.md §6): a `lite.internet:` block renders the
internet-enrollable surface instead of the LAN one — the same files, with the public
zone, ACME, relays and the relay tunnel in vars.yml, plus:
  terraform-<name>/main.tf                        the relays, their DNS and the SSM bucket   (whole file)
  ops/ansible/inventory/relay-tls-posture.sh      the goatnet's relay TLS posture, le-dns01 (marker block)
  ops/dns/<name>/mesh-hosts                       the mesh CoreDNS zone, once lite.internet.mesh_ip is set
  .envrc.local.d/goatlite-<name>.refs             the Cloudflare token reference, under a reference store
and no LAN DNS zone. The rendered internet values are checked before the run ends
(internet_problems); `--verify` runs that check alone.

Every whole file carries this first line:
  # generated by ops/scripts/goatlite-render.py from goatlite.yaml — edit goatlite.yaml, or remove this line to own the file
A file whose first line is gone is the learner's (make-it-yours): it is REPORTED
and never overwritten. A marker block (`# BEGIN goatlite <name>` .. `# END goatlite
<name>`) is the renderer's; hand content outside the markers is never touched.

usage: goatlite-render.py --site <name> [--config <path>] [--check] [--remove] [--verify]
  --check   exit 1 if anything would change; write nothing
  --verify  check the rendered vars.yml carries internet-correct values; write nothing
  --remove  undo the render (a retired goatlite, or a rehearsal): delete the
            generated whole files and marker blocks, the rendered pins.yml and
            intent, the two door inventory groups, and the goatnet's CA (root
            cert dir, public key, <state dir>/<name>-ca and -leaves).
exit 0 rendered (or nothing to do) · 1 --check found drift, or an input is wrong · 2 usage
"""
