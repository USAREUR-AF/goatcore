docker_engine_containerd_root: "/var/lib/containerd"
require_docker_data_separate_mount: false
luks_passphrase_envvar: "{{{{ site_id_upper }}}}_{{{{ router_role | upper }}}}_LUKS_PASS"
luks_volumes_mgmt_host: []
luks_fido2_user_presence: false
