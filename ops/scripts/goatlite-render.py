def zone_address(f: dict) -> str:
    """The IPv4 address the zone points at. The zone file cannot hold a hostname."""
    if f["host_is_ip"]:
        return f["host"]
    try:
        return socket.gethostbyname(f["host"])
    except OSError as e:
        raise Refuse(f"lite.host {f['host']!r} does not resolve from this machine, and the LAN "
                     f"DNS zone needs its address: set lite.host to the box's IP address ({e})")


def zone_hosts(f: dict) -> str:
    n, zone = f["name"], f["zone"]
    ip = zone_address(f)
    node = f"mgmt-{n}-01"
    lines = [HEADER,
             f"# LAN zone for {zone}, consumed by the lan-coredns role through CoreDNS's hosts plugin.",
             "# Every name resolves to the one host.",
             "",
             f"{ip}    {node} {node}.{zone}",
             f"{ip}    netbird.{zone}"]
    lines += [f"{ip}    {svc}.{n}.{zone}" for svc in ZONE_SERVICES]
    return "\n".join(lines) + "\n"


def mesh_hosts(f: dict) -> str:
    """The mesh CoreDNS zone of a goatlite grown to the internet (goat-coredns.yml reads
    ops/dns/<site>/mesh-hosts): the apex and every service name at the box's mesh
    address, so enrolled peers reach the box over the mesh. Needs lite.internet.mesh_ip."""
    n, sz, ip = f["name"], f["site_zone"], f["internet"]["mesh_ip"]
    lines = [HEADER,
             f"# Mesh zone for {sz}, served by goat-coredns.yml on the box's mesh address.",
             "# Every name resolves to the one host's mesh IP (lite.internet.mesh_ip).",
             "",
             f"{ip}  {f['apex']}"]
    lines += [f"{ip}  {svc}.{n}.{sz}" for svc in ZONE_SERVICES]
    return "\n".join(lines) + "\n"


