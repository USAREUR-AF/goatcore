def run_pins(f: dict, rep: "Report") -> None:
    """generate-pins.py renders every listed member; keep only this goatnet's output."""
    watch = list((REPO / "ops/ansible/group_vars").glob("*/pins.yml")) + \
        list((REPO / "ops/consistency/intent").glob("*/intent.json"))
    mine = {REPO / "ops/ansible/group_vars" / f["group"] / "pins.yml",
            REPO / "ops/consistency/intent" / f["name_us"] / "intent.json"}
    before = {p: p.read_text(encoding="utf-8") for p in watch if p not in mine}
    r = subprocess.run([sys.executable, str(REPO / "ops/pins/generate-pins.py")], capture_output=True, text=True)
    for p, old in before.items():
        if p.exists() and p.read_text(encoding="utf-8") != old:
            p.write_text(old, encoding="utf-8")  # another goatnet's drift is not this render's business
    if r.returncode != 0:
        raise Refuse(f"ops/pins/generate-pins.py failed:\n{(r.stdout + r.stderr).strip()[-1500:]}")
    for p in mine:
        rep.add(p, "rendered by ops/pins/generate-pins.py" if p.exists() else "NOT rendered (generate-pins.py wrote nothing here)")


def run_doors(f: dict, rep: "Report", check: bool) -> None:
    cmd = [sys.executable, str(REPO / "ops/scripts/generate-door-inventory.py"), f["name"]] + (["--check"] if check else [])
    r = subprocess.run(cmd, capture_output=True, text=True)
    out = (r.stdout + r.stderr).strip().splitlines()
    if check:
        rep.add("door inventories (generate-door-inventory.py --check)", "present" if r.returncode == 0 else "would write")
        if r.returncode != 0:
            rep.changed = True
    elif r.returncode != 0:
        raise Refuse("ops/scripts/generate-door-inventory.py failed:\n" + "\n".join(out[-10:]))
    else:
        rep.add("door inventories (doors.ini, doors-groupvars.ini)", out[-1] if out else "rendered")


