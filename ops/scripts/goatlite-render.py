def load_config(path: Path, site: str) -> dict:
    try:
        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except OSError:
        raise Refuse(f"{path} does not exist — goatlite is `preset: lite` in that file (docs/design/goatlite.md §2)")
    except yaml.YAMLError as e:
        raise Refuse(f"{path}: not valid YAML: {e}")
    if not isinstance(doc, dict) or doc.get("preset") != "lite":
        raise Refuse(f"{path}: `preset: lite` is not declared; nothing to render")
    lite = doc.get("lite")
    if not isinstance(lite, dict):
        raise Refuse(f"{path}: a `lite:` block with name, host, ssh_user and admin is required")
    name = str(lite.get("name", "")).strip()
    if not NAME_RE.match(name):
        raise Refuse(f"lite.name {name!r} must match {NAME_RE.pattern} (a lowercase goatnet name, 2-24 chars)")
    if name != site:
        raise Refuse(f"lite.name is {name!r} but --site is {site!r}; one goatlite.yaml names one goatnet")
    host = str(lite.get("host", "")).strip()
    if not host or not HOST_RE.match(host):
        raise Refuse("lite.host must be the LAN address or hostname of the one box")
    user = str(lite.get("ssh_user", "")).strip()
    if not USER_RE.match(user):
        raise Refuse(f"lite.ssh_user {user!r} must be a unix user name")
    admin = str(lite.get("admin", "")).strip()
    if "@" not in admin or admin.startswith("@") or admin.endswith("@") or " " in admin:
        raise Refuse("lite.admin must be the administrator's e-mail address (it is the first login)")
    zone = str(lite.get("zone") or f"{name}.lan").strip().lower().rstrip(".")
    if not re.match(r"^[a-z0-9-]+(\.[a-z0-9-]+)+$", zone):
        raise Refuse(f"lite.zone {zone!r} must be a DNS zone like {name}.lan")
    enc = lite.get("disk_encryption", True)
    if not isinstance(enc, bool):
        raise Refuse("lite.disk_encryption must be true or false")
    internet = load_internet(lite.get("internet"), name, admin, zone) if "internet" in lite else None
    disk =str(lite.get("data_disk") or "/dev/nvme0n1").strip()
    if not re.match(r"^/dev/[a-z0-9/_-]+$", disk):
        raise Refuse(f"lite.data_disk {disk!r} must be a block device path such as /dev/nvme0n1")
    pubkey = lite.get("ssh_pubkey")
    candidates = [Path(os.path.expanduser(str(pubkey)))] if pubkey else \
        [Path(os.path.expanduser(f"~/.ssh/{k}.pub")) for k in ("id_ed25519", "id_ecdsa", "id_rsa")]
    pubkey_path = next((c for c in candidates if c.is_file()), None)
    if pubkey_path is None:
        raise Refuse("no SSH public key for the administrator: set lite.ssh_pubkey to the .pub file you SSH into the "
                     "box with (none of ~/.ssh/id_ed25519.pub, id_ecdsa.pub, id_rsa.pub exists)")
    registry = str(lite.get("image_registry") or "").strip().rstrip("/")
    if registry and not IMAGE_REGISTRY.match(registry):
        raise Refuse(f"lite.image_registry {registry!r} must be <host>[:<port>]/<namespace>, "
                     "such as 127.0.0.1:5000/goat (ops/recipes/local-registry/README.md)")
    unknown = set(lite) - {"name", "host", "ssh_user", "admin", "zone", "disk_encryption", "data_disk", "ssh_pubkey",
                           "internet", "image_registry"}
    if unknown:
        raise Refuse(f"lite: unknown key(s) {', '.join(sorted(unknown))}")
    try:
        is_ip = isinstance(ipaddress.ip_address(host), ipaddress.IPv4Address)
    except ValueError:
        is_ip = False
    return {"name": name, "host": host, "user": user, "admin": admin, "zone": zone,
            "disk_encryption": enc, "data_disk": disk, "host_is_ip": is_ip, "ssh_pubkey": pubkey_path,
            "image_registry": registry,
            "internet": internet}


def load_internet(block, name: str, admin: str, lan_zone: str) -> dict:
    """lite.internet (goatlite.md §6): the public zone and what reaching it needs.
    Secrets are never values here: the Cloudflare token is CLOUDFLARE_API_TOKEN_<NAME>
    under the declared secrets posture, and cloudflare_token_ref may only name a
    reference for a reference store to resolve."""
    if not isinstance(block, dict) or not block:
        raise Refuse("lite.internet must be a block with at least `zone:` (docs/design/goatlite.md §6)")
    unknown = set(block) - INTERNET_KEYS
    if unknown:
        raise Refuse(f"lite.internet: unknown key(s) {', '.join(sorted(unknown))}")
    zone = str(block.get("zone") or "").strip().lower().rstrip(".")
    if not re.match(r"^[a-z0-9-]+(\.[a-z0-9-]+)+$", zone):
        raise Refuse(f"lite.internet.zone {zone!r} must be a public DNS zone you control, like {name}.example.org")
    if zone.endswith(PRIVATE_SUFFIXES) or zone == lan_zone:
        raise Refuse(f"lite.internet.zone {zone!r} is a LAN-only name; the internet zone is a public domain "
                     f"whose DNS Cloudflare serves (ACME DNS-01 and the relay records are written there)")
    email = str(block.get("acme_email") or admin).strip()
    if "@" not in email or email.startswith("@") or email.endswith("@") or " " in email:
        raise Refuse("lite.internet.acme_email must be an e-mail address (Let's Encrypt's account contact)")
    profile = str(block.get("aws_profile") or name).strip()
    if not re.match(r"^[A-Za-z0-9_.+-]{1,64}$", profile):
        raise Refuse(f"lite.internet.aws_profile {profile!r} must be an AWS profile name")
    ref = block.get("cloudflare_token_ref")
    key = f"CLOUDFLARE_API_TOKEN_{name.replace('-', '_').upper()}"
    if ref is not None:
        ref = str(ref).strip()
        if ref == key:
            ref = None   # the env-file key phase 7 reads: the default, named
        elif not ref.startswith(tuple(REF_PREFIXES)):
            raise Refuse(f"lite.internet.cloudflare_token_ref must be a reference (op://, bao:// or bw://) or {key}, "
                         f"the store key phase 7 reads; never a value, and no other key name. Under env-file, "
                         f"git-crypt or sops the token is the value of {key} in the store, and "
                         "`goatbuilder secrets init` lists it as the one outside value to fill")
    relays = block.get("relays", [dict(r) for r in DEFAULT_RELAYS])
    if not isinstance(relays, list) or not 1 <= len(relays) <= 4:
        raise Refuse("lite.internet.relays must list one to four relays, each {name, region}")
    seen = set()
    for r in relays:
        if not isinstance(r, dict) or set(r) != {"name", "region"}:
            raise Refuse("lite.internet.relays: each relay is exactly {name, region}")
        r["name"], r["region"] = str(r["name"]).strip(), str(r["region"]).strip()
        if not re.match(r"^[a-z0-9]{1,8}$", r["name"]) or r["name"] in seen:
            raise Refuse(f"lite.internet.relays: name {r['name']!r} must be 1-8 lowercase letters or digits, unique")
        if not re.match(r"^[a-z]{2}(-gov)?-[a-z]+-[0-9]$", r["region"]):
            raise Refuse(f"lite.internet.relays: region {r['region']!r} must be an AWS region such as us-east-2")
        seen.add(r["name"])
    mesh_ip = block.get("mesh_ip")
    if mesh_ip is not None:
        mesh_ip = str(mesh_ip).strip()
        try:
            ipaddress.IPv4Address(mesh_ip)
        except ValueError:
            raise Refuse(f"lite.internet.mesh_ip {mesh_ip!r} must be the box's mesh IPv4 address (netbird status, after phase 8)")
    return {"zone": zone, "acme_email": email, "aws_profile": profile, "cloudflare_token_ref": ref,
            "relays": relays, "mesh_ip": mesh_ip}


def facts(cfg: dict) -> dict:
    name = cfg["name"]
    f = dict(cfg)
    f["name_us"] = name.replace("-", "_")
    f["group"] = f["name_us"] + "_hosts"
    f["upper"] = f["name_us"].upper()
    f["today"] = dt.date.today().isoformat()
    f["root_cert"] = REPO / "ops/enrollment/ca" / name / "root-cert.pem"
    f["root_key"] = STATE_DIR / f"{name}-ca" / "ca.key.age"
    f["age_identity"] = Path(os.path.expanduser("~/.config/age/keys.txt"))
    f["pubkey_dir"] = REPO / "ops/enrollment/public-keys"
    f["ca_id"] = existing_ca_id(f) or f"dev-{name}-ca-ecdsa-{f['today']}"
    if cfg["host_is_ip"]:
        f["lan_cidr"] = str(ipaddress.ip_network(cfg["host"] + "/24", strict=False))
    else:
        f["lan_cidr"] = ""
    # The DNS zone the site's services live under. A LAN goatlite: lite.zone, served by
    # the box's LAN CoreDNS. Grown to the internet: the enrolment apex netbird.<public
    # zone>, which traefik-acme.yml requires site_dns_zone to equal (Ory issuers and the
    # ACME routes must agree), with service names <svc>.<name>.netbird.<public zone>
    # served by mesh CoreDNS. The SPIRE trust domain stays on lite.zone either way:
    # it is locked once minted, and growing must not rename it.
    inet = cfg.get("internet")
    f["site_zone"] = f"netbird.{inet['zone']}" if inet else cfg["zone"]
    f["apex"] = f"netbird.{inet['zone'] if inet else cfg['zone']}"
    return f


def relay_fqdns(f: dict) -> list:
    """Each relay's public name, as terraform/modules/goat-relay writes it."""
    inet = f["internet"]
    return [f"{RELAY_DNS_PREFIX}-{r['name']}.{inet['zone']}" for r in inet["relays"]]


# ----------------------------------------------------------------------------- the CA

def existing_ca_id(f: dict) -> str:
    """The ca_id of an already-minted CA, read from the CA-ID header of the public key
    ca-init wrote under ops/enrollment/public-keys/; '' when none."""
    for p in sorted(f["pubkey_dir"].glob(f"dev-{f['name']}-ca-*.pem")):
        for ln in p.read_text(encoding="utf-8", errors="replace").splitlines():
            if ln.startswith("CA-ID:"):
                return ln.split(":", 1)[1].strip()
    return ""


def tool(name: str) -> str:
    """A binary from ops/enrollment/cmd/<name>: PATH first, else built into ops/enrollment/bin
    (the way mint-site-certs.sh builds cert-sign)."""
    found = shutil.which(name)
    if found:
        return found
    built = REPO / "ops/enrollment/bin" / name
    if not built.exists():
        if not shutil.which("go"):
            raise Refuse(f"{name} is not on PATH and go is not installed to build ops/enrollment/cmd/{name}")
        print(f"goatlite-render: {name} not on PATH — building from ops/enrollment/cmd/{name}", file=sys.stderr)
        r = subprocess.run(["go", "build", "-o", str(built), f"./cmd/{name}"], cwd=REPO / "ops/enrollment",
                           capture_output=True, text=True)
        if r.returncode != 0:
            raise Refuse(f"building {name} failed:\n{r.stderr.strip()[-800:]}")
    return str(built)


def ensure_ca(f: dict, rep: "Report", check: bool) -> None:
    """The goatnet's CA, minted when neither half exists (ADR 1213 D4) by the ONE code
    path phase 4 also uses: mint-site-certs.sh --mint-ca-only (age identity, ca-init,
    public key under ops/enrollment/public-keys; half a CA is refused). Needs the
    rendered manifest, which names the paths."""
    cert, key = f["root_cert"], f["root_key"]
    if cert.exists() and key.exists():
        rep.add(cert, f"present (ca_id {f['ca_id']})")
        return
    if check:
        rep.add(cert, f"would mint (mint-site-certs.sh --mint-ca-only, ca_id {f['ca_id']})")
        return
    r = subprocess.run([str(REPO / "ops/scripts/mint-site-certs.sh"), f["name"], "--mint-ca-only"],
                       capture_output=True, text=True)
    if r.returncode != 0 or not (cert.exists() and key.exists()):
        raise Refuse(f"mint-site-certs.sh --mint-ca-only failed:\n{(r.stdout + r.stderr).strip()[-900:]}")
    rep.add(f["age_identity"], "age identity (the CA key's single recipient; back it up)")
    rep.add(cert, f"written (root cert; ca_id {f['ca_id']})")
    rep.add(key, "written (age-encrypted CA key — never commit it)")
    rep.add(f["pubkey_dir"] / f"{f['ca_id']}.pem", "written (CA public key — commit it)")


def admin_ssh_pubkey(f: dict, rep: "Report", check: bool) -> None:
    """PLATFORM_ADMIN_SSH_PUBKEYS (mgmt-host-baseline.yml's admin key list) from the
    learner's own public key, stored under the declared secrets posture: written through
    posture.set_values on a value store, a hint on a reference store."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("goat_posture", REPO / "ops/secrets/posture.py")
    posture = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(posture)
    name = "PLATFORM_ADMIN_SSH_PUBKEYS"
    value = f["ssh_pubkey"].read_text(encoding="utf-8").strip()
    if not value.startswith(("ssh-", "ecdsa-")):
        raise Refuse(f"{f['ssh_pubkey']} does not look like an SSH public key")
    try:
        store = posture.store(str(REPO))
    except posture.PostureError as e:
        raise Refuse(str(e))
    if store in posture.VALUE_STORES:
        if check:
            rep.add(f"{name} ({store})", "would store" if name not in posture.available(str(REPO)) else "present")
            return
        try:
            state = posture.set_values({name: value}, str(REPO))[name]
        except posture.PostureError as e:
            raise Refuse(str(e))
        rep.add(f"{name} ({store}: {os.path.relpath(posture.store_file(str(REPO)), REPO)})",
                f"{state} from {f['ssh_pubkey']}")
    else:
        rep.add(f"{name} ({store})", "not written — a reference store takes references: "
                + " ".join(posture.hint([name], str(REPO))))


def sign_intent(f: dict, rep: "Report") -> None:
    intent = REPO / "ops/consistency/intent" / f["name_us"] / "intent.json"
    if not intent.exists():
        rep.add(intent, "NOT present — nothing to sign")
        return
    signer = tool("intent-sign")
    r = subprocess.run([signer, "--intent", str(intent), "--root-key", str(f["root_key"]),
                        "--age-identity", str(f["age_identity"]), "--pubkey-dir", str(f["pubkey_dir"]),
                        "--audit-log", str(STATE_DIR.parent / "ca-audit.jsonl")],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise Refuse(f"intent-sign failed:\n{(r.stdout + r.stderr).strip()[-800:]}")
    rep.add(intent.with_suffix(".json.sig"), f"signed with {f['ca_id']}")


