def dev_rung_name() -> str:
    """The first rung of the checkout's promotion path (ops/goatbuilder/goatbuilder.yaml),
    whose fleet-pins deviations a goatlite borrows where a component's fleet row is null.
    Read, never named: a checkout outside this repository has its own rungs, or none."""
    cfg = REPO / "ops/goatbuilder/goatbuilder.yaml"
    if not cfg.is_file():
        return ""
    data = yaml.safe_load(cfg.read_text(encoding="utf-8")) or {}
    for stage in ((data.get("promotion") or {}).get("path") or []):
        if stage.get("kind") == "rung" and stage.get("environment"):
            return str(stage["environment"])
    return ""


# A goat image pin: ghcr.io/<org>/<name>, the org written as the `{{ ghcr_org }}`
# template group_vars/all.yml resolves, or literally as that org ($GHCR_ORG, else
# the default that file sets). lite.image_registry replaces that prefix
# (ops/recipes/local-registry/README.md); another project's image on ghcr.io
# (ghcr.io/spiffe/...) is not goat's and keeps its registry.
def default_ghcr_org() -> str:
    """$GHCR_ORG, else the ghcr_org default group_vars/all.yml sets (the rule of
    ops/scripts/standup-images.py). Empty when neither names one."""
    org = os.environ.get("GHCR_ORG") or ""
    if org:
        return org
    try:
        text = (REPO / "ops/ansible/group_vars/all.yml").read_text(encoding="utf-8")
    except OSError:
        return ""
    m = re.search(r"""^ghcr_org:.*["' ]([A-Za-z0-9][A-Za-z0-9._-]*)["']?[ }"]*$""", text, re.M)
    return m.group(1) if m else ""


GOAT_ORG = default_ghcr_org()
GOAT_IMAGE = re.compile(r"^ghcr\.io/(\{\{ *ghcr_org *\}\}" + (("|" + re.escape(GOAT_ORG)) if GOAT_ORG else "") + r")/")
IMAGE_REGISTRY = re.compile(r"^[a-z0-9][a-z0-9.-]*(:[0-9]{1,5})?(/[a-z0-9][a-z0-9._-]*)+$")


def registry_vars(f: dict) -> str:
    """The vars.yml lines lite.image_registry adds: none for an unset or loopback
    registry (Docker reaches 127.0.0.0/8 over plain HTTP without being told), else the
    registry's host:port in docker_engine_insecure_registries, which phase 2 writes
    into daemon.json. The pins stay digest-pinned, so the content is still checked."""
    registry = f.get("image_registry") or ""
    host = registry.split("/", 1)[0]
    if not registry or host.split(":", 1)[0] in ("localhost",) or host.startswith("127."):
        return ""
    return (f"\n\n# -- Image registry (goatlite.yaml image_registry; ops/recipes/local-registry/) --\n"
            f"docker_engine_insecure_registries: [\"{host}\"]")


def from_registry(ref: str, registry: str) -> str:
    """The pin `ref` as served by `registry` (<host>[:<port>]/<namespace>): a goat image
    keeps its name and digest under the new prefix; any other image is returned as is."""
    return GOAT_IMAGE.sub(registry + "/", ref, count=1) if registry else ref


def lite_deviations(image_registry: str = "") -> dict:
    """component -> ("absent", why) or ("value", ref, why) for a goatlite; why is `tier`
    or `null` for an absent component, `dev` or `registry` for a value. The component
    list and the dev rung's values are read from fleet-pins.yaml, where component
    definitions live. With image_registry set, every goat image the goatlite runs is
    pinned at that registry under the same name and digest."""
    table = yaml.safe_load(FLEET_PINS.read_text(encoding="utf-8"))
    comps = table.get("components") or {}
    dev_rung = dev_rung_name()
    out = {}
    for cname, spec in comps.items():
        devs = spec.get("deviations") or {}
        is_image = (spec.get("artifact_type") or "image") == "image"
        if cname in LITE_ABSENT:
            out[cname] = ("absent", "tier")
        elif (devs.get(dev_rung) or {}).get("value") if dev_rung else False:
            # A goatlite is a learner goatnet and sits on the dev rung: where that
            # rung runs a candidate, the goatlite runs the same candidate, whether
            # or not the fleet row has a graduated value. Found live: the graduated
            # portal predates the release-sets API that main's grant-keyd proves,
            # so a goatlite on the fleet row failed step 12 while the dev rung
            # passed it.
            ref = str(devs[dev_rung]["value"])
            out[cname] = ("value", from_registry(ref, image_registry) if is_image else ref, "dev")
        elif spec.get("fleet") is None:
            out[cname] = ("absent", "null")
        elif image_registry and is_image and GOAT_IMAGE.match(str(spec["fleet"])):
            out[cname] = ("value", from_registry(str(spec["fleet"]), image_registry), "registry")
    return out


