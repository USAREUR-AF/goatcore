def pins_deviation_blocks(f: dict, rep: "Report", check: bool) -> None:
    """One marker block per component under its `deviations:` map in lite-pins.yaml —
    adding the `deviations:` line, or the whole `<component>:` block, when the sidecar
    has none yet; both then live inside the markers and leave with them."""
    path = LITE_PINS
    wanted = sorted(pins_deviations(f).items())
    first = path.read_text(encoding="utf-8").split("\n")
    # Components the sidecar does not carry yet are appended at EOF in this order, so
    # a new block is followed by the NEXT new block's `  <component>:` (indent 2) —
    # or by nothing. Knowing that up front keeps the END marker's indent (yamllint's
    # comments-indentation rule) identical between the first render and a re-render.
    new_comps = [c for c, _ in wanted if not any(ln == f"  {c}:" for ln in first)]
    for cname, entry in wanted:
        tag = f"(pins: {cname})"
        text = path.read_text(encoding="utf-8")
        lines = text.split("\n")
        label = f"{path.relative_to(REPO)} [{tag}]"
        found = find_markers(lines, f["name"], "#", tag)
        if found:
            i, j = found
            body = lines[i + 1:j]
            want = entry.split("\n")
            if body and body[0] == f"  {cname}:":
                want_full = [f"  {cname}:", "    deviations:"] + want
            elif body and body[0] == "    deviations:":
                want_full = ["    deviations:"] + want
            else:
                want_full = want
            rendered = framed(f["name"], want_full, "#", tag, lines[j + 1:], "      ")
            if lines[i:j + 1] == rendered:
                rep.add(label, "unchanged")
                continue
            new_lines = lines[:i] + rendered + lines[j + 1:]
        else:
            start = next((k for k, ln in enumerate(lines) if ln == f"  {cname}:"), None)
            if start is None:
                # a component the sidecar does not carry yet: the whole block, at the end
                # of `components:` (the last top-level key of the sidecar)
                while lines and lines[-1] == "":
                    lines.pop()
                body = [f"  {cname}:", "    deviations:"] + entry.split("\n")
                later = new_comps[new_comps.index(cname) + 1:] if cname in new_comps else []
                after = [f"  {later[0]}:"] if later else []
                new_lines = lines + framed(f["name"], body, "#", tag, after, "  ") + [""]
            else:
                stop = next((k for k in range(start + 1, len(lines))
                             if re.match(r"^  [a-z0-9-]+:\s*$", lines[k]) or re.match(r"^[a-z]", lines[k])), len(lines))
                devs_at = next((k for k in range(start + 1, stop) if lines[k].rstrip() == "    deviations:"), None)
                if devs_at is not None:
                    ins = devs_at + 1
                    body = entry.split("\n")
                else:
                    ins = start + 1
                    body = ["    deviations:"] + entry.split("\n")
                new_lines = lines[:ins] + framed(f["name"], body, "#", tag, lines[ins:], "      ") + lines[ins:]
        if not check:
            path.write_text("\n".join(new_lines), encoding="utf-8")
        rep.add(label, "would write" if check else "written")


