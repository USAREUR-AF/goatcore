def lite_table_close(path: Path, rep: "Report", check: bool) -> None:
    """After the last block leaves a map, spell it `{}` again so the committed empty
    sidecar is what a fully removed render leaves behind, byte for byte."""
    if not path.exists():
        return
    lines = path.read_text(encoding="utf-8").split("\n")
    out, changed, i = [], False, 0
    while i < len(lines):
        m = re.match(r"^(goatnets|components):\s*$", lines[i])
        if m:
            j = i + 1
            while j < len(lines) and not re.match(r"^[A-Za-z]", lines[j]):
                j += 1
            if not any(ln.strip() and not ln.lstrip().startswith("#") for ln in lines[i + 1:j]):
                out.append(f"{m.group(1)}: {{}}")
                changed = True
                i = j
                continue
        out.append(lines[i])
        i += 1
    if changed:
        text = "\n".join(out)
        text = re.sub(r"\n{3,}", "\n\n", text).rstrip("\n") + "\n"
        if not check:
            path.write_text(text, encoding="utf-8")
        rep.add(f"{path.relative_to(REPO)} [empty maps]", "would close" if check else "closed back to the empty table")


