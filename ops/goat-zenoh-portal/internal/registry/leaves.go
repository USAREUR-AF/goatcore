// SlotLeafClock is the time the reuse quarantine compares leaf expiry against.
// A variable so tests can stand in for a year passing.
var SlotLeafClock = time.Now

// SlotLeaf is one row of slot_leaves: a fabric leaf issued for a slot.
type SlotLeaf struct {
	ID                int64  `db:"id"                  json:"id"`
	SlotID            string `db:"slot_id"             json:"slot_id"`
	Generation        int64  `db:"generation"          json:"generation"`
	Serial            string `db:"serial"              json:"serial"`
	NotBefore         int64  `db:"not_before"          json:"not_before"`
	NotAfter          int64  `db:"not_after"           json:"not_after"`
	IssuedForIdentity string `db:"issued_for_identity" json:"issued_for_identity,omitempty"`
	// IssuedForCustodian is the machine custodian the slot was enrolled under
	// when the leaf was minted. A free slot kept out of the pool by such a
	// leaf counts against that custodian's machine quota until the leaf
	// expires (machineQuarantineSQL), so revoking and re-enrolling machines
	// cannot drain the pool.
	IssuedForCustodian string `db:"issued_for_custodian" json:"issued_for_custodian,omitempty"`
	LateAttributed     int64  `db:"late_attributed"      json:"late_attributed,omitempty"`
	IssuedAt           int64  `db:"issued_at"           json:"issued_at"`
	SupersededAt       *int64 `db:"superseded_at"       json:"superseded_at,omitempty"`
}

// LeafCN is the Subject CN of a slot's leaf at generation gen: the bare anchor
// at generation 0 (every leaf minted before generations existed), otherwise
// "<anchor>.g<gen>".
func LeafCN(anchor string, gen int64) string {
	if gen <= 0 {
		return anchor
	}
	return anchor + ".g" + strconv.FormatInt(gen, 10)
}

var leafCNRe = regexp.MustCompile(`^([0-9a-f]{32})(?:\.g([1-9][0-9]*))?$`)

// AnchorOfCN splits a slot leaf CN into its anchor and generation. ok is false
// for a CN that is not slot-shaped (an infra or per-vendor "-trial-peer" CN),
// which the caller must then treat as it did before. "<anchor>.g0" is not a CN
// any mint produces and is refused.
func AnchorOfCN(cn string) (anchor string, gen int64, ok bool) {
	m := leafCNRe.FindStringSubmatch(strings.TrimSpace(cn))
	if m == nil {
		return "", 0, false
	}
	if m[2] == "" {
		return m[1], 0, true
	}
	g, err := strconv.ParseInt(m[2], 10, 64)
	if err != nil {
		return "", 0, false
	}
	return m[1], g, true
}

// slotReusableSQL is the free-pool condition: no leaf recorded for the slot is
// still valid, except leaves issued for the claimant itself. $n carries the
// clock (Unix seconds), $n+1 the claimant's identity UUID (empty = none, which no
// leaf matches, so an unidentified claim never gets a slot with a live leaf).
func slotReusableSQL(n int) string {
	return fmt.Sprintf(`NOT EXISTS (SELECT 1 FROM slot_leaves l
	    WHERE l.slot_id = slots.slot_id AND l.not_after > $%d
	      AND ($%d = '' OR lower(l.issued_for_identity) <> lower($%d)))`, n, n+1, n+1)
}

// BumpSlotGeneration advances an ASSIGNED slot's generation and marks every
// leaf issued under an earlier one superseded, in one transaction, and returns
// the new generation. Rotation and collection call it before minting, so the
// leaf they mint carries a CN no earlier leaf had, and the fragment rendered
// after it no longer names the earlier CN. ErrNotFound when the slot is unknown
// or free: a free slot has no holder to issue a leaf to.
//
// It fails closed: if the mint after the bump fails, the holder's previous
// leaf stops matching at the router's next reload and no new leaf exists until
// the rotate or collect is retried.
func (r *Registry) BumpSlotGeneration(ctx context.Context, slotID string) (int64, error) {
	tx, err := r.beginLocked(ctx)
	if err != nil {
		return 0, fmt.Errorf("bump slot generation: begin: %w", err)
	}
	defer func() { _ = tx.Rollback() }()
	var gen int64
	err = tx.GetContext(ctx, &gen,
		`UPDATE slots SET generation = generation + 1
		  WHERE slot_id = $1 AND assigned_to IS NOT NULL AND revoked_at IS NULL
		  RETURNING generation`, slotID)
	if errors.Is(err, sqlErrNoRows()) {
		return 0, ErrNotFound
	}
	if err != nil {
		return 0, fmt.Errorf("bump slot generation: %w", err)
	}
	if err := supersedeLeaves(ctx, tx, slotID, time.Now().Unix()); err != nil {
		return 0, err
	}
	if err := tx.Commit(); err != nil {
		return 0, fmt.Errorf("bump slot generation: commit: %w", err)
	}
	return gen, nil
}

func supersedeLeaves(ctx context.Context, tx *sqlx.Tx, slotID string, now int64) error {
	if _, err := tx.ExecContext(ctx,
		`UPDATE slot_leaves SET superseded_at = $1 WHERE slot_id = $2 AND superseded_at IS NULL`,
		now, slotID); err != nil {
		return fmt.Errorf("supersede slot leaves: %w", err)
	}
	return nil
}

// RecordSlotLeaf records a leaf just minted for slotID at generation gen. It
// refuses a leaf whose generation is not the slot's current one: that leaf was
// minted against a generation a concurrent assign, rotate, collect or revoke
// has already replaced, so its CN is not rendered and must not be handed out.
// The row is still written first, because the leaf exists and its validity is
// what keeps the slot in quarantine.
func (r *Registry) RecordSlotLeaf(ctx context.Context, l SlotLeaf) error {
	if l.SlotID == "" {
		return errors.New("record slot leaf: slot id required")
	}
	if l.NotAfter <= 0 {
		return errors.New("record slot leaf: not_after required")
	}
	if l.IssuedAt == 0 {
		l.IssuedAt = time.Now().Unix()
	}
	tx, err := r.beginLocked(ctx)
	if err != nil {
		return fmt.Errorf("record slot leaf: begin: %w", err)
	}
	defer func() { _ = tx.Rollback() }()
	var cur int64
	var identity, custodian *string
	row := tx.QueryRowxContext(ctx, `SELECT generation, identity_id, enrolled_by FROM slots WHERE slot_id = $1`, l.SlotID)
	if err := row.Scan(&cur, &identity, &custodian); err != nil {
		if errors.Is(err, sqlErrNoRows()) {
			return fmt.Errorf("record slot leaf: slot %q not found", l.SlotID)
		}
		return fmt.Errorf("record slot leaf: read slot: %w", err)
	}
	// The caller names the identity it minted for when it has one (collect,
	// rotate, onboard with a linkage). A slot that changed hands while the
	// mint ran (a relink, GHSA-rr3p review r5 F3) must not get a leaf the
	// registry would then attribute to its new owner.
	changedHands := false
	if l.IssuedForIdentity != "" && (identity == nil || !strings.EqualFold(*identity, l.IssuedForIdentity)) {
		changedHands = true
	}
	if l.IssuedForIdentity == "" && identity != nil {
		l.IssuedForIdentity = *identity
	}
	if l.IssuedForCustodian == "" && custodian != nil {
		l.IssuedForCustodian = *custodian
	}
	var superseded any
	if l.Generation != cur || changedHands {
		superseded = l.IssuedAt
	}
	if _, err := tx.ExecContext(ctx,
		`INSERT INTO slot_leaves (slot_id, generation, serial, not_before, not_after, issued_for_identity, issued_for_custodian, issued_at, superseded_at)
		 VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)`,
		l.SlotID, l.Generation, strings.ToLower(l.Serial), l.NotBefore, l.NotAfter, l.IssuedForIdentity, l.IssuedForCustodian, l.IssuedAt, superseded); err != nil {
		return fmt.Errorf("record slot leaf: %w", err)
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("record slot leaf: commit: %w", err)
	}
	if l.Generation != cur {
		return fmt.Errorf("%w: leaf minted at generation %d, slot %s is now at %d", ErrStaleGeneration, l.Generation, l.SlotID, cur)
	}
	if changedHands {
		return fmt.Errorf("%w: leaf minted for identity %s, slot %s is now linked to another", ErrStaleGeneration, l.IssuedForIdentity, l.SlotID)
	}
	return nil
}

// endAnchorAllowances removes what an anchor's holder was allowed as that
// anchor and that the next holder of the index must not inherit (GHSA-fghv):
// the machine-enrolment grant, custody of the machines it enrolled, and its
// topic-budget allowance (topic_budgets.owner = anchor).
func endAnchorAllowances(ctx context.Context, tx *sqlx.Tx, anchor string) error {
	if _, err := tx.ExecContext(ctx, `DELETE FROM machine_grants WHERE custodian = $1`, anchor); err != nil {
		return fmt.Errorf("machine grant: %w", err)
	}
	if _, err := tx.ExecContext(ctx, `UPDATE slots SET enrolled_by = NULL WHERE enrolled_by = $1`, anchor); err != nil {
		return fmt.Errorf("custody: %w", err)
	}
	if _, err := tx.ExecContext(ctx, `DELETE FROM topic_budgets WHERE owner = $1`, anchor); err != nil {
		return fmt.Errorf("topic budget: %w", err)
	}
	return nil
}

// machineQuarantineSQL counts the free pool slots a custodian's machines left
// in reuse quarantine: slots with an unexpired leaf minted while enrolled under
// that custodian. $1 is the custodian, $2 the clock (Unix seconds).
const machineQuarantineSQL = `SELECT COUNT(DISTINCT l.slot_id) FROM slot_leaves l JOIN slots s ON s.slot_id = l.slot_id
	 WHERE l.issued_for_custodian = $1 AND l.not_after > $2 AND s.assigned_to IS NULL`

// endAnchorGrants revokes the active data grants tied to an anchor's holder:
// those where the anchor is the PRODUCER (others reading its namespace) and
// those where it is the GRANTEE (GHSA-rr3p review r7 F1): a co-publish write
// grant naming the writer's anchor, which the router binds to slot-<anchor>,
// and a principal view grant that puts the anchor in a DEK audience. The next
// holder of the index must inherit neither. createdBefore > 0 limits it to
// grants created before that time (the reissue of a slot reused before the
// fix keeps what its current holder was granted since its assignment).
func endAnchorGrants(ctx context.Context, tx *sqlx.Tx, anchor string, now int64, by string, createdBefore int64) error {
	if _, err := tx.ExecContext(ctx,
		`UPDATE grants SET status = 'revoked', revoked_at = $1, revoked_by = $3
		  WHERE status = 'active'
		    AND (producer = $2 OR (grantee_kind = 'principal' AND grantee_id = $2))
		    AND ($4 = 0 OR created_at < $4)`, now, anchor, by, createdBefore); err != nil {
		return fmt.Errorf("data grants: %w", err)
	}
	return nil
}

// ErrStaleGeneration means a leaf was minted for a generation the slot has
// since left. The caller must not hand that leaf out.
var ErrStaleGeneration = errors.New("slot generation moved during the mint")

// NormalizeIdentityID is the one spelling of a Kratos identity UUID the slot
// registry stores and compares: trimmed and lower-case (GHSA-rr3p review r7
// F3). ValidIdentityID accepts either hex case, and a re-stamp of the same
// person in a different case must not read as a change of hands.
func NormalizeIdentityID(id string) string {
	return strings.ToLower(strings.TrimSpace(id))
}

// SlotByID returns the slot row for slotID, or ErrNotFound.
func (r *Registry) SlotByID(ctx context.Context, slotID string) (*Slot, error) {
	var s Slot
	err := r.reader().GetContext(ctx, &s, `SELECT * FROM slots WHERE slot_id = $1`, slotID)
	if errors.Is(err, sqlErrNoRows()) {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("slot by id: %w", err)
	}
	return &s, nil
}

// StampSlotCertAt is StampSlotCert for a mint at generation gen for
// identityID ("" = none): it writes only while the slot is still assigned at
// that generation and linked to that identity, and returns ErrStaleGeneration
// otherwise. A hand-over landing between a mint and its stamps would otherwise
// be undone by them, locking the new identity out (GHSA-rr3p review r6 F3).
func (r *Registry) StampSlotCertAt(ctx context.Context, slotID, bundleToken, bundlePath string, gen int64, identityID string) error {
	now := time.Now().Unix()
	res, err := r.db.ExecContext(ctx,
		`UPDATE slots SET cert_minted_at = $1, bundle_token = $2, bundle_path = $3, bundle_minted_at = $1
		  WHERE slot_id = $4 AND generation = $5 AND assigned_to IS NOT NULL
		    AND lower(identity_id) IS NOT DISTINCT FROM lower($6::TEXT)`,
		now, bundleToken, bundlePath, slotID, gen, nullIfEmpty(identityID))
	if err != nil {
		return fmt.Errorf("stamp slot cert: %w", err)
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return fmt.Errorf("%w: slot %s is no longer at generation %d for the identity it was minted for", ErrStaleGeneration, slotID, gen)
	}
	return nil
}

// StampSlotCollectedAt is StampSlotCollected under the same condition as
// StampSlotCertAt.
func (r *Registry) StampSlotCollectedAt(ctx context.Context, slotID string, gen int64, identityID string) error {
	res, err := r.db.ExecContext(ctx,
		`UPDATE slots SET collected_at = $1
		  WHERE slot_id = $2 AND generation = $3 AND assigned_to IS NOT NULL
		    AND lower(identity_id) IS NOT DISTINCT FROM lower($4::TEXT)`,
		time.Now().Unix(), slotID, gen, nullIfEmpty(identityID))
	if err != nil {
		return fmt.Errorf("stamp slot collected: %w", err)
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return fmt.Errorf("%w: slot %s is no longer at generation %d for the identity it was collected by", ErrStaleGeneration, slotID, gen)
	}
	return nil
}

// HasLeafAt reports whether any leaf is recorded for slotID at generation gen.
func (r *Registry) HasLeafAt(ctx context.Context, slotID string, gen int64) (bool, error) {
	var n int
	if err := r.reader().GetContext(ctx, &n,
		`SELECT COUNT(*) FROM slot_leaves WHERE slot_id = $1 AND generation = $2`, slotID, gen); err != nil {
		return false, fmt.Errorf("has leaf at: %w", err)
	}
	return n > 0, nil
}

// SlotLeaves returns every leaf recorded for slotID, oldest first.
func (r *Registry) SlotLeaves(ctx context.Context, slotID string) ([]SlotLeaf, error) {
	var out []SlotLeaf
	if err := r.reader().SelectContext(ctx, &out,
		`SELECT * FROM slot_leaves WHERE slot_id = $1 ORDER BY issued_at, id`, slotID); err != nil {
		return nil, fmt.Errorf("slot leaves: %w", err)
	}
	return out, nil
}

// SlotBinding is what the router fragment needs for one pool slot: its anchor
// and, when the slot is assigned, the CN of its current generation. CN is ""
// for a free (including quarantined) slot, which the fragment renders as no CN
// at all.
type SlotBinding struct {
	Anchor string
	Idx    int64
	CN     string
	// Copub lists every co-publish target (ADR 1105) this anchor has EVER
	// been granted, one per multi-publisher topic base, so the router's
	// per-topic copub subjects stay declared after a grant ends (GHSA-rr3p
	// reviews r7, r8 F1).
	Copub []CopubBinding
}

// CopubBinding is one (writer anchor, multi-publisher topic) pair. Live is
// true only while the slot is assigned and a grant for exactly this topic is
// active and inside its effective window at render time; the fragment then
// gives that topic's subject the slot's current CN.
type CopubBinding struct {
	Key  string // CopubKey(base)
	Base string
	Live bool
}

// CopubKey is the subject key of a multi-publisher topic base: the first 16
// hex of sha256(base). The router role computes the same with
// `(base | hash('sha256'))[:16]`.
func CopubKey(base string) string {
	sum := sha256.Sum256([]byte(base))
	return hex.EncodeToString(sum[:])[:16]
}

// SlotBindings returns one binding per pool slot, in index order.
func (r *Registry) SlotBindings(ctx context.Context) ([]SlotBinding, error) {
	var rows []struct {
		SlotID     string  `db:"slot_id"`
		Idx        int64   `db:"idx"`
		Generation int64   `db:"generation"`
		AssignedTo *string `db:"assigned_to"`
		RevokedAt  *int64  `db:"revoked_at"`
	}
	if err := r.reader().SelectContext(ctx, &rows,
		`SELECT slot_id, idx, generation, assigned_to, revoked_at FROM slots ORDER BY idx, slot_id`); err != nil {
		return nil, fmt.Errorf("slot bindings: %w", err)
	}
	var writes []Grant
	if err := r.reader().SelectContext(ctx, &writes,
		`SELECT * FROM grants WHERE action = 'write' AND grantee_kind = 'principal' ORDER BY grantee_id, producer, id`); err != nil {
		return nil, fmt.Errorf("slot bindings: co-publish grants: %w", err)
	}
	now := SlotLeafClock().Unix()
	copub := map[string]map[string]bool{} // anchor -> base -> live
	for _, g := range writes {
		base := g.CoPublishKeyBase()
		if base == "" {
			continue
		}
		if copub[g.GranteeID] == nil {
			copub[g.GranteeID] = map[string]bool{}
		}
		copub[g.GranteeID][base] = copub[g.GranteeID][base] || g.InEffectAt(now)
	}
	out := make([]SlotBinding, 0, len(rows))
	for _, s := range rows {
		b := SlotBinding{Anchor: s.SlotID, Idx: s.Idx}
		assigned := s.AssignedTo != nil && *s.AssignedTo != "" && s.RevokedAt == nil
		if assigned {
			b.CN = LeafCN(s.SlotID, s.Generation)
		}
		bases := make([]string, 0, len(copub[s.SlotID]))
		for base := range copub[s.SlotID] {
			bases = append(bases, base)
		}
		sort.Strings(bases)
		for _, base := range bases {
			b.Copub = append(b.Copub, CopubBinding{Key: CopubKey(base), Base: base, Live: assigned && copub[s.SlotID][base]})
		}
		out = append(out, b)
	}
	return out, nil
}
