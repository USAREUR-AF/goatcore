// Slot generations and the leaves issued under them (GHSA-rr3p, F-305).
//
// A slot's anchor is fixed per index, and zenoh 1.9 matches a leaf only by its
// Subject CN: it has no CRL and no serial check. So the CN carries a per-slot
// generation, `<anchor>.g<N>`, and the router admits only the CN of a slot's
// CURRENT generation (the slot fragment, internal/acl/slotfragment.go). Every
// assignment, rotation, collection and revoke advances the generation, so every
// leaf issued before it stops matching any subject once the fragment is live.
// The anchor itself (the namespace, <anchor>/**) never carries the generation.
//
// Generation 0 is the bare anchor: every leaf minted before this change.

// slotLeavesSQL is registry migration 2. It adds slots.generation and the
// slot_leaves table, and backfills one "unknown leaf" row per slot that has
// any recorded history, so the reuse quarantine (live leaves) covers leaves
// minted before the table existed. The serial of those leaves is not on file
// here (leaves minted at collection left no tarball), so the row is keyed to no
// identity and lasts a year and a day past the latest thing the slot row says
// happened to it, which is the window the earlier cert_minted_at/revoked_at
// quarantine covered. It carries the slot's machine custodian (enrolled_by,
// which a revoke leaves in place), so a pre-fix machine's quarantined slot
// counts against that custodian's quota like a post-fix one, and for an
// assigned slot the identity on file, so a later relink away from that person
// is a hand-over.
const slotLeavesSQL = `
ALTER TABLE slots ADD COLUMN generation BIGINT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS slot_leaves (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id             TEXT COLLATE "C" NOT NULL,   -- the slot (anchor) the leaf was issued for
    generation          BIGINT NOT NULL,             -- slots.generation the leaf's CN carries
    serial              TEXT COLLATE "C" NOT NULL,   -- lowercase hex; '' = not on file (backfilled)
    not_before          BIGINT NOT NULL,             -- Unix seconds; 0 = not on file
    not_after           BIGINT NOT NULL,             -- Unix seconds; the slot is quarantined until every row has passed this
    issued_for_identity TEXT COLLATE "C" NOT NULL DEFAULT '', -- Kratos identity UUID the slot held at mint; '' = none or unknown
    issued_for_custodian TEXT COLLATE "C" NOT NULL DEFAULT '', -- machine custodian (slots.enrolled_by) at mint; '' = not a machine
    late_attributed     BIGINT NOT NULL DEFAULT 0,   -- 1 = issued_for_identity was written by a late linkage, not at mint
    issued_at           BIGINT NOT NULL,
    superseded_at       BIGINT                       -- when a later generation (or the free) replaced it; NULL = current
);
CREATE INDEX IF NOT EXISTS slot_leaves_slot_idx ON slot_leaves(slot_id, not_after);

INSERT INTO slot_leaves (slot_id, generation, serial, not_before, not_after, issued_for_identity, issued_for_custodian, issued_at, superseded_at)
SELECT slot_id, 0, '', 0,
       GREATEST(cert_minted_at, bundle_minted_at, collected_at, assigned_at, revoked_at) + 366 * 86400,
       CASE WHEN assigned_to IS NOT NULL THEN COALESCE(identity_id, '') ELSE '' END,
       COALESCE(enrolled_by, ''),
       GREATEST(cert_minted_at, bundle_minted_at, collected_at, assigned_at, revoked_at),
       CASE WHEN assigned_to IS NULL THEN revoked_at END
  FROM slots
 WHERE GREATEST(cert_minted_at, bundle_minted_at, collected_at, assigned_at, revoked_at) IS NOT NULL;
`

