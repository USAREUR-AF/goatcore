// parseOperatorAPIKeys parses the "handle1:key1,handle2:key2" form of
// PORTAL_OPERATOR_API_KEYS into a handle→key map. Whitespace
// around handles, keys, and the comma separators is trimmed; blank
// comma-entries are ignored. A pair without exactly one colon, or with an
// empty handle or key, is a configuration error.
func parseOperatorAPIKeys(raw string) (map[string]string, error) {
	out := map[string]string{}
	for index, pair := range strings.Split(raw, ",") {
		pair = strings.TrimSpace(pair)
		if pair == "" {
			continue
		}
		idx := strings.IndexByte(pair, ':')
		if idx < 0 || strings.IndexByte(pair[idx+1:], ':') >= 0 {
			return nil, fmt.Errorf("operator-api-keys entry %d must be exactly one handle:key pair", index+1)
		}
		handle := strings.TrimSpace(pair[:idx])
		key := strings.TrimSpace(pair[idx+1:])
		if handle == "" || key == "" {
			return nil, fmt.Errorf("operator-api-keys entry %d has an empty handle or key", index+1)
		}
		out[handle] = key
	}
	return out, nil
}

// Validate returns a non-nil error when the configuration is structurally
// incomplete. Called once at startup; fail fast.
func (c *Config) Validate() error {
	if c.Listen == "" {
		return errors.New("listen address is required (--listen)")
	}
	if err := c.RequireDSN(); err != nil {
		return err
	}
	switch c.IdentityModel {
	case IdentityModelPerVendor:
		// nothing extra to validate.
	case IdentityModelPerUUID:
		if c.SlotPoolSalt == "" {
			return errors.New("per-uuid-slot-pool requires --slot-pool-salt (must match the router template's zenoh_slot_pool_salt)")
		}
		if c.SlotPoolSize <= 0 {
			return errors.New("per-uuid-slot-pool requires --slot-pool-size > 0 (must equal the router's zenoh_slot_pool_size)")
		}
	default:
		return fmt.Errorf("identity-model %q: must be %q or %q", c.IdentityModel, IdentityModelPerVendor, IdentityModelPerUUID)
	}
	if c.OperatorAPIKey == "" && len(c.OperatorAPIKeys) == 0 {
		return errors.New("operator API key is required (--operator-api-key or --operator-api-keys); without it no one can register vendors")
	}
	if _, err := url.Parse(c.ZenohRest); err != nil && !c.ZenohRestFake {
		return fmt.Errorf("zenoh-rest URL is invalid: %w", err)
	}
	if c.ACLConfigPath == "" {
		return errors.New("acl config path is required (--acl-config)")
	}
	if c.ACLStorageDirPrefix == "" {
		return errors.New("acl storage dir prefix is required (--acl-storage-dir-prefix)")
	}
	if !c.ACLReloadFake && c.ACLContainerName == "" {
		return errors.New("either --acl-container-name must be set OR --acl-reload-fake must be passed")
	}
	switch strings.ToLower(strings.TrimSpace(c.DataLabelAccessDefault)) {
	case "", "community", "org", "controlled":
		// valid (empty resolves to community at read time)
	default:
		return fmt.Errorf("data-label-access-default %q: must be community, org, or controlled (ADR 1075)", c.DataLabelAccessDefault)
	}
	if !c.CertSignFake {
		if c.CABundleDir == "" {
			return errors.New("cert-sign requires --ca-bundle-dir (or pass --cert-sign-fake for dev)")
		}
		if c.AgeIdentityPath == "" {
			return errors.New("cert-sign requires --age-identity (or pass --cert-sign-fake for dev)")
		}
		if c.CARootCert == "" {
			return errors.New("cert-sign requires --ca-root-cert to bundle into vendor tarballs (or --cert-sign-fake)")
		}
		if strings.TrimSpace(c.CertSignCAID) == "" {
			return errors.New("cert-sign requires --ca-id, the id of this goatnet's signing CA (or --cert-sign-fake)")
		}
	}
	return nil
}

// envOrAlias reads the legacy env name first, then its neutral alias; the
// legacy name wins when both are set.
func envOrAlias(legacy, alias, dflt string) string {
	return envOr(legacy, envOr(alias, dflt))
}

func envOr(key, dflt string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return dflt
}

func envInt(key string, dflt int) int {
	v := os.Getenv(key)
	if v == "" {
		return dflt
	}
	n, err := strconv.Atoi(v)
	if err != nil {
		return dflt
	}
	return n
}

func envBool(key string, dflt bool) bool {
	v := os.Getenv(key)
	if v == "" {
		return dflt
	}
	switch strings.ToLower(v) {
	case "1", "true", "yes", "on":
		return true
	case "0", "false", "no", "off":
		return false
	default:
		return dflt
	}
}

// RequireDSN fails when no registry DSN is configured. When only the SQLite
// path is, it says what to do: the registry is in Postgres only now (ADR 1165
// step A), and the file's rows reach Postgres through store-migrate import.
func (c *Config) RequireDSN() error {
	if strings.TrimSpace(c.DBDSN) != "" {
		return nil
	}
	if strings.TrimSpace(c.DBPath) != "" {
		return fmt.Errorf("PORTAL_DB_DSN (--db-dsn) is not set and PORTAL_DB (--db) is: the portal registry is stored in Postgres only (ADR 1165); import %s with `store-migrate import` and set PORTAL_DB_DSN", c.DBPath)
	}
	return errors.New("registry DSN is required (PORTAL_DB_DSN or --db-dsn)")
}
