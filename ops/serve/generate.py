#!/usr/bin/env python3
"""Generate configuration from the service registry.

Reads ops/serve/services.yaml and produces:
  ops/serve/caddy/Caddyfile           — Caddy routes (static + proxy)
  ops/serve/docker-compose.yml        — Caddy container with Traefik labels
  ops/status/services.env             — Bash-sourceable list for check.sh
  ops/dns/mesh-hosts                  — service DNS entries (managed block)

Run from repo root:
  python3 ops/serve/generate.py
"""

import os
import sys

import yaml

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))
HEADER = "# Generated by ops/serve/generate.py from services.yaml — do not edit\n"


# The serving host's mesh address and its name in ops/dns/mesh-hosts comments.
# services.yaml sets both (`mesh_ip`, `host_label`); these are the example values.
DEFAULT_MESH_IP = "100.127.1.23"
DEFAULT_HOST_LABEL = "NETHOST"

def load_registry():
    with open(os.path.join(SCRIPT_DIR, "services.yaml")) as f:
        return yaml.safe_load(f)


def caddy_services(reg):
    """Services routed through Caddy (static, static_dir, proxy)."""
    return [s for s in reg["services"] if s["type"] in ("static", "static_dir", "proxy")]


def generate_caddyfile(reg):
    suffix = reg["domain_suffix"]
    lines = [HEADER, ":80 {"]
    for svc in reg["services"]:
        fqdn = f"{svc['name']}.{suffix}"
        if svc["type"] == "static":
            lines += [
                f"\t@{svc['name']} host {fqdn}",
                f"\thandle @{svc['name']} {{",
                f"\t\troot * /srv",
                f"\t\trewrite * /{svc['file']}",
                f"\t\tfile_server",
                f"\t}}",
                "",
            ]
        elif svc["type"] == "static_dir":
            lines += [
                f"\t@{svc['name']} host {fqdn}",
                f"\thandle @{svc['name']} {{",
                f"\t\troot * /srv/{svc['dir']}",
                f"\t\ttry_files {{path}} /index.html",
                f"\t\tfile_server",
                f"\t}}",
                "",
            ]
        elif svc["type"] == "proxy":
            host = svc["upstream_host"]
            port = svc["upstream_port"]
            proto = svc.get("upstream_protocol", "http")
            upstream = f"{host}:{port}" if proto == "http" else f"https://{host}:{port}"
            lines += [
                f"\t@{svc['name']} host {fqdn}",
                f"\thandle @{svc['name']} {{",
                f"\t\treverse_proxy {upstream}",
                f"\t}}",
                "",
            ]
    # List container services so readers know this isn't the full picture.
    container_svcs = [s for s in reg["services"] if s["type"] == "container"]
    if container_svcs:
        lines += [
            "\t# Container services (routed by Traefik directly, not Caddy):",
        ]
        for svc in container_svcs:
            fqdn = f"{svc['name']}.{suffix}"
            lines.append(f"\t#   {fqdn}")
        lines += [
            "\t# Full list: ops/serve/services.yaml",
            "",
        ]

    lines += ["}", ""]
    path = os.path.join(SCRIPT_DIR, "caddy", "Caddyfile")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines))
    return path


def generate_caddy_compose(reg):
    suffix = reg["domain_suffix"]
    resolver = reg["tls_certresolver"]
    svcs = caddy_services(reg)
    labels = [
        '      - "traefik.enable=true"',
        # Wildcard cert — one cert covers all *.netbird.legacy.example
        f'      - "traefik.http.routers.wildcard-cert.rule=HostRegexp(`^.+\\\\.netbird\\\\.{reg["domain_suffix"].split(".", 1)[1]}$`)"',
        f'      - "traefik.http.routers.wildcard-cert.entrypoints=websecure"',
        f'      - "traefik.http.routers.wildcard-cert.tls=true"',
        f'      - "traefik.http.routers.wildcard-cert.tls.certresolver={resolver}"',
        f'      - "traefik.http.routers.wildcard-cert.tls.domains[0].main={suffix}"',
        f'      - "traefik.http.routers.wildcard-cert.tls.domains[0].sans=*.{suffix}"',
        '      - "traefik.http.routers.wildcard-cert.priority=1"',
        '      - "traefik.http.routers.wildcard-cert.service=caddy-proxy"',
        # Mesh-only access: only allow requests from WireGuard peers (100.64.0.0/10).
        # Blocks requests arriving via rathole (127.0.0.1) from the public internet.
        # Netbird management traffic uses its own Traefik routers — unaffected.
        '      - "traefik.http.middlewares.mesh-only.ipallowlist.sourcerange=100.64.0.0/10"',
    ]
    for svc in svcs:
        fqdn = f"{svc['name']}.{suffix}"
        n = svc["name"]
        labels += [
            f'      - "traefik.http.routers.{n}.rule=Host(`{fqdn}`)"',
            f'      - "traefik.http.routers.{n}.entrypoints=websecure"',
            f'      - "traefik.http.routers.{n}.tls=true"',
            f'      - "traefik.http.routers.{n}.middlewares=mesh-only"',
        ]
    labels.append('      - "traefik.http.services.caddy-proxy.loadbalancer.server.port=80"')

    # If any proxy services use hostnames, Caddy needs Netbird DNS to resolve them.
    has_hostname_proxy = any(
        s["type"] == "proxy" and not s["upstream_host"].replace(".", "").isdigit()
        for s in reg["services"]
    )
    dns_block = ""
    if has_hostname_proxy:
        dns_block = f"\n    dns:\n      - {reg.get('mesh_ip', DEFAULT_MESH_IP)}  # Netbird DNS proxy on {reg.get('host_label', DEFAULT_HOST_LABEL)} mesh interface"

    content = HEADER + f"""
services:
  caddy-proxy:
    container_name: caddy-proxy
    image: caddy:latest
    restart: unless-stopped
    volumes:
      - ./caddy/Caddyfile:/etc/caddy/Caddyfile:ro
      - .:/srv:ro{dns_block}
    labels:
{chr(10).join(labels)}
    networks:
      - traefik

networks:
  traefik:
    external: true
    name: ${{TRAEFIK_NETWORK:-netbird_netbird}}
"""
    path = os.path.join(SCRIPT_DIR, "docker-compose.yml")
    with open(path, "w") as f:
        f.write(content)
    return path


def validate_container_middleware(reg):
    """Check that container services have mesh-only middleware in their docker-compose."""
    _ = reg["domain_suffix"]  # Keep the required-key check for direct callers.
    container_svcs = [s for s in reg["services"] if s["type"] == "container"]
    warnings = []
    for svc in container_svcs:
        compose_path = os.path.join(REPO_ROOT, svc["compose_dir"], "docker-compose.yml")
        if not os.path.exists(compose_path):
            warnings.append(f"  WARNING: {svc['name']}: {compose_path} not found")
            continue
        with open(compose_path) as f:
            content = f.read()
        missing = []
        if "middlewares=mesh-only" not in content:
            missing.append(f"traefik.http.routers.{svc['name']}.middlewares=mesh-only")
        if "traefik.docker.network=" not in content:
            missing.append("traefik.docker.network=netbird_netbird")
        if "entrypoints=websecure" not in content:
            missing.append(f"traefik.http.routers.{svc['name']}.entrypoints=websecure")
        if "tls.certresolver=" in content:
            warnings.append(
                f"  WARNING: {svc['name']}: {compose_path} has tls.certresolver — remove it.\n"
                f"           The wildcard-cert router on caddy-proxy obtains the cert.\n"
                f"           Individual certresolver labels cause duplicate ACME requests."
            )
        if missing:
            warnings.append(
                f"  WARNING: {svc['name']}: {compose_path} missing required Traefik labels:\n"
                + "\n".join(f"           - {m}" for m in missing)
            )
    return warnings


def update_mesh_hosts(reg):
    """Update the managed service DNS block in ops/dns/mesh-hosts."""
    suffix = reg["domain_suffix"]
    mesh_ip = reg.get("mesh_ip", DEFAULT_MESH_IP)
    path = os.path.join(REPO_ROOT, "ops", "dns", "mesh-hosts")

    BEGIN = "# BEGIN services (managed by generate.py — do not edit)"
    END = "# END services (managed by generate.py)"

    entries = []
    for svc in reg["services"]:
        entries.append(f"{mesh_ip}  {svc['name']}.{suffix}")

    managed_block = "\n".join([BEGIN] + entries + [END])

    if os.path.exists(path):
        with open(path) as f:
            content = f.read()
        # Replace existing managed block or insert before custom service entries
        import re
        pattern = re.compile(
            rf"^{re.escape(BEGIN)}$.*?^{re.escape(END)}$",
            re.MULTILINE | re.DOTALL,
        )
        if pattern.search(content):
            content = pattern.sub(managed_block, content)
        else:
            # Replace the old manual "Services hosted on <host>" block if present
            old_svc = f"# Services hosted on {reg.get('host_label', DEFAULT_HOST_LABEL)} (mesh-only, behind Traefik TLS)\n"
            if old_svc in content:
                # Find the old block: from the comment to the last 100.x.x.x service line
                old_lines = content.split("\n")
                new_lines = []
                in_old_block = False
                for line in old_lines:
                    if line == old_svc.strip():
                        in_old_block = True
                        new_lines.append(managed_block)
                        continue
                    if in_old_block:
                        if line.startswith(mesh_ip) and suffix in line:
                            continue  # skip old service entries
                        in_old_block = False
                    new_lines.append(line)
                content = "\n".join(new_lines)
            else:
                # Append before EOF
                content = content.rstrip("\n") + "\n\n" + managed_block + "\n"
    else:
        content = managed_block + "\n"

    with open(path, "w") as f:
        f.write(content)
    return path


def generate_services_env(reg):
    suffix = reg["domain_suffix"]
    lines = [
        HEADER,
        "# Sourced by check.sh for auto-discovered app health checks.",
        "# Format: id|description|fqdn|type|container_name|container_port|health_path",
        "# type: static, static_dir, proxy, container",
        "# container_name/port: only for container services (direct Docker health check)",
        "# health_path: optional path for health checks (default: /)",
        "APP_SERVICES=(",
    ]
    for svc in reg["services"]:
        fqdn = f"{svc['name']}.{suffix}"
        stype = svc["type"]
        cname = svc.get("container_name", "")
        cport = svc.get("container_port", "")
        hpath = svc.get("health_path", "/")
        lines.append(f'  "{svc["name"]}|{svc["description"]}|{fqdn}|{stype}|{cname}|{cport}|{hpath}"')
    lines += [")", ""]
    path = os.path.join(REPO_ROOT, "ops", "status", "services.env")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    return path


def main():
    reg = load_registry()
    count = len(reg["services"])
    print(f"Loaded {count} services from services.yaml\n")
    print("Generating:")
    for gen in (generate_caddyfile, generate_caddy_compose, generate_services_env, update_mesh_hosts):
        path = gen(reg)
        print(f"  {os.path.relpath(path, REPO_ROOT)}")
    # Validate container services have mesh-only middleware.
    warnings = validate_container_middleware(reg)
    if warnings:
        print(f"\nSecurity validation FAILED:")
        for w in warnings:
            print(w)
        print(f"\n  Container services must apply the mesh-only Traefik middleware.")
        print(f"  Without it, services are accessible from the public internet via relay bypass.")
        print(f"  See: docs/operations/hosting-services.md")
        sys.exit(1)
    else:
        container_count = len([s for s in reg["services"] if s["type"] == "container"])
        if container_count:
            print(f"\nSecurity: {container_count} container service(s) verified — mesh-only middleware present.")

    print(f"\nNext steps:")
    print(f"  1. Review generated files")
    print(f"  2. Deploy Caddy: cd /opt/goat/serve && TRAEFIK_NETWORK=netbird_netbird docker compose up -d")
    print(f"  3. Deploy status: ansible-playbook ops/ansible/nethost-status.yml")
    print(f"\nNote: Services resolve via mesh dnsmasq only (no public DNS records).")


if __name__ == "__main__":
    main()
