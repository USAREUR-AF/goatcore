#!/usr/bin/env bash
# Block 68B build-image-karbon.sh — pre-baked Karbon 801 image build.
#
# Builds a raw IMG (Ubuntu 24.04 + cloud-init seed) for the karbon-mgmt
# hardware class. Karbon 801 procurement is inbound; this script is
# operator-runnable today against an x86 cloud-init VM as a stand-in.
#
# Spec:    docs/design/rapid-site-bringup.md §4
# Spike:   docs/project/block-68a-config-input-spike.md
#
# Status: SKELETON. Uses `mkosi` (https://github.com/systemd/mkosi) as
# the build engine — modern, well-maintained, native systemd-friendly,
# produces signed images. Alternative: `packer` with the qemu builder.
# Decision recorded here: mkosi over packer because (a) systemd-native
# matches the goat host shape, (b) no separate provisioner step needed
# beyond the mkosi.conf, (c) reproducible-build property comes for
# free per the Block 40 future.
#
# Builder-host requirements:
#   - x86_64 Linux (any distro with systemd ≥ 254 + mkosi ≥ 22)
#   - sudo (mkosi root-bind-mounts during build)
#   - 40 GB free disk
#   - Operator's offline-CA YubiKey for the final image signature
#
# Usage:
#   ./build-image-karbon.sh \
#     --bundle-tag bundle-vYYYYMMDD \
#     --output-dir /tmp/karbon-mgmt-vYYYYMMDD
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
# The image's install directories (the repo under $GOAT_HOST_OPT_DIR/repo, the
# state and log dirs first-boot.sh writes): the environment, else the tree's
# group_vars/all.yml, else /opt/goat and friends (lib-host-layout.sh).
# shellcheck source=ops/bootstrap/lib-host-layout.sh
. "$REPO_ROOT/ops/bootstrap/lib-host-layout.sh"
host_layout_load "$REPO_ROOT"

usage() {
  cat <<EOF
build-image-karbon.sh — Block 68 pre-baked Karbon image builder

Usage:
  $(basename "$0") --bundle-tag <tag> --output-dir <path>

Options:
  --bundle-tag <tag>   Bundle tag to build from (e.g. bundle-v20260506)
  --output-dir <path>  Where to write the image artifact + signature
EOF
  exit 1
}

BUNDLE_TAG=""
OUTPUT_DIR=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --bundle-tag) BUNDLE_TAG=$2; shift 2;;
    --output-dir) OUTPUT_DIR=$2; shift 2;;
    -h|--help) usage;;
    *) echo "unknown arg: $1" >&2; usage;;
  esac
done

[[ -n "$BUNDLE_TAG" && -n "$OUTPUT_DIR" ]] || usage
mkdir -p "$OUTPUT_DIR"

step() { echo ""; echo "=== $* ==="; }

command -v mkosi >/dev/null \
  || { echo "mkosi not installed; see https://github.com/systemd/mkosi" >&2; exit 1; }

# -- Step 1: snapshot repo at signed bundle tag --------------------------
step "Step 1: snapshot repo at $BUNDLE_TAG"
STAGE="$OUTPUT_DIR/stage"
rm -rf "$STAGE"
mkdir -p "$STAGE"
git -C "$REPO_ROOT" archive --format=tar "$BUNDLE_TAG" \
  | tar -x -C "$STAGE" -f -
# The unit and the script it starts name this build's layout.
host_layout_render "$STAGE/ops/bootstrap/first-boot/first-boot.service" \
  "$STAGE/ops/bootstrap/first-boot/first-boot.sh"

# -- Step 2: write mkosi.conf -------------------------------------------
step "Step 2: render mkosi.conf"
MKOSI_DIR="$OUTPUT_DIR/mkosi"
mkdir -p "$MKOSI_DIR/mkosi.extra$GOAT_HOST_OPT_DIR"
mkdir -p "$MKOSI_DIR/mkosi.extra/etc/systemd/system/multi-user.target.wants"

cp -a "$STAGE" "$MKOSI_DIR/mkosi.extra$GOAT_HOST_OPT_DIR/repo"
cp "$STAGE/ops/bootstrap/first-boot/first-boot.service" \
   "$MKOSI_DIR/mkosi.extra/etc/systemd/system/first-boot.service"
ln -sf /etc/systemd/system/first-boot.service \
   "$MKOSI_DIR/mkosi.extra/etc/systemd/system/multi-user.target.wants/first-boot.service"

cat > "$MKOSI_DIR/mkosi.conf" <<EOF
# Block 68 karbon-mgmt image — auto-generated by build-image-karbon.sh
[Distribution]
Distribution=ubuntu
Release=noble

[Output]
Format=disk
ImageId=karbon-mgmt
ImageVersion=$BUNDLE_TAG
SplitArtifacts=no

[Content]
Bootable=yes
Bootloader=systemd-boot
RootPassword=hashed:!  # locked; first-boot.service drives login
Packages=
    ansible
    ca-certificates
    cryptsetup
    curl
    docker.io
    docker-compose-plugin
    git
    jq
    openssl
    python3-pip
    sudo
    systemd-boot
    tpm2-tools
    yq
RemoveFiles=
    /var/cache/apt/archives
    /var/log/dpkg.log

[Validation]
SecureBoot=yes
EOF

# -- Step 3: invoke mkosi -----------------------------------------------
step "Step 3: mkosi build"
(cd "$MKOSI_DIR" && sudo mkosi build)

OUT_IMG=$(find "$MKOSI_DIR" -maxdepth 2 -name '*.raw' | head -1)
[[ -n "$OUT_IMG" ]] || { echo "mkosi did not produce a .raw image" >&2; exit 1; }

cp "$OUT_IMG" "$OUTPUT_DIR/karbon-mgmt-${BUNDLE_TAG}.img"
echo "  image: $OUTPUT_DIR/karbon-mgmt-${BUNDLE_TAG}.img"

# -- Step 4: sign with offline-CA YubiKey -------------------------------
step "Step 4: sign image with offline-CA YubiKey"
cat >&2 <<EOF
  TODO — Operator-fired signing step. Run on the operator workstation
  with the offline-CA YubiKey present:

    ssh-keygen -Y sign \\
      -f /dev/<yubikey-piv-identity> \\
      -n bootstrap-image \\
      "$OUTPUT_DIR/karbon-mgmt-${BUNDLE_TAG}.img" \\
    > "$OUTPUT_DIR/karbon-mgmt-${BUNDLE_TAG}.img.sig"

  See docs/operations/image-builder-host.md for the full ceremony.
EOF

step "build-image-karbon.sh complete"
