#!/usr/bin/env python3
"""backout_core — take ONE peering's admission out of our core router's access control.

Phase 10 admits a peering by splicing the fragment `goatbuilder federate apply` /
`goat federate apply` renders (`<work>/applied/ops/federation/acl/<them>-fragment.json5`)
into the core's ORG fragment and assembling the live configuration with
roles/goat-zenoh/files/acl-assemble.py. Backing that peering out is the inverse:
remove exactly the blocks that fragment added, assemble again with the same
assembler, and restart the router on the result.

WHAT BELONGS TO PARTNER P. The fragment is generated, so its ids are fixed by P:

  subjects  fed-P     cert_common_names ["fed.P.<us>.01"]           (P's edge, ADR 1157)
            fed-rp-P  cert_common_names ["fed.<us>.P.republisher.01"] (our republisher)
  rules     fed-w-P fed-w-interest-P fed-r-P fed-r-interest-P
            fed-rp-r-P fed-rp-r-interest-P fed-rp-w-P fed-rp-w-interest-P
  policies  the ones whose subjects are exactly ["fed-P"] or ["fed-rp-P"]
  comments  the GENERATED header block that names P's peering CN

A sovereign id may contain '-', so one partner's id set can contain another's id
(partner `interest-xab` owns `fed-r-interest-xab`, which is also partner `xab`'s
interest rule). Every other partner present in the fragment is found by its edge
subject, and the removal is REFUSED when any id it would take is also an id of a
partner that stays. Nothing is guessed: an id is removed only when it is P's alone.

WHAT IT PROVES BEFORE ANYTHING IS WRITTEN.
  * the live configuration equals assemble(seed, org): otherwise the live file holds
    something this tool cannot account for, and replacing it would drop that;
  * the candidate ORG fragment is the old one with whole lines removed and nothing
    added or reordered, and every removed line is inside a block owned by P;
  * the candidate live configuration is assemble(seed, candidate org), with the same
    assembler the core uses.

A core configured by roles/goat-zenoh from `zenoh_sovereign_peerings` carries P as
`sovereign-P*` ids instead. Those are the deployment's configuration, not a splice;
this tool reports them (`role_declared`) and removes nothing for them.

  backout_core.py plan --partner P --seed S --org O --live L --out-dir D [--us U]

writes D/org.candidate, D/live.candidate and D/plan.json and prints plan.json.
Exit 0 with a plan (possibly "absent"), 1 refused (plan.json says why), 2 usage.
It reads three files and writes only into D.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
import re
import sys
from pathlib import Path

FRAG_HDR = "##ACL-ORG-REGION "  # acl-assemble.py's section header
ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{1,15}$")
# The header words of a generated fragment: crates/goat-federation/src/render.rs
# GENERATED_MARKERS (today's `goat federate apply` and the `goatbuilder federate apply`
# form). test_backout_core.py reads that constant and fails when this list differs.
GENERATED_MARKERS = ("GENERATED by `goat federate apply`", "GENERATED by `goatbuilder federate apply`")


# The two lines `goatbuilder federate` admission puts around a partner's lines in each
# region of the org fragment: crates/goatbuilder/src/federate/admit.rs begin() and end(),
# matched trimmed, as admission matches them. test_backout_core.py reads admit.rs and
# fails when this text differs.
ADMISSION_MARKERS = ("      // BEGIN peering {them} (goatbuilder federate)", "      // END peering {them}")


def admission_blocks(lines, partner):
    """[(begin, end)] line indexes of each region's admission block for `partner`.
    A block that begins twice, never ends, or ends without beginning is refused."""
    begin, end = (m.replace("{them}", partner).strip() for m in ADMISSION_MARKERS)
    any_marker = re.compile("^(?:" + "|".join(
        re.escape(m.strip()).replace(re.escape("{them}"), r"(\S+)") for m in ADMISSION_MARKERS) + ")$")
    blocks, start, region = [], None, None
    for i, ln in enumerate(lines):
        other = any_marker.match(ln.strip())
        if start is not None and other and ln.strip() not in (begin, end):
            them = other.group(1) or other.group(2)
            raise ValueError(f"region {region}: the admission block for {partner} holds a marker line of "
                             f"partner {them} ({ln.strip()}); removing it would break {them}'s back-out. "
                             "Separate the two blocks by review.")
        if ln.startswith(FRAG_HDR):
            if start is not None:
                raise ValueError(f"region {region}: the admission block for {partner} begins and never ends")
            region = ln[len(FRAG_HDR):].strip()
        elif ln.strip() == begin:
            if start is not None:
                raise ValueError(f"region {region}: the admission block for {partner} begins twice without ending")
            start = i
        elif ln.strip() == end:
            if start is None:
                raise ValueError(f"region {region}: the admission block for {partner} ends without beginning")
            blocks.append((start, i))
            start = None
    if start is not None:
        raise ValueError(f"region {region}: the admission block for {partner} begins and never ends")
    return blocks


def is_generated(text: str) -> bool:
    return any(m in text for m in GENERATED_MARKERS)


def load_assembler():
    """The assembler the core itself uses, imported from the role, never copied."""
    here = Path(__file__).resolve()
    path = here.parents[2] / "ansible/roles/goat-zenoh/files/acl-assemble.py"
    spec = importlib.util.spec_from_file_location("acl_assemble", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def rule_ids(p: str) -> set:
    return {f"fed-w-{p}", f"fed-w-interest-{p}", f"fed-r-{p}", f"fed-r-interest-{p}",
            f"fed-rp-r-{p}", f"fed-rp-r-interest-{p}", f"fed-rp-w-{p}", f"fed-rp-w-interest-{p}"}


def subject_ids(p: str) -> set:
    return {f"fed-{p}", f"fed-rp-{p}"}


def edge_cn(p: str, us: str) -> str:
    return f"fed.{p}.{us}.01"


def republisher_cn(us: str, p: str) -> str:
    return f"fed.{us}.{p}.republisher.01"


_STR = re.compile(r'"([^"\\]*)"')


def _field(text: str, name: str):
    """The first `name: "x"` or `name: ["a", "b"]` in a block's text."""
    m = re.search(r"\b" + re.escape(name) + r"\s*:\s*(\[[^\]]*\]|\"[^\"]*\")", text)
    if not m:
        return None
    v = m.group(1)
    if v.startswith("["):
        return _STR.findall(v)
    return v[1:-1]


class Block:
    """One `{ ... },` object in a region, by line index, or one loose line."""

    def __init__(self, region, start, end, lines):
        self.region = region
        self.start = start          # first line index, inclusive
        self.end = end              # last line index, inclusive
        self.text = "".join(lines[start:end + 1])
        self.is_object = self.text.lstrip().startswith("{")
        self.id = _field(self.text, "id") if self.is_object else None
        self.cns = _field(self.text, "cert_common_names") if self.is_object else None
        self.subjects = _field(self.text, "subjects") if self.is_object else None
        self.rules = _field(self.text, "rules") if self.is_object else None


def parse(lines):
    """Split an ORG fragment into blocks. Lines before the first region header and
    the headers themselves are never part of a block and are never removed."""
    blocks = []
    region = None
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith(FRAG_HDR):
            region = ln[len(FRAG_HDR):].strip()
            i += 1
            continue
        if region is None:
            i += 1
            continue
        if ln.lstrip().startswith("{"):
            depth, j = 0, i
            while j < len(lines):
                depth += lines[j].count("{") - lines[j].count("}")
                if depth <= 0:
                    break
                j += 1
            if depth > 0:
                raise ValueError(f"line {i + 1}: an object in region '{region}' never closes")
            blocks.append(Block(region, i, j, lines))
            i = j + 1
            continue
        if ln.lstrip().startswith("//"):
            j = i
            # A GENERATED line starts a new block: the header of the next fragment never
            # merges with the comment that ends the previous one.
            while j + 1 < len(lines) and lines[j + 1].lstrip().startswith("//") \
                    and not is_generated(lines[j + 1]):
                j += 1
            blocks.append(Block(region, i, j, lines))
            i = j + 1
            continue
        blocks.append(Block(region, i, i, lines))
        i += 1
    return blocks


def partners_present(blocks):
    """{partner: our id} for every edge subject `fed-X` whose CN is `fed.X.<us>.01`."""
    out = {}
    for b in blocks:
        if b.region != "subjects" or not b.id or not b.id.startswith("fed-") or not b.cns:
            continue
        x = b.id[len("fed-"):]
        for cn in b.cns:
            parts = cn.split(".")
            if len(parts) == 4 and parts[0] == "fed" and parts[1] == x and parts[3] == "01":
                out[x] = parts[2]
    return out


def plan(org_text: str, partner: str, us: str | None = None):
    """What removing `partner` takes out of `org_text`: (candidate text, report dict).
    Raises ValueError with the refusal when the removal is not provably P's alone."""
    if not ID_RE.match(partner):
        raise ValueError(f"'{partner}' is not a sovereign id (2-16 characters of a-z0-9-)")
    lines = org_text.splitlines(keepends=True)
    blocks = parse(lines)
    present = partners_present(blocks)
    if partner in present:
        if us and present[partner] != us:
            raise ValueError(f"fed-{partner}'s CN names us as '{present[partner]}', not '{us}'")
        us = present[partner]
    others = {x: u for x, u in present.items() if x != partner}

    mine_rules, mine_subjects = rule_ids(partner), subject_ids(partner)
    for x in others:
        clash = (mine_rules | mine_subjects) & (rule_ids(x) | subject_ids(x))
        if clash:
            raise ValueError(
                f"partner '{partner}' and partner '{x}' share the ids {sorted(clash)}: removing "
                f"'{partner}' could take '{x}''s admission with it. Remove these blocks by review.")

    owned_cns = set()
    if us:
        owned_cns = {edge_cn(partner, us), republisher_cn(us, partner)}
    take = []
    taken = {"rules": [], "subjects": [], "policies": [], "comments": 0}
    rules_kept_refs = set()
    for b in blocks:
        if not b.is_object:
            continue
        if b.region == "policies" and b.subjects is not None:
            if set(b.subjects) & mine_subjects:
                if not set(b.subjects) <= mine_subjects:
                    raise ValueError(f"a policy binds {b.subjects}: it mixes '{partner}' with another subject")
                foreign = [r for r in (b.rules or []) if r not in mine_rules]
                if foreign:
                    raise ValueError(f"a policy for {b.subjects} binds rules that are not '{partner}''s: {foreign}")
                take.append(b)
                taken["policies"].append(b.subjects[0])
            else:
                rules_kept_refs.update(b.rules or [])
    for b in blocks:
        if not b.is_object or not b.id:
            continue
        if b.region == "write-rules" and b.id in mine_rules:
            if b.id in rules_kept_refs:
                raise ValueError(f"rule {b.id} is bound by a policy that stays")
            take.append(b)
            taken["rules"].append(b.id)
        elif b.region == "subjects" and b.id in mine_subjects:
            if owned_cns and b.cns and not set(b.cns) <= owned_cns:
                raise ValueError(f"subject {b.id} carries {b.cns}, not '{partner}''s derived names")
            take.append(b)
            taken["subjects"].append(b.id)
    if owned_cns:
        cn = edge_cn(partner, us)
        for b in blocks:
            if not b.is_object and is_generated(b.text) and cn in b.text:
                take.append(b)
                taken["comments"] += 1

    drop = set()
    for b in take:
        drop.update(range(b.start, b.end + 1))
    # Admission's block for P goes whole, its two marker lines with it, so the fragment
    # is again what it was before admission. Every object inside must be P's (already
    # selected above); a blank or comment line inside belongs to the block.
    markers = 0
    for begin, end in admission_blocks(lines, partner):
        for b in blocks:
            if b.is_object and begin < b.start <= end and not set(range(b.start, b.end + 1)) <= drop:
                raise ValueError(f"the admission block for {partner} holds lines that are not {partner}'s: "
                                 + b.text.strip().splitlines()[0])
        drop.update(range(begin, end + 1))
        markers += 2
    taken["markers"] = markers
    for i in drop:
        if lines[i].startswith(FRAG_HDR):
            raise ValueError("internal: a region header was selected for removal")
    candidate = "".join(ln for i, ln in enumerate(lines) if i not in drop)
    report = {
        "partner": partner,
        "us": us or "",
        "others": sorted(others),
        "removed": {k: (sorted(v) if isinstance(v, list) else v) for k, v in taken.items()},
        "removed_lines": len(drop),
        "absent": not drop,
    }
    return candidate, report


def is_line_subsequence(small: str, big: str) -> bool:
    """`small` is `big` with whole lines removed, in order, nothing added."""
    it = iter(big.splitlines(keepends=True))
    return all(any(a == b for b in it) for a in small.splitlines(keepends=True))


def sha256(s: str) -> str:
    return "sha256:" + hashlib.sha256(s.encode()).hexdigest()


def assemble_text(asm, seed_path: str, org_text: str, out_dir: str, name: str) -> str:
    org_path = os.path.join(out_dir, name + ".org")
    out_path = os.path.join(out_dir, name)
    with open(org_path, "w", encoding="utf-8") as f:
        f.write(org_text)
    import contextlib
    import io
    with contextlib.redirect_stdout(io.StringIO()):
        asm.assemble(seed_path, org_path, out_path)
    os.unlink(org_path)
    with open(out_path, encoding="utf-8") as f:
        return f.read()


def run_plan(partner, seed, org, live, out_dir, us=None):
    os.makedirs(out_dir, exist_ok=True)
    result = {"schema": "goat-federation-backout-core/v1", "partner": partner, "refused": None}

    def read(path):
        with open(path, encoding="utf-8") as f:
            return f.read()

    live_text = read(live)
    result["role_declared"] = bool(re.search(r'id:\s*"sovereign-' + re.escape(partner) + r'"', live_text))
    try:
        org_text = read(org)
        seed_text = read(seed)
    except OSError as e:
        result["refused"] = f"cannot read the seed or the org fragment: {e}"
        return result, 1
    del seed_text
    asm = load_assembler()
    try:
        current = assemble_text(asm, seed, org_text, out_dir, "live.reassembled")
    except SystemExit as e:
        result["refused"] = f"the assembler refused the current seed and org fragment: {e}"
        return result, 1
    os.unlink(os.path.join(out_dir, "live.reassembled"))
    result["live_is_seed_plus_org"] = current == live_text
    if current != live_text:
        result["refused"] = ("the live configuration is not assemble(seed, org fragment): it holds something "
                             "this tool cannot account for, so replacing it could drop more than this peering. "
                             "Reconcile the live file with the seed and the org fragment first.")
        return result, 1
    try:
        candidate, rep = plan(org_text, partner, us)
    except ValueError as e:
        result["refused"] = str(e)
        return result, 1
    result.update(rep)
    if not is_line_subsequence(candidate, org_text):
        result["refused"] = "internal: the candidate is not the old fragment with lines removed"
        return result, 1
    live_candidate = assemble_text(asm, seed, candidate, out_dir, "live.candidate")
    with open(os.path.join(out_dir, "org.candidate"), "w", encoding="utf-8") as f:
        f.write(candidate)
    if not is_line_subsequence(live_candidate, live_text):
        result["refused"] = "internal: the candidate live configuration adds lines"
        return result, 1
    result["live_removed_lines"] = len(live_text.splitlines()) - len(live_candidate.splitlines())
    result["live_sha256"] = sha256(live_text)
    result["candidate_sha256"] = sha256(live_candidate)
    result["org_candidate_sha256"] = sha256(candidate)
    return result, 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("plan")
    p.add_argument("--partner", required=True)
    p.add_argument("--seed", required=True)
    p.add_argument("--org", required=True)
    p.add_argument("--live", required=True)
    p.add_argument("--out-dir", required=True)
    p.add_argument("--us")
    a = ap.parse_args(argv)
    try:
        result, rc = run_plan(a.partner, a.seed, a.org, a.live, a.out_dir, a.us)
    except OSError as e:
        result, rc = {"schema": "goat-federation-backout-core/v1", "partner": a.partner,
                      "refused": f"cannot read an input: {e}"}, 1
    with open(os.path.join(a.out_dir, "plan.json"), "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, sort_keys=True)
        f.write("\n")
    print(json.dumps(result, sort_keys=True))
    return rc


if __name__ == "__main__":
    sys.exit(main())
