"""backout_core removes one peering's core admission and nothing of another's.

The fragments below are written in the exact shape crates/goat-federation/src/render.rs
emits for `<them>-fragment.json5`, and the seed is the acl-assemble fixture's, so the
test exercises the same splice the core runs.
"""
import importlib.util
import json
import os
import re
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
FIXTURE = REPO / "ops/ansible/roles/goat-zenoh/tests/acl-assemble/fixture-live.json5"


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


bc = load("backout_core", HERE / "backout_core.py")
asm = load("acl_assemble", REPO / "ops/ansible/roles/goat-zenoh/files/acl-assemble.py")


def fragment(us, them, ingress=True, egress=True, republishes=True):
    """render.rs, section 5, for one partner."""
    a = []
    a.append("// GENERATED by `goat federate apply` from the composed agreement\n")
    a.append(f"// sha256:{them * 8}\n//\n")
    a.append("// Subject is the peering CN, DERIVED (spec section 3.1) and never agreed in\n"
             f"// prose: fed.{them}.{us}.01. The access layer matches this name and cannot see which\n"
             "// authority issued the certificate, which is why the far side's CA\n"
             "// belongs only in the edge's own trust store and never in a core router's.\n")
    a.append("##ACL-ORG-REGION storages\n")
    a.append("##ACL-ORG-REGION write-rules\n")

    def rule(i, messages, flow, keys):
        a.append("      {\n")
        a.append(f'        id: "{i}",\n')
        a.append(f"        messages: [{messages}],\n")
        a.append(f'        flows: ["{flow}"],\n')
        a.append('        permission: "allow",\n')
        a.append("        key_exprs: [\n")
        for k in keys:
            a.append(f'          "{k}",\n')
        a.append("        ],\n      },\n")

    inn, out, rel = [f"from/{them}/**"], [f"from/{us}/REL-ALL/**"], ["release/REL-ALL/**"]
    if ingress:
        rule(f"fed-w-{them}", '"put", "delete"', "ingress", inn)
        rule(f"fed-w-interest-{them}", '"declare_subscriber", "query", "declare_queryable"', "egress", inn)
    if egress:
        rule(f"fed-r-{them}", '"put", "delete", "declare_subscriber", "query", "reply"', "egress", out)
        rule(f"fed-r-interest-{them}", '"declare_subscriber", "query", "declare_queryable"', "ingress", out)
    rp = [f"fed-rp-r-{them}", f"fed-rp-r-interest-{them}", f"fed-rp-w-{them}", f"fed-rp-w-interest-{them}"]
    rep = egress and republishes
    if rep:
        rule(rp[0], '"put", "delete", "declare_subscriber", "query", "reply"', "egress", rel)
        rule(rp[1], '"declare_subscriber", "query", "declare_queryable"', "ingress", rel)
        rule(rp[2], '"put", "delete"', "ingress", out)
        rule(rp[3], '"declare_subscriber", "query", "declare_queryable"', "egress", out)
    a.append("##ACL-ORG-REGION subjects\n")
    a.append("      {\n")
    a.append(f'        id: "fed-{them}",\n')
    a.append(f'        cert_common_names: ["fed.{them}.{us}.01"],\n      }},\n')
    if rep:
        a.append("      {\n")
        a.append(f'        id: "fed-rp-{them}",\n')
        a.append(f'        cert_common_names: ["fed.{us}.{them}.republisher.01"],\n      }},\n')
    a.append("##ACL-ORG-REGION policies\n")
    bound = []
    if ingress:
        bound += [f"fed-w-{them}", f"fed-w-interest-{them}"]
    if egress:
        bound += [f"fed-r-{them}", f"fed-r-interest-{them}"]
    q = ", ".join(f'"{r}"' for r in bound)
    a.append(f'      {{ rules: [{q}], subjects: ["fed-{them}"] }},\n')
    if rep:
        q = ", ".join(f'"{r}"' for r in rp)
        a.append(f'      {{ rules: [{q}], subjects: ["fed-rp-{them}"] }},\n')
    return "".join(a)


class Fixture:
    def __init__(self, *frags):
        # Removed with the fixture (each test's local `fx`), and at exit at the latest.
        self._tmp = tempfile.TemporaryDirectory(prefix="backout-core-")
        self.dir = self._tmp.name
        self.seed = os.path.join(self.dir, "seed.json5")
        vendor = os.path.join(self.dir, "vendor.org")
        import contextlib
        import io
        with contextlib.redirect_stdout(io.StringIO()):
            asm.extract(str(FIXTURE), self.seed, vendor)
        with open(vendor, encoding="utf-8") as f:
            self.vendor = f.read()
        self.org = os.path.join(self.dir, "org.json5")
        self.live = os.path.join(self.dir, "live.json5")
        self.write_org(self.vendor + "".join(frags))

    def write_org(self, text):
        with open(self.org, "w", encoding="utf-8") as f:
            f.write(text)
        self.assemble(self.org, self.live)

    def assemble(self, org, out):
        import contextlib
        import io
        with contextlib.redirect_stdout(io.StringIO()):
            asm.assemble(self.seed, org, out)

    def text(self, path):
        with open(path, encoding="utf-8") as f:
            return f.read()

    def plan(self, partner, us=None):
        out = os.path.join(self.dir, "out-" + partner)
        return bc.run_plan(partner, self.seed, self.org, self.live, out, us) + (out,)


class OnePeeringOfTwo(unittest.TestCase):
    def test_backing_out_one_leaves_the_other_byte_for_byte(self):
        fx = Fixture(fragment("xaa", "xab"), fragment("xaa", "xac"))
        result, rc, out = fx.plan("xac")
        self.assertEqual(rc, 0, result)
        self.assertEqual(result["others"], ["xab"])
        self.assertEqual(sorted(result["removed"]["subjects"]), ["fed-rp-xac", "fed-xac"])
        self.assertEqual(len(result["removed"]["rules"]), 8)
        self.assertEqual(len(result["removed"]["policies"]), 2)
        self.assertEqual(result["removed"]["comments"], 1)
        # What stays is exactly the core admitted with xab alone.
        want = os.path.join(fx.dir, "want.json5")
        alone = os.path.join(fx.dir, "alone.org")
        with open(alone, "w", encoding="utf-8") as f:
            f.write(fx.vendor + fragment("xaa", "xab"))
        fx.assemble(alone, want)
        self.assertEqual(fx.text(os.path.join(out, "live.candidate")), fx.text(want))
        cand = fx.text(os.path.join(out, "org.candidate"))
        self.assertIn('id: "fed-xab"', cand)
        self.assertNotIn("xac", cand)
        # Every line of xab's fragment survives, in order.
        self.assertTrue(bc.is_line_subsequence(fragment("xaa", "xab"), cand))

    def test_the_first_peering_can_go_as_well_as_the_last(self):
        fx = Fixture(fragment("xaa", "xab"), fragment("xaa", "xac"))
        result, rc, out = fx.plan("xab")
        self.assertEqual(rc, 0, result)
        cand = fx.text(os.path.join(out, "org.candidate"))
        self.assertNotIn("xab", cand)
        # xac's fragment from its first region header on survives in order (its leading
        # comment sat in xab's policies region and is not part of this comparison).
        self.assertTrue(bc.is_line_subsequence("##" + fragment("xaa", "xac").split("##", 1)[1], cand))
        for line in fragment("xaa", "xac").splitlines():
            if line.startswith("      ") or line.startswith("        "):
                self.assertIn(line, cand)

    def test_vendor_blocks_are_never_touched(self):
        fx = Fixture(fragment("xaa", "xab"))
        result, rc, out = fx.plan("xab")
        self.assertEqual(rc, 0, result)
        cand = fx.text(os.path.join(out, "org.candidate"))
        for line in fx.vendor.splitlines():
            self.assertIn(line, cand)

    def test_twice_is_absent_the_second_time(self):
        fx = Fixture(fragment("xaa", "xab"), fragment("xaa", "xac"))
        result, rc, out = fx.plan("xac")
        fx.write_org(fx.text(os.path.join(out, "org.candidate")))
        again, rc2, out2 = fx.plan("xac")
        self.assertEqual(rc2, 0, again)
        self.assertTrue(again["absent"])
        self.assertEqual(again["removed_lines"], 0)
        self.assertEqual(again["candidate_sha256"], again["live_sha256"])

    def test_a_partner_never_admitted_is_absent(self):
        fx = Fixture(fragment("xaa", "xab"))
        result, rc, _ = fx.plan("xad", us="xaa")
        self.assertEqual(rc, 0, result)
        self.assertTrue(result["absent"])

    def test_a_send_only_peering_without_a_republisher(self):
        fx = Fixture(fragment("xaa", "xab"), fragment("xaa", "xac", egress=False))
        result, rc, out = fx.plan("xac")
        self.assertEqual(rc, 0, result)
        self.assertEqual(result["removed"]["subjects"], ["fed-xac"])
        self.assertNotIn("xac", fx.text(os.path.join(out, "org.candidate")))

    def test_a_recognition_only_neighbor_keeps_its_trailing_comment(self):
        # xab grants nothing, so its policies region ends in a comment, right before
        # xac's GENERATED header: removing xac must not take xab's comment with it.
        quiet = fragment("xaa", "xab").split("##ACL-ORG-REGION write-rules", 1)[0] + (
            "##ACL-ORG-REGION write-rules\n##ACL-ORG-REGION subjects\n##ACL-ORG-REGION policies\n"
            "      // NO RULES, NO SUBJECT, NO POLICY. This agreement grants no access in\n")
        fx = Fixture(quiet, fragment("xaa", "xac"))
        result, rc, out = fx.plan("xac")
        self.assertEqual(rc, 0, result)
        self.assertIn("NO RULES, NO SUBJECT", fx.text(os.path.join(out, "org.candidate")))

    def test_a_prefix_of_another_id_is_not_a_match(self):
        # xa is a valid id and a prefix of xab: nothing of xab may go with it.
        fx = Fixture(fragment("xaa", "xab"), fragment("xaa", "xa"))
        result, rc, out = fx.plan("xa")
        self.assertEqual(rc, 0, result)
        cand = fx.text(os.path.join(out, "org.candidate"))
        for i in bc.rule_ids("xab") | bc.subject_ids("xab"):
            self.assertIn(f'"{i}"', cand)
        for i in bc.rule_ids("xa") | bc.subject_ids("xa"):
            self.assertNotIn(f'"{i}"', cand)


class Header(unittest.TestCase):
    def test_the_markers_are_render_rs_constants(self):
        src = (REPO / "crates/goat-federation/src/render.rs").read_text()
        by = re.search(r'pub const GENERATED_BY: &str = "([^"]+)";', src).group(1)
        rest = re.search(r'pub const GENERATED_MARKERS: &\[&str\] = &\[GENERATED_BY, ([^\]]*)\];', src).group(1)
        markers = (by,) + tuple(re.findall(r'"([^"]+)"', rest))
        self.assertEqual(markers, bc.GENERATED_MARKERS)

    def test_a_goatbuilder_worded_fragment_is_still_recognized(self):
        frag = fragment("xaa", "xac").replace("`goat federate apply`", "`goatbuilder federate apply`")
        fx = Fixture(fragment("xaa", "xab"), frag)
        result, rc, out = fx.plan("xac")
        self.assertEqual(rc, 0, result)
        self.assertEqual(result["removed"]["comments"], 1)
        self.assertNotIn("xac", fx.text(os.path.join(out, "org.candidate")))


class Refusals(unittest.TestCase):
    def test_overlapping_ids_between_two_partners_refuse(self):
        # `interest-xab` owns fed-r-interest-xab, which is also xab's interest rule.
        fx = Fixture(fragment("xaa", "xab"), fragment("xaa", "interest-xab"))
        result, rc, _ = fx.plan("interest-xab")
        self.assertEqual(rc, 1)
        self.assertIn("share the ids", result["refused"])
        result, rc, _ = fx.plan("xab")
        self.assertEqual(rc, 1)

    def test_a_live_file_that_is_not_seed_plus_org_refuses(self):
        fx = Fixture(fragment("xaa", "xab"), fragment("xaa", "xac"))
        with open(fx.live, "a", encoding="utf-8") as f:
            f.write("// edited by hand\n")
        result, rc, _ = fx.plan("xac")
        self.assertEqual(rc, 1)
        self.assertFalse(result["live_is_seed_plus_org"])

    def test_a_policy_mixing_partners_refuses(self):
        frag = fragment("xaa", "xac").replace('subjects: ["fed-xac"]', 'subjects: ["fed-xac", "fed-xab"]')
        fx = Fixture(fragment("xaa", "xab"), frag)
        result, rc, _ = fx.plan("xac")
        self.assertEqual(rc, 1)
        self.assertIn("mixes", result["refused"])

    def test_a_rule_another_policy_uses_refuses(self):
        frag = fragment("xaa", "xab").replace('rules: ["fed-w-xab"', 'rules: ["fed-w-xac", "fed-w-xab"')
        fx = Fixture(frag, fragment("xaa", "xac"))
        result, rc, _ = fx.plan("xac")
        self.assertEqual(rc, 1)

    def test_a_role_declared_core_is_reported(self):
        fx = Fixture(fragment("xaa", "xab"))
        with open(fx.live, "a", encoding="utf-8") as f:
            f.write('      { id: "sovereign-xac", cert_common_names: ["x"] },\n')
        result, rc, _ = fx.plan("xac", us="xaa")
        self.assertTrue(result["role_declared"])

    def test_a_bad_id_is_refused(self):
        with self.assertRaises(ValueError):
            bc.plan("", "X/../", None)


class Cleanup(unittest.TestCase):
    def test_a_fixture_leaves_no_directory_behind(self):
        # Each test builds a Fixture; its working directory must go with it, or
        # every run leaves one backout-core-* directory per test in the temp dir.
        fx = Fixture(fragment("xaa", "xab"))
        d = fx.dir
        self.assertTrue(os.path.isdir(d))
        del fx
        self.assertFalse(os.path.exists(d), d)


class Cli(unittest.TestCase):
    def test_the_command_line_writes_its_plan(self):
        fx = Fixture(fragment("xaa", "xab"), fragment("xaa", "xac"))
        out = os.path.join(fx.dir, "cli")
        p = subprocess.run([sys.executable, str(HERE / "backout_core.py"), "plan", "--partner", "xac",
                            "--seed", fx.seed, "--org", fx.org, "--live", fx.live, "--out-dir", out],
                           capture_output=True, text=True, check=False)
        self.assertEqual(p.returncode, 0, p.stderr)
        with open(os.path.join(out, "plan.json"), encoding="utf-8") as f:
            self.assertEqual(json.load(f)["partner"], "xac")
        self.assertTrue(os.path.exists(os.path.join(out, "live.candidate")))


if __name__ == "__main__":
    unittest.main()
