// ProbeReport is what each probe POSTs to the collector every cycle.
type ProbeReport struct {
	PeerID    string             `json:"peer_id"`
	PeerName  string             `json:"peer_name"`
	PeerIP    string             `json:"peer_ip"`
	Timestamp time.Time          `json:"timestamp"`
	Network   NetworkFingerprint `json:"network"`
	Netbird   NetbirdHealth      `json:"netbird"`
	Peers     []PeerMeasurement  `json:"peers"`
	// Block 61 (snitch v2 — F-042 closed loop). Per-cycle visibility into
	// relay-side state that snitch was blind to before. Drove from the
	// review: the bench had silently been WS-only for weeks
	// because no probe asserted transport. Each entry == one configured
	// relay endpoint.
	Relays []RelayHealth `json:"relays,omitempty"`
	// MTU is filled at probe boot only (one-shot path-MTU detection per
	// interface; doesn't change between cycles unless interface flips).
	MTU *MTUInfo `json:"mtu,omitempty"`
	// RaceDialer counts transport outcomes parsed from the local netbird
	// daemon log over the report window. Catches transport thrashing.
	RaceDialer *RaceDialerCounters `json:"race_dialer,omitempty"`
	// CycleBudget records this cycle's measured runtime + whether any
	// sub-step was skipped because of the soft budget cap.
	CycleBudget *CycleBudgetInfo `json:"cycle_budget,omitempty"`
	// SelfMetrics is the probe's self-instrumentation: how much network
	// load the probe itself generated this cycle, and how it's behaving
	// (cycles completed/skipped, current policy in effect, kill-switch
	// status). Lets operators monitor probe load fleet-wide and flip
	// policies with confidence. Always emitted (zero-cost).
	SelfMetrics *ProbeSelfMetrics `json:"self_metrics,omitempty"`
}

// ProbePolicy is the operator-controlled probe-load policy. Pulled from
// the collector once per cycle; defaults to PolicyDefault if the
// collector is unreachable. Local kill switch (env var SNITCH_PROBE_DISABLED)
// supersedes the collector's policy → forces PolicyOff regardless.
type ProbePolicy struct {
	Mode      string    `json:"mode"`             // "off" | "minimal" | "default" | "focused-research"
	Reason    string    `json:"reason,omitempty"` // operator note
	SetBy     string    `json:"set_by,omitempty"` // operator identity / "auto"
	SetAt     time.Time `json:"set_at"`
	ExpiresAt time.Time `json:"expires_at,omitempty"` // zero = no expiry; probe auto-reverts to "default" at this time
}

const (
	// PolicyOff: probe loop sleeps every cycle. Heartbeat report only
	// (peer ID + timestamp + self-metrics) so the collector knows the
	// peer is alive. Use when probes need to be silenced fleet-wide
	// (operational disruption, classified mission window, etc.).
	PolicyOff = "off"

	// PolicyMinimal: peer ICMP pings + ss-counts only. No relay TCP
	// reachability probe, no TLS cert probe, no MTU probe, no
	// race-dialer journalctl read. Reduces probe load to ~10% of
	// default while keeping basic mesh-health visibility.
	PolicyMinimal = "minimal"

	// PolicyDefault: normal probe surface (Block 61 — transport assert,
	// TCP reach, TLS cached 1h, MTU on iface change, race-dialer 5min
	// window). The do-no-harm posture is the default operating mode.
	PolicyDefault = "default"

	// PolicyFocusedResearch: full surface, time-bounded. Bypasses the
	// 1h TLS cache (probes every cycle); forces network-fingerprint
	// refresh; runs MTU every cycle. Operator sets ExpiresAt to a
	// short window (e.g. 10 minutes) for deep network-health snapshots.
	// Auto-reverts at expiry; manually abortable by setting policy
	// back to default with a fresh SetAt.
	PolicyFocusedResearch = "focused-research"
)

// ProbeSelfMetrics is the probe's self-instrumentation. Emitted on
// every report so operators can monitor probe load fleet-wide. The
// byte estimates are intentionally rough — they cover the dominant
// probe egress (TCP-connect probes, TLS handshakes, throughput
// samples); inbound is the report POST itself + cert-chain bytes.
//
// "Cumulative" counters reset on probe-process restart (operators
// reading these should rate them with `KillSwitchActive` to detect
// restarts).
type ProbeSelfMetrics struct {
	PolicyMode       string    `json:"policy_mode"`                 // policy in effect this cycle
	PolicyExpiresAt  time.Time `json:"policy_expires_at,omitempty"` // when the current policy auto-reverts
	PolicySource     string    `json:"policy_source"`               // "collector" | "kill-switch-env" | "fallback-cached" | "fallback-default"
	KillSwitchActive bool      `json:"kill_switch_active"`          // SNITCH_PROBE_DISABLED env var present

	BytesOutEstimate int64 `json:"bytes_out_estimate"` // bytes generated by probe sub-steps this cycle
	BytesInEstimate  int64 `json:"bytes_in_estimate"`  // bytes received from probe sub-steps this cycle (cert chains, etc.)
	CyclesCompleted  int64 `json:"cycles_completed"`   // cumulative since probe boot
	CyclesSkipped    int64 `json:"cycles_skipped"`     // cumulative skipped (off mode + budget overruns)
	RelayProbesRun   int64 `json:"relay_probes_run"`   // cumulative
	TLSHandshakes    int64 `json:"tls_handshakes"`     // cumulative — load on relays' TLS listeners
	TCPConnects      int64 `json:"tcp_connects"`       // cumulative — load on relays' TCP accept path
}

// RelayHealth captures everything the snitch probe can learn about ONE
// configured relay endpoint without help from the relay itself.
//
// Drove from F-016 / F-021 / F-041 / F-042: the bench env's daemon was
// silently on WebSocket because (a) firewall layers blocked UDP, (b) the
// race-dialer is non-deterministic, (c) the goat-relay binary's QUIC
// listener didn't advertise the netbird ALPN string. None of these were
// surfaced by snitch before. With this struct, fleet-wide WS-vs-QUIC
// distribution is queryable; firewall drift catches itself; cert expiry
// gets a 7-day-warning surface.
type RelayHealth struct {
	URL              string `json:"url"`                          // e.g. "rels://relay.example:33073"
	Endpoint         string `json:"endpoint"`                     // host:port
	Transport        string `json:"transport"`                    // "quic" | "ws" | "none"
	UDPReachable     bool   `json:"udp_reachable"`                // nc -zu on UDP/<port>
	TCPReachable     bool   `json:"tcp_reachable"`                // nc -z on TCP/<port>
	TLSDaysUntil     int    `json:"tls_days_until_expiry"`        // ceil((NotAfter - now)/24h); -1 on probe failure
	TLSCertSubject   string `json:"tls_cert_subject,omitempty"`   // CN= for sanity checking
	GoatRelayVersion string `json:"goat_relay_version,omitempty"` // best-effort; populated if the relay surfaces it
}

// MTUInfo is the result of a one-shot path-MTU probe.
type MTUInfo struct {
	Interface string `json:"interface"` // probe's own interface
	PathMTU   int    `json:"path_mtu"`  // max payload that survives without fragmentation
	OK1500    bool   `json:"ok_1500"`   // whether full Ethernet MTU works
	OK1280    bool   `json:"ok_1280"`   // whether the WireGuard floor (1280) works
}

// RaceDialerCounters are the transport-outcome counters parsed from the
// netbird daemon's client.log over the report window.
type RaceDialerCounters struct {
	WindowSeconds int `json:"window_s"` // size of the window we counted over
	QUICSuccess   int `json:"quic_success"`
	WSSuccess     int `json:"ws_success"`
	QUICFailure   int `json:"quic_failure"` // parsed "failed to dial via quic" entries
	WSFailure     int `json:"ws_failure"`
}

// CycleBudgetInfo records this cycle's runtime + sub-step skip count.
type CycleBudgetInfo struct {
	BudgetMs   int  `json:"budget_ms"`        // soft cap configured for this run
	ActualMs   int  `json:"actual_ms"`        // total wall-clock for the cycle
	Skipped    int  `json:"skipped_substeps"` // count of sub-steps that opted out due to budget
	OverBudget bool `json:"over_budget"`      // ActualMs > BudgetMs
}

