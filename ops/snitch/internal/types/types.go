// MarshalJSON emits in_satlink_range and, for existing API clients, the same
// value under compat.SatlinkRangeJSONKey.
func (r SatlinkProbeResult) MarshalJSON() ([]byte, error) {
	type plain SatlinkProbeResult
	b, err := json.Marshal(plain(r))
	if err != nil {
		return nil, err
	}
	return withCompatRangeKey(b, r.InSatlinkRange), nil
}

// MarshalJSON emits in_satlink_range and, for existing API clients, the same
// value under compat.SatlinkRangeJSONKey.
func (e SatlinkPopEvent) MarshalJSON() ([]byte, error) {
	type plain SatlinkPopEvent
	b, err := json.Marshal(plain(e))
	if err != nil {
		return nil, err
	}
	return withCompatRangeKey(b, e.InSatlinkRange), nil
}

// withCompatRangeKey appends the compat range key to a marshaled non-empty
// JSON object. Where the compat key is the same string as the current key the
// object already carries it and is returned unchanged.
func withCompatRangeKey(obj []byte, v bool) []byte {
	if bytes.Contains(obj, []byte(`"`+compat.SatlinkRangeJSONKey+`":`)) {
		return obj
	}
	out := append([]byte{}, obj[:len(obj)-1]...)
	out = append(out, `,"`+compat.SatlinkRangeJSONKey+`":`...)
	out = strconv.AppendBool(out, v)
	return append(out, '}')
}
