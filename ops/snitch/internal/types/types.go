// PeerMeasurement is a single probe→target measurement.
type PeerMeasurement struct {
	PeerID    string  `json:"peer_id"`
	PeerName  string  `json:"peer_name"`
	PeerIP    string  `json:"peer_ip"`
	Connected bool    `json:"connected"`
	Direct    bool    `json:"direct"`               // true = P2P, false = relayed
	LatencyMs float64 `json:"latency_ms,omitempty"` // average ICMP RTT
	JitterMs  float64 `json:"jitter_ms,omitempty"`
	LossPct   float64 `json:"loss_pct,omitempty"`
	P50Ms     float64 `json:"p50_ms,omitempty"`
	P95Ms     float64 `json:"p95_ms,omitempty"`
	Samples   int     `json:"samples,omitempty"`

	// Transport quality — the signals ICMP cannot see. Added
	// after two severe defects went undetected by a monitor
	// measuring only latency, jitter and loss. Both are optional: a link
	// with no TCP carried has no TCP quality, and a gap that reads as a gap
	// is better than a zero that reads as health.
	Transport *TransportQuality `json:"transport,omitempty"`
	Reorder   *ReorderResult    `json:"reorder,omitempty"`
}

// TransportQuality is kernel TCP state for connections already in flight to a
// peer. It costs NO packets to collect, which is what makes it affordable
// every cycle.
//
// The field that matters most is MinCwnd. F-301: cubic sat at a median cwnd
// of 43-56 where 208-295 segments were needed, and the resulting 5 Mbps was
// pure arithmetic off that window. No latency or loss reading revealed it.
type TransportQuality struct {
	// Smallest congestion window across connections to this peer. The MINIMUM
	// is deliberate: one collapsed flow beside nine healthy ones is the
	// failure, and an average would hide it.
	MinCwnd     int `json:"min_cwnd,omitempty"`
	MinSsthresh int `json:"min_ssthresh,omitempty"`
	MSS         int `json:"mss,omitempty"`

	RTTMs    float64 `json:"rtt_ms,omitempty"`
	RTTVarMs float64 `json:"rtt_var_ms,omitempty"`
	// MinRTT is the path's floor. RTTMs - MinRTTMs is queueing plus jitter,
	// and on a satellite leg that difference is the interesting number.
	MinRTTMs float64 `json:"min_rtt_ms,omitempty"`

	RetransSegs int     `json:"retrans_segs,omitempty"`
	RetransPct  float64 `json:"retrans_pct,omitempty"`

	// Bytes the application has queued that TCP has not put on the wire.
	// Non-zero here alongside a small cwnd is what proves the sender is
	// throttled rather than idle.
	NotSentBytes uint64 `json:"not_sent_bytes,omitempty"`

	CongestionControl string `json:"congestion_control,omitempty"`

	// KERNEL-MEASURED REORDERING DEGREE, from `ss -tin`'s `reordering:` field.
	//
	// This is the displacement F-301 turned on — how far out of order the
	// stack has actually seen segments arrive — and the kernel computes it
	// from REAL TRAFFIC, so it costs nothing to read. Linux starts at 3 and
	// raises the estimate as it observes worse; >= 3 is the duplicate-ACK
	// threshold where reordering starts tripping spurious fast retransmits.
	//
	// This replaced a synthetic UDP echo burst that was written and never ran
	// because nothing echoed it. Reading the kernel needs no listening port,
	// generates no packets, and measures the traffic actually on the link
	// rather than a probe's idea of it.
	Reordering int `json:"reordering,omitempty"`

	// True when the kernel's reordering estimate has reached the fast
	// retransmit threshold. The distinction that matters: "the network
	// jitters" versus "TCP will collapse on this path".
	ReorderTripsFastRetransmit bool `json:"reorder_trips_fast_retransmit,omitempty"`

	// Which limit is binding. Without these a low cwnd is ambiguous, and the
	// ambiguity is what made F-301 take ten hours instead of one.
	AppLimited    bool `json:"app_limited,omitempty"`
	RwndLimited   bool `json:"rwnd_limited,omitempty"`
	SndbufLimited bool `json:"sndbuf_limited,omitempty"`

	// The verdict: a window at or below Linux's initial cwnd on a sender that
	// is NOT app-limited and has data queued. This is the alertable state.
	CwndCollapsed bool `json:"cwnd_collapsed,omitempty"`
}

// ReorderResult is a sequenced UDP burst's arrival statistics.
//
// MedianDisplacement is the field this type exists for. A count of
// out-of-order packets is nearly useless on its own: displacement 1-2 is
// harmless, displacement >= 3 trips TCP's duplicate-ACK threshold and is
// indistinguishable from loss. F-301 measured 2.00% reordering at median
// displacement exactly 3 — a bare percentage would have been dismissed.
type ReorderResult struct {
	Sent     int     `json:"sent"`
	Received int     `json:"received"`
	LossPct  float64 `json:"loss_pct"`

	OutOfOrder    int     `json:"out_of_order"`
	OutOfOrderPct float64 `json:"out_of_order_pct"`

	MedianDisplacement int `json:"median_displacement,omitempty"`
	MaxDisplacement    int `json:"max_displacement,omitempty"`

	// True when the typical reordering event on this path looks like loss to
	// a standard TCP stack. The alertable state.
	TripsFastRetransmit bool `json:"trips_fast_retransmit,omitempty"`
}

// PathType classifies the network path between two peers.
type PathType string

const (
	PathLAN      PathType = "lan"      // Same ethernet/WiFi segment, <2ms
	Path5G       PathType = "5g"       // Same private 5G network, 5-20ms
	PathInternet PathType = "internet" // Commercial ISP, NAT punch, 20-80ms
	PathStarlink PathType = "starlink" // satellite uplink CGNAT, 40-120ms
	PathRelayed  PathType = "relayed"  // Netbird relay fallback, 100-300ms
	PathUnknown  PathType = "unknown"
)

