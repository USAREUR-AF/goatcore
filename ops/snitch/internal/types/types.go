// InferPathType classifies the path based on measurement data and network context.
func InferPathType(direct bool, latencyMs float64, fromNet, toNet NetworkFingerprint) PathType {
	if !direct {
		return PathRelayed
	}
	// Same public IP = same network (LAN or 5G behind same NAT)
	if fromNet.PublicIP != "" && fromNet.PublicIP == toNet.PublicIP {
		if latencyMs < 3 {
			return PathLAN
		}
		return Path5G
	}
	// Check for Starlink ASN
	if isStarlink(fromNet.ASN) || isStarlink(toNet.ASN) {
		return PathStarlink
	}
	return PathInternet
}

func isStarlink(asn string) bool {
	// AS14593 = SpaceX Services (Starlink)
	return asn == "AS14593"
}

