#!/usr/bin/env python3
"""Generate this repository's goatbuilder config from its sources of record.

goatbuilder.yaml is never hand-maintained: every fact in it already has a home
— the components in ops/pins/fleet-pins.yaml, the environments and the
promotion path in ops/release/ladder.yaml, the release source and the deploy
values in ops/goatbuilder/project.yml, the secrets posture in
ops/goatbuilder/posture.yml, and federation environment overlays and peerings
in ops/goatbuilder/federation.yml — and a second copy of those facts would only
drift. This script derives the config from them and emits only what they
evidence.

project.yml and posture.yml belong to the deployment. federation.yml is absent
from the public core and belongs to an overlay when it declares federation. A
deployment that keeps its own values in a private overlay carries the files
there. A checkout without project.yml gets placeholder coordinates that name
no one.

Usage:
    ./gen-config.py            # (re)write ops/goatbuilder/goatbuilder.yaml
    ./gen-config.py --check    # exit 1 if the committed file is not what the
                               # sources would generate (a local drift check)

Exit codes: 0 ok, 1 drift or refused source/output, 2 usage or missing dependency.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import math
import os
import sys

try:
    import yaml
except ImportError:
    sys.stderr.write("ERROR: PyYAML is required: pip install pyyaml\n")
    sys.exit(2)

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
PINS = os.path.join(REPO, "ops", "pins", "fleet-pins.yaml")
LADDER = os.path.join(REPO, "ops", "release", "ladder.yaml")
PROJECT = os.path.join(HERE, "project.yml")
POSTURE = os.path.join(HERE, "posture.yml")
FEDERATION = os.path.join(HERE, "federation.yml")
OUT = os.path.join(HERE, "goatbuilder.yaml")
FEDERATION_DIGEST_PREFIX = "# federation-declarations-sha256: "


class _UniqueKeyLoader(yaml.SafeLoader):
    """Safe YAML loader that refuses a mapping key repeated at any depth."""


def _construct_unique_mapping(loader, node, deep=False):
    mapping = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=deep)
        try:
            duplicate = key in mapping
        except TypeError as e:
            raise yaml.constructor.ConstructorError(
                "while constructing a mapping", node.start_mark,
                f"unhashable mapping key {key!r}", key_node.start_mark,
            ) from e
        if duplicate:
            raise yaml.constructor.ConstructorError(
                "while constructing a mapping", node.start_mark,
                f"duplicate key {key!r}", key_node.start_mark,
            )
        mapping[key] = loader.construct_object(value_node, deep=deep)
    return mapping


_UniqueKeyLoader.add_constructor(
    yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _construct_unique_mapping
)

HEADER = (
    "# GENERATED by ops/goatbuilder/gen-config.py from ops/pins/fleet-pins.yaml,\n"
    "# ops/release/ladder.yaml, ops/goatbuilder/project.yml,\n"
    "# ops/goatbuilder/posture.yml and ops/goatbuilder/federation.yml — do not edit;\n"
    "# change the source and regenerate.\n"
    "# Validated against ops/goatbuilder/schema/goatbuilder-v1.schema.json\n"
    "# (docs/design/goatbuilder.md, ADR 1198).\n"
)


# A checkout that declares no project.yml: coordinates that belong to no one,
# so nothing is released from or pulled out of somebody else's repository.
DEFAULT_REPO = {
    "source": "example-org/example-repo",
    "image_namespace": "ghcr.io/example-org",
    "signing": "intent-sign",
}
# In schema order. release_source is optional: the repository whose release
# workflow signs the goatbuilder binaries `goatbuilder update` installs; omitted,
# goatbuilder uses source.
REPO_KEYS = ("source", "image_namespace", "release_source", "signing")
DEPLOY_KEYS = ("aws_profile", "ssh_user", "state_dir")
GENERATED_ENVIRONMENT_KEYS = ("name", "converger", "groups")


def generate(pins_path: str = PINS, ladder_path: str = LADDER, project_path: str = PROJECT,
             posture_path: str = POSTURE, federation_path: str = FEDERATION) -> dict:
    """Return the config dict the sources of record evidence."""
    with open(pins_path) as fh:
        pins = yaml.safe_load(fh) or {}
    with open(ladder_path) as fh:
        ladder = yaml.safe_load(fh) or {}

    components: dict[str, dict] = {}
    for name in sorted(pins.get("components") or {}):
        c = pins["components"][name] or {}
        wf = c.get("image_workflow")
        comp: dict = {
            "image_workflow": os.path.basename(wf) if wf else None,
            "declared_in": "ops/pins/fleet-pins.yaml",
        }
        if c.get("var"):
            comp["var"] = c["var"]
        ledger = c.get("ledger_component") or name
        if ledger != name:
            comp["ledger"] = ledger
        components[name] = comp

    rungs = [r for r in ladder.get("rungs") or [] if r.get("status") == "live"]
    if not rungs:
        sys.exit("ERROR: ladder.yaml has no live rungs")
    goatnets = pins.get("goatnets") or {}
    environments = []
    for r in rungs:
        env = {"name": r["goatnet"], "converger": "push-ansible"}
        members = (goatnets.get(r["goatnet"]) or {}).get("members") or []
        if members:
            env["groups"] = list(members)
        environments.append(env)

    environment_overlays, peerings = federation(federation_path)
    declared_environments = {env["name"] for env in environments}
    unknown_environments = sorted(set(environment_overlays) - declared_environments)
    if unknown_environments:
        _federation_error(
            federation_path,
            f"`environments:` names undeclared environments {unknown_environments}; "
            "declare them in the live release ladder and fleet pins, or remove them",
        )
    for env in environments:
        if env["name"] in environment_overlays:
            env.update(copy.deepcopy(environment_overlays[env["name"]]))
    _check_peering_references(federation_path, environments, peerings)

    gates_into: dict[str, list] = {}
    for hop in ladder.get("hops") or []:
        if hop.get("status") != "live":
            continue
        gates = []
        for g in hop.get("gates") or []:
            gate = {"id": g["id"]}
            if "min_days" in g:
                gate["min_days"] = int(g["min_days"])
            gates.append(gate)
        gates_into[hop["to"]] = gates

    path = []
    for r in rungs:
        stage = {"name": r["name"], "kind": "rung", "environment": r["goatnet"]}
        if gates_into.get(r["name"]):
            stage["gates"] = gates_into[r["name"]]
        path.append(stage)

    repo, deploy = project(project_path)
    config = {"schema": "goatbuilder/v1", "preset": "full", "repo": repo}
    # The deploy values (goatbuilder-portability.md): a value project.yml does
    # not declare is left out, and goatbuilder falls back to a name that
    # belongs to no project, or refuses where no such name can be right.
    if deploy:
        config["deploy"] = deploy
    config.update({
        "components": components,
        "environments": environments,
        "promotion": {"path": path},
        # The secrets posture (ADR 1204), declared in ops/goatbuilder/posture.yml,
        # with op_account pinning the account op:// references resolve against so
        # `op` can never prompt across every configured account; OP_ACCOUNT in the
        # environment overrides it per command. A checkout that declares no
        # posture gets the store that needs no account of anyone's: an env file,
        # which `goatbuilder secrets init` can write with strong random values.
        "secrets": posture(posture_path),
    })
    if peerings:
        config["peerings"] = copy.deepcopy(peerings)
    return config


def _mapping(path: str, what: str, reject_duplicates: bool = False,
             federation_source: bool = False) -> dict | None:
    """A YAML file's top-level mapping; None when the file does not exist."""
    try:
        with open(path, encoding="utf-8") as fh:
            loader = _UniqueKeyLoader if reject_duplicates else yaml.SafeLoader
            declared = yaml.load(fh, Loader=loader)
    except FileNotFoundError:
        return None
    except (OSError, UnicodeError, yaml.YAMLError) as e:
        if federation_source:
            _federation_error(
                path,
                f"cannot read federation declarations: {e}. Correct the YAML and regenerate",
            )
        raise SystemExit(f"{path}: cannot read {what}: {e}")
    if declared is None:
        return {}
    if not isinstance(declared, dict):
        if federation_source:
            _federation_error(
                path,
                "must be a mapping with `environments:` and `peerings:`; correct the YAML and regenerate",
            )
        raise SystemExit(f"{path} must be a mapping of {what}")
    return declared


def _federation_error(path: str, message: str) -> None:
    """Refuse an unsafe federation source with its catalog code and recovery."""
    raise SystemExit(f"GB-079: {path}: {message}")


def _yaml_path(parent: str, key) -> str:
    if isinstance(key, str) and key:
        return f"{parent}.{key}" if parent else key
    return f"{parent}[{key!r}]" if parent else f"[{key!r}]"


def _validate_federation_value(value, path: str, source: str) -> None:
    """Accept only the YAML value model the digest can encode unambiguously."""
    if value is None or type(value) in (bool, int, str):
        return
    if type(value) is float:
        if math.isfinite(value):
            return
        _federation_error(
            source, f"`{path}` is a non-finite float; quote it as text or use a finite number",
        )
    if isinstance(value, list):
        for index, item in enumerate(value):
            _validate_federation_value(item, f"{path}[{index}]", source)
        return
    if isinstance(value, dict):
        for key, item in value.items():
            if type(key) is not str:
                _federation_error(
                    source,
                    f"`{_yaml_path(path, key)}` has a {type(key).__name__} mapping key; "
                    "quote the key so every mapping key is text",
                )
            _validate_federation_value(item, _yaml_path(path, key), source)
        return
    _federation_error(
        source,
        f"`{path}` has unsupported YAML type {type(value).__name__}; quote dates and other "
        "typed scalars as text",
    )


def _block(path: str, declared: dict, name: str, keys: tuple) -> dict:
    block = declared.get(name) or {}
    if not isinstance(block, dict):
        raise SystemExit(f"{path}: `{name}:` must be a mapping")
    unknown = sorted(set(block) - set(keys))
    if unknown:
        raise SystemExit(f"{path}: `{name}:` has unknown keys {unknown}; known: {list(keys)}")
    return {k: block[k] for k in keys if block.get(k) not in (None, "")}


def project(path: str = PROJECT) -> tuple[dict, dict]:
    """The `repo:` and `deploy:` blocks, from ops/goatbuilder/project.yml."""
    declared = _mapping(path, "project values")
    if declared is None:
        return dict(DEFAULT_REPO), {}
    unknown = sorted(set(declared) - {"repo", "deploy"})
    if unknown:
        raise SystemExit(f"{path}: unknown top-level keys {unknown}; known: ['repo', 'deploy']")
    repo = _block(path, declared, "repo", REPO_KEYS)
    missing = [k for k in ("source", "image_namespace") if k not in repo]
    if missing:
        raise SystemExit(f"{path}: `repo:` must declare {missing} (the release source and image namespace)")
    repo.setdefault("signing", DEFAULT_REPO["signing"])
    return {k: repo[k] for k in REPO_KEYS if k in repo}, _block(path, declared, "deploy", DEPLOY_KEYS)


def posture(path: str = POSTURE) -> dict:
    """The `secrets:` block, from ops/goatbuilder/posture.yml where it exists."""
    try:
        with open(path, encoding="utf-8") as fh:
            declared = yaml.safe_load(fh) or {}
    except FileNotFoundError:
        return {"store": "env-file"}
    except (OSError, UnicodeError, yaml.YAMLError) as e:
        _federation_error(
            path,
            f"cannot read the secrets posture: {e}. Correct the YAML and regenerate",
        )
    if not isinstance(declared, dict) or not declared.get("store"):
        raise SystemExit(f"{path} declares no secrets store: add `store: <name>` (ADR 1204)")
    if "federation" in declared:
        _validate_federation_value(declared["federation"], "posture.federation", path)
    return {k: v for k, v in declared.items() if v not in (None, "")}


def federation(path: str = FEDERATION) -> tuple[dict, list]:
    """Environment overlays and peerings from the deployment's source."""
    declared = _mapping(
        path, "federation declarations", reject_duplicates=True, federation_source=True
    )
    if declared is None:
        return {}, []
    _validate_federation_value(declared, "federation", path)
    unknown = sorted(set(declared) - {"environments", "peerings"})
    if unknown:
        _federation_error(
            path,
            f"unknown top-level keys {unknown}; known: ['environments', 'peerings']",
        )
    missing = sorted({"environments", "peerings"} - set(declared))
    if missing:
        _federation_error(
            path,
            f"missing required top-level keys {missing}; declare both `environments:` and "
            "`peerings:` (use `environments: {}` and `peerings: []` when intentionally empty)",
        )
    environments = declared["environments"]
    if not isinstance(environments, dict):
        _federation_error(path, "`environments:` must map environment names to overlays")
    for environment, overlay in environments.items():
        if not isinstance(environment, str) or not environment:
            _federation_error(path, "every `environments:` key must be a non-empty name")
        if not isinstance(overlay, dict):
            _federation_error(path, f"`environments.{environment}:` must be a mapping")
        conflicts = sorted(set(overlay) & set(GENERATED_ENVIRONMENT_KEYS))
        if conflicts:
            _federation_error(
                path,
                f"`environments.{environment}:` declares generator-owned fields {conflicts}; "
                "change environment identity in fleet-pins.yaml or ladder.yaml, and keep only "
                "operator-owned fields in federation.yml",
            )
        rows = overlay.get("sites")
        if rows is None:
            continue
        if not isinstance(rows, list) or not rows:
            _federation_error(path, f"`environments.{environment}.sites:` must be a non-empty list")
        if not all(isinstance(row, dict) for row in rows):
            _federation_error(path, f"every entry in `environments.{environment}.sites:` must be a mapping")
        for i, row in enumerate(rows):
            _identifier(
                row.get("name"), f"`environments.{environment}.sites[{i}].name`", path
            )
            classes = row.get("classes", {})
            if not isinstance(classes, dict):
                _federation_error(path, f"`environments.{environment}.sites[{i}].classes` must be a mapping")
            for name in classes:
                _identifier(
                    name, f"`environments.{environment}.sites[{i}].classes` key", path
                )
    peerings = declared["peerings"]
    if not isinstance(peerings, list):
        _federation_error(path, "`peerings:` must be a list")
    if not all(isinstance(row, dict) for row in peerings):
        _federation_error(path, "every `peerings:` entry must be a mapping")
    return environments, peerings


def _identifier(value, field: str, federation_source: str | None = None) -> str:
    if not isinstance(value, str) or not value:
        if federation_source:
            _federation_error(
                federation_source, f"{field} must be a non-empty string, got {value!r}"
            )
        raise SystemExit(f"{field} must be a non-empty string, got {value!r}")
    return value


def _check_peering_references(path: str, environments: list[dict], peerings: list[dict]) -> None:
    """Refuse federation rows that point outside the generated topology."""
    sites = {
        env["name"]: {site["name"]: site for site in env.get("sites") or []}
        for env in environments
    }
    identities = set()
    for i, peering in enumerate(peerings):
        values = {
            key: _identifier(peering.get(key), f"`peerings[{i}].{key}`", path)
            for key in ("with", "environment", "site", "edge_class")
        }
        environment = values["environment"]
        identity = (environment, values["with"])
        if identity in identities:
            _federation_error(
                path,
                f"`peerings[{i}]` duplicates peering identity "
                f"'{environment}/{values['with']}'; keep one row for each environment/partner",
            )
        identities.add(identity)
        if environment not in sites:
            _federation_error(
                path, f"`peerings[{i}]` names undeclared environment '{environment}'"
            )
        site = sites[environment].get(values["site"])
        if site is None:
            _federation_error(
                path,
                f"`peerings[{i}]` names undeclared site '{values['site']}' in environment "
                f"'{environment}'",
            )
        if values["edge_class"] not in (site.get("classes") or {}):
            _federation_error(
                path,
                f"`peerings[{i}]` edge_class '{values['edge_class']}' is not declared at "
                f"site '{values['site']}'",
            )


def _declarations(config: dict, label: str) -> tuple[dict, dict, object | None]:
    """Source-owned declarations indexed by their stable identities."""
    overlays = {}
    environments = config.get("environments") or []
    if not isinstance(environments, list):
        raise SystemExit(f"{label}: `environments:` must be a list")
    for ei, env in enumerate(environments):
        if not isinstance(env, dict):
            raise SystemExit(f"{label}: `environments[{ei}]` must be a mapping")
        environment = _identifier(env.get("name"), f"{label}: `environments[{ei}].name`")
        if environment in overlays:
            raise SystemExit(f"{label}: duplicate environment declaration {environment!r}")
        overlay = {
            key: value for key, value in env.items()
            if key not in GENERATED_ENVIRONMENT_KEYS
        }
        if overlay:
            overlays[environment] = overlay

    peerings = {}
    rows = config.get("peerings") or []
    if not isinstance(rows, list):
        raise SystemExit(f"{label}: `peerings:` must be a list")
    for i, peering in enumerate(rows):
        if not isinstance(peering, dict):
            raise SystemExit(f"{label}: `peerings[{i}]` must be a mapping")
        environment = _identifier(peering.get("environment"), f"{label}: `peerings[{i}].environment`")
        partner = _identifier(peering.get("with"), f"{label}: `peerings[{i}].with`")
        identity = (environment, partner)
        if identity in peerings:
            raise SystemExit(f"{label}: duplicate peering declaration {identity}")
        peerings[identity] = peering
    secrets = config.get("secrets") or {}
    if not isinstance(secrets, dict):
        raise SystemExit(f"{label}: `secrets:` must be a mapping")
    federation_secrets = secrets.get("federation") if "federation" in secrets else None
    return overlays, peerings, federation_secrets


def _canonical_value(value):
    """A deterministic, type-tagged JSON value for the supported YAML model."""
    if value is None:
        return ["null"]
    if type(value) is bool:
        return ["bool", value]
    if type(value) is int:
        return ["int", str(value)]
    if type(value) is float:
        return ["float", value.hex()]
    if type(value) is str:
        return ["str", value]
    if isinstance(value, list):
        return ["list", [_canonical_value(item) for item in value]]
    if isinstance(value, dict):
        return [
            "map",
            [[key, _canonical_value(value[key])] for key in sorted(value)],
        ]
    raise TypeError(f"unsupported canonical value {type(value).__name__}")


def _federation_digest(config: dict) -> str:
    overlays, peerings, federation_secrets = _declarations(config, "generated config")
    declarations = {
        "environments": [[identity, value] for identity, value in sorted(overlays.items())],
        "peerings": [[list(identity), value] for identity, value in sorted(peerings.items())],
        "secrets.federation": federation_secrets,
    }
    canonical = json.dumps(
        _canonical_value(declarations), ensure_ascii=False, separators=(",", ":")
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _same_value(left, right) -> bool:
    if type(left) is not type(right):
        return False
    if isinstance(left, dict):
        return (
            set(left) == set(right)
            and all(_same_value(left[key], right[key]) for key in left)
        )
    if isinstance(left, list):
        return len(left) == len(right) and all(
            _same_value(a, b) for a, b in zip(left, right)
        )
    return left == right


def _missing_content(old, new, path: str) -> list[str]:
    """Paths whose old declaration content is absent or changed in the source."""
    if isinstance(old, dict):
        if not isinstance(new, dict):
            return [path]
        missing = []
        for key, value in old.items():
            child = f"{path}.{key}"
            if key not in new:
                missing.append(child)
            else:
                missing.extend(_missing_content(value, new[key], child))
        return missing
    if isinstance(old, list):
        if not isinstance(new, list):
            return [path]
        unmatched = list(new)
        missing = []
        for item in old:
            identity_match = None
            if isinstance(item, dict) and isinstance(item.get("name"), str):
                identity_match = next(
                    (index for index, candidate in enumerate(unmatched)
                     if isinstance(candidate, dict)
                     and type(candidate.get("name")) is type(item["name"])
                     and candidate.get("name") == item["name"]),
                    None,
                )
            if identity_match is not None:
                candidate = unmatched.pop(identity_match)
                missing.extend(
                    _missing_content(item, candidate, f"{path}[{item['name']!r}]")
                )
                continue
            if isinstance(item, dict) and isinstance(item.get("name"), str):
                missing.append(f"{path}[{item['name']!r}]")
                continue
            match = next(
                (index for index, candidate in enumerate(unmatched)
                 if _same_value(item, candidate)),
                None,
            )
            if match is None:
                missing.append(f"{path}[{item!r}]")
            else:
                unmatched.pop(match)
        return missing
    return [] if _same_value(old, new) else [f"{path} ({old!r} -> {new!r})"]


def refuse_discarded_declarations(config: dict, out_path: str = OUT,
                                   federation_path: str = FEDERATION,
                                   posture_path: str = POSTURE) -> None:
    """Adopt legacy declarations without losing any of their content."""
    try:
        with open(out_path, encoding="utf-8") as fh:
            existing_text = fh.read()
    except FileNotFoundError:
        return
    except (OSError, UnicodeError) as e:
        _federation_error(out_path, f"cannot read the generated output: {e}")
    try:
        existing = yaml.load(existing_text, Loader=_UniqueKeyLoader)
    except yaml.YAMLError as e:
        _federation_error(
            out_path, f"cannot parse the generated output: {e}. Correct it before regenerating"
        )
    if not isinstance(existing, dict):
        _federation_error(out_path, "the generated output must contain a mapping")
    _validate_federation_value(existing, "output", out_path)

    try:
        old_environments, old_peerings, old_federation_secrets = _declarations(
            existing, out_path
        )
    except SystemExit as e:
        _federation_error(out_path, f"cannot inspect the generated output: {e}")
    if not os.path.isfile(federation_path) and (old_environments or old_peerings):
        _federation_error(
            out_path,
            f"refusing to discard declarations because {federation_path} is missing. Restore "
            "the overlay source; to intentionally remove every environment overlay and peering, "
            "keep that file with explicit `environments: {}` and `peerings: []`",
        )
    if old_federation_secrets is not None and not os.path.isfile(posture_path):
        _federation_error(
            out_path,
            f"refusing to discard `secrets.federation` because {posture_path} is missing. "
            "Restore that posture source; after adoption, intentionally remove the key/CA "
            "paths by keeping posture.yml with `store:` and removing its `federation:` block",
        )

    marker = next(
        (line.removeprefix(FEDERATION_DIGEST_PREFIX) for line in existing_text.splitlines()
         if line.startswith(FEDERATION_DIGEST_PREFIX)),
        None,
    )
    if marker == _federation_digest(existing):
        return  # the old declarations came from the source, so source changes are intentional

    try:
        wanted_environments, wanted_peerings, wanted_federation_secrets = _declarations(
            config, "replacement generated from federation.yml and posture.yml"
        )
    except SystemExit as e:
        _federation_error(out_path, f"cannot inspect the replacement: {e}")
    missing = []
    for identity, old in old_environments.items():
        new = wanted_environments.get(identity)
        path = f"environments[{identity}]"
        missing.extend([path] if new is None else _missing_content(old, new, path))
    for identity, old in old_peerings.items():
        new = wanted_peerings.get(identity)
        path = f"peerings[{identity[0]}/{identity[1]}]"
        missing.extend([path] if new is None else _missing_content(old, new, path))
    if old_federation_secrets is not None:
        missing.extend(
            ["secrets.federation"]
            if wanted_federation_secrets is None
            else _missing_content(
                old_federation_secrets,
                wanted_federation_secrets,
                "secrets.federation",
            )
        )
    if missing:
        _federation_error(
            out_path,
            f"refusing to discard declaration content: {', '.join(missing)}. Preserve "
            f"environment overlays and peerings in {federation_path}, and preserve "
            f"`secrets.federation` key/CA paths in {posture_path}; regenerate once to record "
            "those sources, after which intentional source edits regenerate normally",
        )


def render(config: dict) -> str:
    marker = f"{FEDERATION_DIGEST_PREFIX}{_federation_digest(config)}\n"
    return HEADER + marker + yaml.safe_dump(config, sort_keys=False, default_flow_style=False, width=100)


def write_or_check(config: dict, check: bool, out_path: str = OUT, repo_path: str = REPO,
                   federation_path: str = FEDERATION, posture_path: str = POSTURE) -> None:
    """Write the generated config, or compare it without changing the file."""
    refuse_discarded_declarations(config, out_path, federation_path, posture_path)
    text = render(config)
    relative = os.path.relpath(out_path, repo_path)
    if check:
        try:
            with open(out_path, encoding="utf-8") as fh:
                committed = fh.read()
        except FileNotFoundError:
            sys.exit(f"DRIFT: {relative} is missing; run ops/goatbuilder/gen-config.py")
        if committed != text:
            sys.exit(
                f"DRIFT: {relative} differs from what the sources generate; "
                "run ops/goatbuilder/gen-config.py"
            )
        print(f"ok: {relative} matches its sources")
        return
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {relative}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed config differs from the generated one")
    a = ap.parse_args()
    config = generate()
    write_or_check(config, a.check)


if __name__ == "__main__":
    main()
