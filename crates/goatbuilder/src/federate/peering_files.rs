//! `goatbuilder federate allocate`: the per-peering files a person used to
//! write by hand, rendered from the `peerings:` declaration and the allocated
//! values (federate/alloc.rs).
//!
//! What it writes, relative to the repository (the deployment's own checkout):
//!
//! | File | What |
//! |---|---|
//! | `ops/goatbuilder/peering-values.yaml` | the allocation record: the reviewable proposal, committed |
//! | `ops/ansible/group_vars/<edge_group>/peering-values.yml` | the edge's per-peering values |
//! | `ops/ansible/group_vars/<core_group>/peering-values.yml` | the core's per-peering values (the republisher) |
//! | `ops/ansible/inventory/peering-edges.ini` | the peering inventory, when the peerings declare `hosts:` |
//!
//! What it does NOT write: the agreement's own values. `goat federate apply`
//! renders those beside these files (`federation-<them>.yml`,
//! `federation-<them>-republish.yml`, `federation-<them>-transport.yml`), from
//! the verified agreement, and this module never duplicates one of them.
//!
//! Idempotent: a file whose content is already right is left alone, and a
//! re-run with the record changes nothing. It never overwrites a file it did
//! not generate (the first line says who did). `--dry-run` and `--mock` write
//! nothing and show every file.

use std::path::{Path, PathBuf};

use anyhow::Result;

use super::alloc::{self, AllocContext, PeeringValues};
use super::Options;
use crate::config::{self, Config};
use crate::{Check, Report, EXIT_REFUSED};

/// Every file this module writes starts with this line.
pub const MARKER: &str = "# GENERATED by `goatbuilder federate allocate`";

/// One rendered file: its path relative to the repository, and its text.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rendered {
    pub path: String,
    pub body: String,
}

pub(super) fn header(what: &str) -> String {
    format!(
        "{MARKER}: {what}\n\
         # Do not edit. Pin a value under the peering's `values:` in goatbuilder.yaml and run\n\
         # `goatbuilder federate allocate` again; the allocation record is\n\
         # ops/goatbuilder/peering-values.yaml.\n"
    )
}

pub(super) fn q(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// The edge group's per-peering values.
fn edge_vars(p: &config::Peering, v: &PeeringValues, inventory: bool, installs: bool) -> String {
    let c = &v.cert_dir;
    let mut s = header(&format!(
        "the edge values of peering {} on environment {}.",
        v.peering, v.environment
    ));
    s.push_str(
        "# `goat federate apply` writes the agreement's values beside this file\n\
         # (federation-<them>.yml, federation-<them>-transport.yml); none is repeated here.\n\n",
    );
    let wg = p.tunnel.as_deref() != Some("ipsec");
    s.push_str(&format!("peering_wg_enabled: {wg}\n"));
    s.push_str(&format!("peering_wg_interface: {}\n", q(&v.wg_interface)));
    s.push_str(&format!("peering_wg_listen_port: {}\n", v.wg_listen_port));
    s.push_str(&format!(
        "peering_spire_outbound_port: {}\n",
        v.spire_outbound_port
    ));
    if inventory {
        s.push_str(&format!(
            "peering_spire_server_host: {}\n",
            q(&v.core_host_name)
        ));
    }
    s.push_str(&format!(
        "\n# The edge router's partner-facing port: the same for every peering, because\n\
         # each edge binds its own link address.\n\
         goat_zenoh_edge_listen_port: {}\n",
        v.edge_listen_port
    ));
    if installs {
        // goat-zenoh-edge installs the leaves itself (goat_zenoh_edge_install_certs):
        // it reads them from <fed_work>/pki (this peering's cert_dir, which the
        // driver's --work matches, GB-128), checks them, and installs them in
        // goat_zenoh_edge_cert_dir, deriving the four leaf paths from it and refusing
        // any other value. So the leaf paths are not rendered, and the edge's own
        // per-peering directory is.
        s.push_str(&format!(
            "\n# goat_zenoh_edge_install_certs is on for this group: the role installs this\n\
             # peering's leaves from {c} (phase 8) into the directory below and derives\n\
             # the four leaf paths from it; they are not set here.\n\
             goat_zenoh_edge_cert_dir: {}\n",
            q(&format!("/etc/goat-zenoh-edge-{}/tls", v.peering))
        ));
    } else {
        s.push_str(
            "\n# This peering's leaf certificates: phase 8 writes them here, and the edge reads them\n\
             # here. The two CA paths (goat_zenoh_edge_our_ca_path, goat_zenoh_edge_partner_ca_path)\n\
             # are not rendered: phase 8 does not write those files, and the partner CA is placed\n\
             # only after its fingerprint is checked against the agreement (phase 10).\n",
        );
        for (var, file) in [
            ("goat_zenoh_edge_outward_cert", "peering-outward.pem"),
            ("goat_zenoh_edge_outward_key", "peering-outward-key.pem"),
            ("goat_zenoh_edge_inward_cert", "peering-inward.pem"),
            ("goat_zenoh_edge_inward_key", "peering-inward-key.pem"),
        ] {
            s.push_str(&format!("{var}: {}\n", q(&format!("{c}/{file}"))));
        }
    }
    s.push_str(&super::forwarder::edge_vars(p, v));
    s
}

/// The core group's per-peering values: the republisher of this peering.
fn core_vars(v: &PeeringValues) -> String {
    let c = &v.cert_dir;
    let mut s = header(&format!(
        "the core values of peering {} on environment {}.",
        v.peering, v.environment
    ));
    s.push_str(
        "# `goat federate apply` writes the republisher's agreement half beside it\n\
         # (federation-<them>-republish.yml).\n\n",
    );
    s.push_str(&format!(
        "goat_fed_republisher_metrics_port: {}\n",
        v.republisher_metrics_port
    ));
    s.push_str(&format!(
        "goat_fed_republisher_cert_src: {}\n",
        q(&format!("{c}/republisher.pem"))
    ));
    s.push_str(&format!(
        "goat_fed_republisher_key_src: {}\n",
        q(&format!("{c}/republisher-key.pem"))
    ));
    s
}

fn host_line(name: &str, addr: &str, user: Option<&str>) -> String {
    let mut l = format!("{name} ansible_host={addr}");
    if let Some(u) = user {
        l.push_str(&format!(" ansible_user={u}"));
    }
    l
}

/// The peering inventory: every peering's edge and core, one inventory name per
/// peering per machine, so two peerings on one machine never read each other's
/// group_vars (Ansible merges every group a host name is in).
/// The `[group]` section of an INI inventory, its host lines only.
fn section(text: &str, group: &str) -> Option<Vec<String>> {
    let head = format!("[{group}]");
    let mut lines = text.lines();
    lines.find(|l| l.trim() == head)?;
    Some(
        lines
            .take_while(|l| !l.trim_start().starts_with('['))
            .filter(|l| !l.trim().is_empty() && !l.trim_start().starts_with('#'))
            .map(String::from)
            .collect(),
    )
}

/// Retired peerings' groups, carried over from the last generated inventory:
/// (edge groups, core groups), each with its host lines.
type Retired = (Vec<(String, Vec<String>)>, Vec<(String, Vec<String>)>);

fn retired_groups(
    values: &[PeeringValues],
    previous: &alloc::Record,
    prev: Option<&str>,
) -> Retired {
    let (mut edges, mut cores) = (Vec::new(), Vec::new());
    let Some(text) = prev else {
        return (edges, cores);
    };
    let declared: Vec<String> = values
        .iter()
        .map(|v| format!("{}/{}", v.environment, v.peering))
        .collect();
    for (k, e) in &previous.peerings {
        if declared.contains(k) {
            continue;
        }
        for (g, list) in [(&e.edge_group, &mut edges), (&e.core_group, &mut cores)] {
            if let Some(g) = g {
                if let Some(hosts) = section(text, g) {
                    list.push((g.clone(), hosts));
                }
            }
        }
    }
    (edges, cores)
}

fn inventory(cfg: &Config, values: &[PeeringValues], retired: &Retired) -> Result<String> {
    let mut s = header("the peering inventory, from goatbuilder.yaml peerings: hosts:.");
    s.push_str(
        "# One inventory name per peering for each machine: a host name in two peering\n\
         # groups would read both peerings' values.\n\n",
    );
    let pairs: Vec<(&config::Peering, &PeeringValues)> =
        cfg.peerings.iter().zip(values.iter()).collect();
    s.push_str("[peering_edges:children]\n");
    for (_, v) in &pairs {
        s.push_str(&format!("{}\n", v.edge_group));
    }
    for (g, _) in &retired.0 {
        s.push_str(&format!("{g}\n"));
    }
    for (p, v) in &pairs {
        let h = p.hosts.as_ref().expect("checked by the caller");
        s.push_str(&format!(
            "\n[{}]\n{}\n",
            v.edge_group,
            host_line(&v.edge_host_name, &h.edge, h.user.as_deref())
        ));
    }
    let carry = |s: &mut String, list: &Vec<(String, Vec<String>)>| {
        for (g, hosts) in list {
            s.push_str(&format!(
                "\n# Retired: no longer declared, kept while its record entry stays (it may still run).\n[{g}]\n{}\n",
                hosts.join("\n")
            ));
        }
    };
    carry(&mut s, &retired.0);
    s.push_str("\n# The core host each peering's edge dials; its republisher runs there.\n[peering_cores:children]\n");
    for (_, v) in &pairs {
        s.push_str(&format!("{}\n", v.core_group));
    }
    for (g, _) in &retired.1 {
        s.push_str(&format!("{g}\n"));
    }
    for (p, v) in &pairs {
        let h = p.hosts.as_ref().expect("checked by the caller");
        s.push_str(&format!(
            "\n[{}]\n{}\n",
            v.core_group,
            host_line(&v.core_host_name, &h.core, h.user.as_deref())
        ));
    }
    carry(&mut s, &retired.1);
    s.push_str(&super::forwarder::inventory(cfg, values)?);
    Ok(s)
}

/// Every file for these peerings, the record first. `values` is in declaration
/// order (as `alloc::allocate_all` returns it).
#[cfg(test)]
pub fn render(cfg: &Config, values: &[PeeringValues]) -> Result<Vec<Rendered>> {
    render_with(cfg, values, &alloc::Record::default())
}

/// `render`, keeping the record entries of `previous` whose peering is no
/// longer declared.
#[cfg(test)]
pub fn render_with(
    cfg: &Config,
    values: &[PeeringValues],
    previous: &alloc::Record,
) -> Result<Vec<Rendered>> {
    render_full(cfg, values, previous, None, &Default::default())
}

/// `render_with`, carrying over from `prev_inventory` (the inventory this
/// module generated last time) the groups of record entries no longer
/// declared: their peering may still run, and backing it out needs its hosts.
pub fn render_full(
    cfg: &Config,
    values: &[PeeringValues],
    previous: &alloc::Record,
    prev_inventory: Option<&str>,
    installs: &std::collections::BTreeSet<String>,
) -> Result<Vec<Rendered>> {
    let mut out = vec![Rendered {
        path: format!("ops/goatbuilder/{}", alloc::RECORD_FILE),
        body: alloc::record_text(&alloc::record_of(values, previous)),
    }];
    let with_hosts = cfg.peerings.iter().filter(|p| p.hosts.is_some()).count();
    if with_hosts != 0 && with_hosts != cfg.peerings.len() {
        let missing: Vec<String> = cfg
            .peerings
            .iter()
            .enumerate()
            .filter(|(_, p)| p.hosts.is_none())
            .map(|(i, p)| format!("peerings/{i} (with '{}')", p.with))
            .collect();
        return Err(goat_errors::coded(
            "GB-126",
            format!(
                "the peering inventory is rendered whole, and {} declare no hosts: (GB-126). Add `hosts: {{edge: <address>, core: <address>}}` to each, or remove hosts: from every peering and keep writing ops/ansible/inventory/peering-edges.ini by hand",
                missing.join(", ")
            ),
        )
        .into());
    }
    let inv = with_hosts != 0;
    for (p, v) in cfg.peerings.iter().zip(values.iter()) {
        out.push(Rendered {
            path: format!("ops/ansible/group_vars/{}/peering-values.yml", v.edge_group),
            body: edge_vars(p, v, inv, installs.contains(&v.edge_group)),
        });
        out.push(Rendered {
            path: format!("ops/ansible/group_vars/{}/peering-values.yml", v.core_group),
            body: core_vars(v),
        });
    }
    if inv {
        out.push(Rendered {
            path: "ops/ansible/inventory/peering-edges.ini".into(),
            body: inventory(
                cfg,
                values,
                &retired_groups(values, previous, prev_inventory),
            )?,
        });
    }
    out.extend(super::forwarder::render(cfg, values)?);
    Ok(out)
}

/// Where a rendered path lands: the record beside the config file, the rest
/// under the repository.
fn target(repo: &Path, cfg_dir: &Path, rel: &str) -> PathBuf {
    match rel.strip_prefix("ops/goatbuilder/") {
        Some(name) if name == alloc::RECORD_FILE => cfg_dir.join(name),
        _ => repo.join(rel),
    }
}

/// Files this module generated earlier for a peering that is no longer declared.
fn stale(repo: &Path, rendered: &[Rendered]) -> Vec<String> {
    let mut out = Vec::new();
    let Ok(dirs) = std::fs::read_dir(repo.join("ops/ansible/group_vars")) else {
        return out;
    };
    for d in dirs.flatten() {
        for name in [
            "peering-values.yml",
            "peering-forwarder.yml",
            "peering-deployment.yml",
        ] {
            let f = d.path().join(name);
            let rel = format!(
                "ops/ansible/group_vars/{}/{name}",
                d.file_name().to_string_lossy()
            );
            let ours = std::fs::read_to_string(&f)
                .map(|t| t.starts_with(MARKER))
                .unwrap_or(false);
            if ours && !rendered.iter().any(|r| r.path == rel) {
                out.push(rel);
            }
        }
    }
    out.sort();
    out
}

/// The top-level keys of a YAML mapping (empty when the text is not one).
fn yaml_keys(text: &str) -> Vec<String> {
    match serde_yaml::from_str::<serde_yaml::Value>(text) {
        Ok(serde_yaml::Value::Mapping(m)) => m
            .keys()
            .filter_map(|k| k.as_str().map(String::from))
            .collect(),
        _ => Vec::new(),
    }
}

/// For a rendered group_vars file: another file this module did not generate
/// that sets a key the rendered file sets, with those keys. Looked for in the
/// group's own directory or file, the parent groups `peering_edges`,
/// `peering_cores` and `peering_forwarders`, and the host_vars of `hosts` (the
/// inventory names of the peerings). A group_vars file of `all` is not looked at:
/// a group's own value is meant to override it.
fn shadowed(repo: &Path, r: &Rendered, hosts: &[String]) -> Option<(PathBuf, Vec<String>)> {
    let rest = r.path.strip_prefix("ops/ansible/group_vars/")?;
    let (group, _) = rest.split_once('/')?;
    let mine = yaml_keys(&r.body);
    let mut others: Vec<PathBuf> = Vec::new();
    // The group itself, the parent groups the rendered inventory puts it under,
    // and the inventory names in it: each would set the same variable.
    let mut places: Vec<String> = vec![
        format!("group_vars/{group}"),
        "group_vars/peering_edges".into(),
        "group_vars/peering_cores".into(),
        "group_vars/peering_forwarders".into(),
    ];
    places.extend(hosts.iter().map(|h| format!("host_vars/{h}")));
    for place in places {
        let dir = repo.join("ops/ansible").join(&place);
        others.extend(
            std::fs::read_dir(&dir)
                .map(|it| it.flatten().map(|e| e.path()).collect::<Vec<_>>())
                .unwrap_or_default(),
        );
        for ext in ["yml", "yaml"] {
            others.push(repo.join(format!("ops/ansible/{place}.{ext}")));
        }
    }
    others.sort();
    let own = repo.join(&r.path);
    for f in others {
        let yaml = matches!(f.extension().and_then(|e| e.to_str()), Some("yml" | "yaml"));
        if f == own || !yaml {
            continue;
        }
        let Ok(text) = std::fs::read_to_string(&f) else {
            continue;
        };
        if text.starts_with(MARKER) {
            continue;
        }
        let theirs = yaml_keys(&text);
        let both: Vec<String> = mine
            .iter()
            .filter(|k| theirs.contains(k))
            .cloned()
            .collect();
        if !both.is_empty() {
            return Some((f, both));
        }
    }
    None
}

/// Hand-written (not generated) YAML files of one group_vars group.
fn hand_group_files(repo: &Path, group: &str) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = std::fs::read_dir(repo.join("ops/ansible/group_vars").join(group))
        .map(|it| it.flatten().map(|e| e.path()).collect())
        .unwrap_or_default();
    for ext in ["yml", "yaml"] {
        out.push(repo.join(format!("ops/ansible/group_vars/{group}.{ext}")));
    }
    out.retain(|f| {
        matches!(f.extension().and_then(|e| e.to_str()), Some("yml" | "yaml"))
            && std::fs::read_to_string(f)
                .map(|t| !t.starts_with(MARKER))
                .unwrap_or(false)
    });
    out.sort();
    out
}

/// Whether hand-written group_vars turn on `goat_zenoh_edge_install_certs` for
/// an edge group: the group's own files, else its parent `peering_edges`, else
/// `all`, the way Ansible's group precedence reads them.
fn installs_certs(repo: &Path, edge_group: &str) -> bool {
    let read = |f: &Path| -> Option<bool> {
        let text = std::fs::read_to_string(f).ok()?;
        let v: serde_yaml::Value = serde_yaml::from_str(&text).ok()?;
        match v.get("goat_zenoh_edge_install_certs")? {
            serde_yaml::Value::Bool(b) => Some(*b),
            serde_yaml::Value::String(s) => Some(matches!(
                s.to_ascii_lowercase().as_str(),
                "true" | "yes" | "on" | "1"
            )),
            _ => None,
        }
    };
    for group in [edge_group, "peering_edges", "all"] {
        if let Some(b) = hand_group_files(repo, group)
            .iter()
            .rev()
            .find_map(|f| read(f))
        {
            return b;
        }
    }
    false
}

/// One variable's value as the hand files of `group` set it, else as the role
/// default in this repository sets it.
fn live_value(repo: &Path, group: &str, var: &str, role: &str) -> Option<String> {
    let read = |f: &Path| -> Option<String> {
        let text = std::fs::read_to_string(f).ok()?;
        let v: serde_yaml::Value = serde_yaml::from_str(&text).ok()?;
        match v.get(var)? {
            serde_yaml::Value::String(s) => Some(s.clone()),
            serde_yaml::Value::Number(n) => Some(n.to_string()),
            _ => None,
        }
    };
    hand_group_files(repo, group)
        .iter()
        .rev()
        .find_map(|f| read(f))
        .or_else(|| read(&repo.join(format!("ops/ansible/roles/{role}/defaults/main.yml"))))
}

/// Whether a peering already runs from hand-written configuration: its edge
/// group has hand group_vars, or the hand-written inventory names its group.
fn runs_by_hand(repo: &Path, edge_group: &str) -> bool {
    // A file that only turns on goat-zenoh-edge's certificate install is a
    // setting for the peering to come, not evidence that it runs.
    let evidence = hand_group_files(repo, edge_group).iter().any(|f| {
        let keys = std::fs::read_to_string(f)
            .map(|t| yaml_keys(&t))
            .unwrap_or_default();
        keys.is_empty() || keys.iter().any(|k| k != "goat_zenoh_edge_install_certs")
    });
    if evidence {
        return true;
    }
    hand_inventory(repo)
        .map(|groups| groups.contains_key(edge_group))
        .unwrap_or(false)
}

/// The groups of the hand-written peering inventory and their host names.
/// `None`: there is none, or goatbuilder generated it.
fn hand_inventory(repo: &Path) -> Option<std::collections::BTreeMap<String, Vec<String>>> {
    let text =
        std::fs::read_to_string(repo.join("ops/ansible/inventory/peering-edges.ini")).ok()?;
    if text.starts_with(MARKER) {
        return None;
    }
    let mut groups: std::collections::BTreeMap<String, Vec<String>> = Default::default();
    let mut current: Option<String> = None;
    for line in text.lines() {
        let l = line.trim();
        if l.is_empty() || l.starts_with('#') || l.starts_with(';') {
            continue;
        }
        if let Some(name) = l.strip_prefix('[').and_then(|r| r.strip_suffix(']')) {
            // `:children` and `:vars` sections list groups and variables, not hosts.
            current = (!name.contains(':')).then(|| name.to_string());
            if let Some(g) = &current {
                groups.entry(g.clone()).or_default();
            }
            continue;
        }
        if let (Some(g), Some(host)) = (&current, l.split_whitespace().next()) {
            groups.entry(g.clone()).or_default().push(host.to_string());
        }
    }
    Some(groups)
}

/// Before anything is written: a peering the record does not hold, which
/// already runs from hand-written configuration, must not be given values
/// other than the ones it runs on without that being said. Refuses (GB-230)
/// naming each value that would move, unless `moves` names the peering.
pub fn adoption_check(
    repo: &Path,
    cfg: &Config,
    values: &[PeeringValues],
    ctx: &AllocContext,
    moves: &[String],
) -> Result<()> {
    let mut lines = Vec::new();
    for (p, v) in cfg.peerings.iter().zip(values.iter()) {
        let key = format!("{}/{}", v.environment, v.peering);
        if ctx.record.peerings.contains_key(&key)
            || moves.iter().any(|m| m == &v.peering || m == &key)
            || !runs_by_hand(repo, &v.edge_group)
        {
            continue;
        }
        let wg = p.tunnel.as_deref() != Some("ipsec");
        let mut checks: Vec<(&str, String, &str, String, &str)> = vec![
            (
                "spire_outbound_port",
                v.spire_outbound_port.to_string(),
                "peering_spire_outbound_port",
                v.edge_group.clone(),
                "goat-peering-spire",
            ),
            (
                "republisher_metrics_port",
                v.republisher_metrics_port.to_string(),
                "goat_fed_republisher_metrics_port",
                v.core_group.clone(),
                "goat-fed-republisher",
            ),
        ];
        if wg {
            checks.push((
                "wg_interface",
                v.wg_interface.clone(),
                "peering_wg_interface",
                v.edge_group.clone(),
                "goat-peering-wg",
            ));
            checks.push((
                "wg_listen_port",
                v.wg_listen_port.to_string(),
                "peering_wg_listen_port",
                v.edge_group.clone(),
                "goat-peering-wg",
            ));
        }
        let mut moved = Vec::new();
        for (field, allocated, var, group, role) in checks {
            if let Some(live) = live_value(repo, &group, var, role) {
                if live != allocated {
                    moved.push(format!("{field} {live} -> {allocated}"));
                }
            }
        }
        if !moved.is_empty() {
            lines.push(format!(
                "{key} runs from hand-written files and would move: {}",
                moved.join(", ")
            ));
        }
    }
    if lines.is_empty() {
        return Ok(());
    }
    Err(goat_errors::coded(
        "GB-230",
        format!(
            "goatbuilder federate allocate would change the values of a peering that already runs (GB-230): {}. To adopt it as it runs, pin those values under the peering's values: in goatbuilder.yaml (a pin on 51820 needs the environment's peering_edge_reserved_udp to allow it). To move it on purpose, run again with FED_ALLOCATE_MOVE=<with>[,<with>...]; its next phase 2 then moves the tunnel. Nothing was written",
            lines.join("; ")
        ),
    )
    .into())
}

/// Without `hosts:`, the hand-written inventory must give each peering its own
/// inventory name for each machine: a name in two peering groups merges both
/// peerings' rendered values (GB-231).
fn hand_inventory_names_apart(repo: &Path, values: &[PeeringValues]) -> Result<()> {
    let Some(groups) = hand_inventory(repo) else {
        return Ok(());
    };
    let mut seen: std::collections::BTreeMap<String, String> = Default::default();
    for v in values {
        for g in [&v.edge_group, &v.core_group] {
            for h in groups.get(g.as_str()).into_iter().flatten() {
                if let Some(other) = seen.insert(h.clone(), g.clone()) {
                    if &other != g {
                        return Err(goat_errors::coded(
                            "GB-231",
                            format!(
                                "ops/ansible/inventory/peering-edges.ini puts the inventory name {h} in both {other} and {g} (GB-231): Ansible merges the group_vars of every group a name is in, so each peering would read the other's values. Give each peering its own name for the machine (for example {}-{h} with the same ansible_host), or declare hosts: on every peering and let goatbuilder federate allocate render the inventory",
                                v.peering
                            ),
                        )
                        .into());
                    }
                }
            }
        }
    }
    Ok(())
}

/// The site values a rendered deployment half copies, from the environment's
/// own groups' hand-written group_vars (each of `environments[].groups`, then
/// `all`, the first that sets it): (variable, required).
const EDGE_SITE: &[(&str, bool)] = &[
    ("goat_zenoh_edge_image", true),
    ("goat_zenoh_edge_core_cn", true),
    ("peering_spire_server_addr", true),
    ("goat_zenoh_edge_trust_mode", false),
    ("goat_zenoh_edge_acl_trace", false),
    ("peering_wg_fips_waived_reason", false),
    ("peering_wg_extra_ports", false),
    ("peering_spire_outbound_listen", false),
];
const CORE_SITE: &[(&str, bool)] = &[
    ("goat_fed_republisher_image", true),
    ("goat_fed_republisher_core_endpoint", true),
];

/// A YAML value as one line of a group_vars file (a list as indented items).
fn yaml_line(var: &str, v: &serde_yaml::Value) -> String {
    match v {
        serde_yaml::Value::String(s) => format!("{var}: {}\n", q(s)),
        serde_yaml::Value::Sequence(items) => {
            let mut out = format!("{var}:\n");
            for i in items {
                let one = match i {
                    serde_yaml::Value::String(s) => q(s),
                    other => serde_yaml::to_string(other)
                        .unwrap_or_default()
                        .trim()
                        .to_string(),
                };
                out.push_str(&format!("  - {one}\n"));
            }
            out
        }
        other => format!(
            "{var}: {}\n",
            serde_yaml::to_string(other).unwrap_or_default().trim()
        ),
    }
}

/// One variable from the environment's groups' hand-written group_vars.
fn site_value(repo: &Path, groups: &[String], var: &str) -> Option<serde_yaml::Value> {
    let read = |f: &Path| -> Option<serde_yaml::Value> {
        let text = std::fs::read_to_string(f).ok()?;
        let v: serde_yaml::Value = serde_yaml::from_str(&text).ok()?;
        v.get(var).cloned()
    };
    groups
        .iter()
        .map(String::as_str)
        .chain(["all"])
        .find_map(|g| hand_group_files(repo, g).iter().rev().find_map(|f| read(f)))
}

/// The deployment halves of every peering declared `deployment: rendered`:
/// `group_vars/<edge_group>/peering-deployment.yml` and the core's, from the
/// declaration, the allocated values and the environment's site values.
/// Refuses (GB-232) a required site value no group_vars sets; nothing is
/// invented.
pub fn deployment_halves(
    repo: &Path,
    cfg: &Config,
    values: &[PeeringValues],
) -> Result<Vec<Rendered>> {
    let mut out = Vec::new();
    for (p, v) in cfg.peerings.iter().zip(values.iter()) {
        if p.deployment.as_deref() != Some("rendered") {
            continue;
        }
        let groups: Vec<String> = cfg
            .environments
            .iter()
            .find(|e| e.name == p.environment)
            .map(|e| e.groups.clone())
            .unwrap_or_default();
        let mut missing: Vec<&'static str> = Vec::new();
        let mut take = |list: &[(&'static str, bool)], body: &mut String| {
            for (var, required) in list {
                match site_value(repo, &groups, var) {
                    Some(val) => body.push_str(&yaml_line(var, &val)),
                    None if *required => missing.push(*var),
                    None => {}
                }
            }
        };
        let our_ca = format!("{}/our-ca.pem", v.cert_dir);
        let mut edge = header(&format!(
            "the edge's deployment half of peering {} on environment {}.",
            v.peering, v.environment
        ));
        edge.push_str(&format!(
            "# From the declaration (deployment: rendered), the allocated values, and the site values\n\
             # set in the group_vars of environment {}'s groups ({}) or all.\n\n",
            v.environment,
            if groups.is_empty() { "none declared".to_string() } else { groups.join(", ") }
        ));
        edge.push_str("goat_zenoh_edge_enabled: true\n");
        edge.push_str(&format!("goat_zenoh_edge_partner_id: {}\n", q(&v.peering)));
        edge.push_str("peering_spire_enabled: true\n");
        take(EDGE_SITE, &mut edge);
        let core_endpoint = site_value(repo, &groups, "goat_fed_republisher_core_endpoint");
        if let Some(serde_yaml::Value::String(ep)) = &core_endpoint {
            edge.push_str(&format!(
                "goat_zenoh_edge_core_endpoints:\n  - {}\n",
                q(&format!("{ep}#root_ca_certificate_file={our_ca}"))
            ));
        }
        let mut core = header(&format!(
            "the core's deployment half (the republisher) of peering {} on environment {}.",
            v.peering, v.environment
        ));
        core.push('\n');
        take(CORE_SITE, &mut core);
        core.push_str(&format!(
            "goat_fed_republisher_core_ca_src: {}\n",
            q(&our_ca)
        ));
        if !missing.is_empty() {
            missing.sort();
            missing.dedup();
            return Err(goat_errors::coded(
                "GB-232",
                format!(
                    "peering '{}' declares deployment: rendered, and no group_vars of environment '{}''s groups ({}) or all sets {} (GB-232). Set each once in one of those groups' group_vars, or declare deployment: hand and write the halves by hand",
                    v.peering,
                    v.environment,
                    if groups.is_empty() { "none declared: add environments[].groups".to_string() } else { groups.join(", ") },
                    missing.join(", ")
                ),
            )
            .into());
        }
        out.push(Rendered {
            path: format!(
                "ops/ansible/group_vars/{}/peering-deployment.yml",
                v.edge_group
            ),
            body: edge,
        });
        out.push(Rendered {
            path: format!(
                "ops/ansible/group_vars/{}/peering-deployment.yml",
                v.core_group
            ),
            body: core,
        });
    }
    Ok(out)
}

fn row(name: &str, ok: bool, detail: String, fix: Option<String>) -> Check {
    Check {
        name: name.into(),
        ok,
        detail,
        fix,
    }
}

/// Before a run of `goatbuilder federate <with>`: when the allocation record
/// holds this peering, the driver's working directory, edge group and core group
/// must be the allocated ones, or phase 8 mints certificates where the edge does
/// not read them and the plays run on another peering's hosts. A peering the
/// record does not hold is not checked (the driver as before).
pub fn driver_agrees(
    cfg: &Config,
    cfg_dir: &Path,
    o: &Options,
    work: &str,
    edge_group: &str,
) -> Result<()> {
    let ctx = AllocContext::load(cfg_dir)?;
    // Only a recorded entry is checked; ambiguity matters only then.
    let recorded = cfg.peerings.iter().any(|p| {
        p.with == o.with
            && o.env.map(|e| p.environment == e).unwrap_or(true)
            && ctx
                .record
                .peerings
                .contains_key(&format!("{}/{}", p.environment, p.with))
    });
    if !recorded {
        return Ok(());
    }
    let Some(p) = super::declaration::peering(cfg, o.with, o.env)? else {
        return Ok(());
    };
    if !ctx
        .record
        .peerings
        .contains_key(&format!("{}/{}", p.environment, p.with))
    {
        return Ok(());
    }
    let v = alloc::allocate_in(cfg, Some(&p.environment), &p.with, &ctx)?;
    let mut off = Vec::new();
    let pki = format!("{}/pki", work.trim_end_matches('/'));
    if pki != v.cert_dir {
        off.push(format!("the working directory's pki is {pki} but the allocated cert_dir is {} (pass --work {}, or pin cert_dir to {pki})", v.cert_dir, v.cert_dir.trim_end_matches("/pki")));
    }
    if edge_group != v.edge_group {
        off.push(format!("the edge group is {edge_group} but the allocated edge_group is {} (pass --edge-group {})", v.edge_group, v.edge_group));
    }
    let core = format!("{}_core", o.with);
    if core != v.core_group {
        off.push(format!("the driver runs the republisher on {core} only, and the allocated core_group is {}: the driver does not read the allocated core group yet, so a partner declared on a second environment, or a core_group pin, cannot run through it", v.core_group));
    }
    if off.is_empty() {
        return Ok(());
    }
    Err(goat_errors::coded(
        "GB-128",
        format!(
            "peering '{}' on '{}' disagrees with its allocated values (GB-128): {}",
            p.with,
            p.environment,
            off.join("; ")
        ),
    )
    .into())
}

/// The verb. Allocates every declared peering, then writes (or with
/// `--dry-run`/`--mock` shows) the record and the files.
pub fn run(repo: &Path, o: &Options) -> Result<Report> {
    let cfg_path = match o.mock {
        Some(m) => m.join("goatbuilder.yaml"),
        None => repo.join("ops/goatbuilder/goatbuilder.yaml"),
    };
    let cfg = config::load(&cfg_path)?;
    let cfg_dir = cfg_path
        .parent()
        .map(Path::to_path_buf)
        .unwrap_or_else(|| repo.to_path_buf());
    let ctx = AllocContext::load(&cfg_dir)?;
    let values = alloc::allocate_all(&cfg, &ctx)?;
    let moves: Vec<String> = std::env::var("FED_ALLOCATE_MOVE")
        .unwrap_or_default()
        .split(',')
        .map(|m| m.trim().to_string())
        .filter(|m| !m.is_empty())
        .collect();
    adoption_check(repo, &cfg, &values, &ctx, &moves)?;
    if cfg.peerings.iter().all(|p| p.hosts.is_none()) {
        hand_inventory_names_apart(repo, &values)?;
    }
    let prev_inventory =
        std::fs::read_to_string(repo.join("ops/ansible/inventory/peering-edges.ini"))
            .ok()
            .filter(|t| t.starts_with(MARKER));
    // Edge groups whose hand-written group_vars turn on goat-zenoh-edge's own
    // certificate install.
    let installs: std::collections::BTreeSet<String> = values
        .iter()
        .filter(|v| installs_certs(repo, &v.edge_group))
        .map(|v| v.edge_group.clone())
        .collect();
    let mut rendered = render_full(
        &cfg,
        &values,
        &ctx.record,
        prev_inventory.as_deref(),
        &installs,
    )?;
    rendered.extend(deployment_halves(repo, &cfg, &values)?);
    let writes = !o.dry_run && o.mock.is_none();
    let mode = if o.dry_run {
        " (DRY RUN: nothing is written)"
    } else if o.mock.is_some() {
        " (MOCK: nothing is written)"
    } else {
        ""
    };
    let mut checks = vec![row(
        "allocate",
        true,
        format!(
            "{} peering(s) declared in {}{mode}",
            values.len(),
            cfg_path.display()
        ),
        None,
    )];
    for v in &values {
        checks.push(row("values", true, alloc::summary(v), None));
    }
    // Refuse before writing anything: one foreign file stops the whole run.
    for r in &rendered {
        let t = target(repo, &cfg_dir, &r.path);
        if let Ok(existing) = std::fs::read_to_string(&t) {
            if !existing.starts_with(MARKER) {
                return Err(goat_errors::coded(
                    "GB-125",
                    format!(
                        "{} exists and was not generated by `goatbuilder federate allocate` (GB-125); it is never overwritten. Move its values into goatbuilder.yaml (pins under the peering's values:, addresses under hosts:), remove the file, and run `goatbuilder federate allocate` again",
                        t.display()
                    ),
                )
                .into());
            }
        }
    }
    let host_names: Vec<String> = values
        .iter()
        .flat_map(|v| [v.edge_host_name.clone(), v.core_host_name.clone()])
        .collect();
    // One owner per variable: a key this run renders into a group's directory
    // that another file of that group already sets would be decided by Ansible's
    // file order, silently.
    for r in &rendered {
        if let Some((other, keys)) = shadowed(repo, r, &host_names) {
            return Err(goat_errors::coded(
                "GB-125",
                format!(
                    "{} already sets {} that `goatbuilder federate allocate` would render into {} (GB-125); one variable has one owner, and Ansible's file order would pick between them. Pin the value under the peering's values: in goatbuilder.yaml and remove it from {}, then run `goatbuilder federate allocate` again",
                    other.display(),
                    keys.join(", "),
                    r.path,
                    other.display()
                ),
            )
            .into());
        }
    }
    for r in &rendered {
        let t = target(repo, &cfg_dir, &r.path);
        let same = std::fs::read_to_string(&t)
            .map(|e| e == r.body)
            .unwrap_or(false);
        let state = if same {
            "unchanged"
        } else if !writes {
            "would write"
        } else {
            if let Some(parent) = t.parent() {
                std::fs::create_dir_all(parent)?;
            }
            // Whole or not at all: a reader never sees half a record.
            let tmp = t.with_extension("goatbuilder-tmp");
            std::fs::write(&tmp, &r.body)?;
            std::fs::rename(&tmp, &t)?;
            "written"
        };
        let detail = if writes || same {
            format!("{state}: {}", r.path)
        } else {
            format!("{state}: {}\n{}", r.path, r.body)
        };
        checks.push(row("file", true, detail, None));
    }
    for (k, _) in alloc::retired_entries(&cfg, &ctx) {
        checks.push(row("retired", true, format!("kept: {k} is in {} but no longer declared; its values stay reserved until you remove its entry, once that peering is cut", alloc::RECORD_FILE), None));
    }
    for s in stale(repo, &rendered) {
        checks.push(row("stale", true, format!("left in place: {s} was generated for a peering no longer declared; delete it once that peering is cut"), None));
    }
    if !values.is_empty() && cfg.peerings.iter().all(|p| p.hosts.is_none()) {
        checks.push(row("inventory", true, "not rendered: no peering declares hosts:, so ops/ansible/inventory/peering-edges.ini stays hand-written. Give each peering its own inventory name for each machine (the edge_host_name and core_host_name above): a name in two peering groups reads both peerings' peering-values.yml".into(), None));
    }
    if writes {
        checks.push(row("next", true, "review and commit the changed files (git diff ops/goatbuilder ops/ansible): they are the proposed change to this deployment's configuration".into(), None));
    }
    Ok(Report::new("federate", checks, EXIT_REFUSED))
}

